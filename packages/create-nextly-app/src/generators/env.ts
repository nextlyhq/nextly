import crypto from "crypto";
import path from "path";

import { execa } from "execa";
import fs from "fs-extra";

import type { DatabaseConfig, EnvGenerationResult } from "../types";
import { readEnvKeys, type EnvKeys } from "../utils/env-file";

import type { GeneratedFiles } from "./generated-files";

/**
 * Generate a cryptographically secure NEXTLY_SECRET.
 */
function generateNextlySecret(): string {
  return crypto.randomBytes(32).toString("base64");
}

/**
 * The diagnostics note, written to a new file and appended to one that does
 * not mention the setting yet.
 *
 * One definition because the two paths write it in different situations and a
 * second copy would let them describe the same setting differently.
 */
const DIAGNOSTICS_BLOCK = `# Development diagnostics (opt-in)
# Uncomment to add a _devDiagnostics field to error responses, carrying the
# log context of an error and the underlying cause, so a failure names itself
# while you build instead of only in the server log.
#
# Left commented on purpose. It is the SECOND of two independent signals — the
# first is NODE_ENV — and the second exists precisely because NODE_ENV is a
# runtime value a deployment can carry by mistake. A default that ships in this
# file would be true in exactly that case, which is the one it guards against.
# NEXTLY_DEV_DIAGNOSTICS=1
`;

/** The values Nextly reads at start-up, which every env file must define. */
const REQUIRED_KEYS = [
  "DB_DIALECT",
  "DATABASE_URL",
  "NEXTLY_SECRET",
  "NEXT_PUBLIC_APP_URL",
] as const;

type RequiredKey = (typeof REQUIRED_KEYS)[number];
type Values = Record<RequiredKey, string>;

/**
 * Which file a set of values is for. `.env` holds the real ones and is never
 * committed; `.env.example` is the file a project commits to say what it
 * needs, so it holds only placeholders and generic examples: the secret is
 * left empty, and the database URL is the generic one rather than a URL the
 * person typed with its password. An empty secret is also refused in
 * production, as a missing one is, so a copied example cannot run a deployment.
 */
type Kind = "real" | "example";

const SECRET_COMMENT: Record<Kind, string> = {
  real: "# Authentication (auto-generated, change if needed)",
  example:
    "# Authentication: a random secret of at least 32 characters, for example\n" +
    "# from `openssl rand -base64 32`. The real one goes in .env, never here.",
};

function valuesFor(
  kind: Kind,
  database: DatabaseConfig,
  secret: string
): Values {
  return {
    DB_DIALECT: database.type,
    DATABASE_URL:
      kind === "real" ? database.connectionUrl : database.envExample,
    NEXTLY_SECRET: kind === "real" ? secret : "",
    NEXT_PUBLIC_APP_URL: "http://localhost:3000",
  };
}

/** A whole env file, for a project that has none. */
function fullFile(values: Values, kind: Kind): string {
  return `# Nextly Configuration
# Generated by create-nextly-app

# Database Configuration
DB_DIALECT=${values.DB_DIALECT}
DATABASE_URL=${values.DATABASE_URL}

${SECRET_COMMENT[kind]}
NEXTLY_SECRET=${values.NEXTLY_SECRET}

# Where the Nextly app itself lives: the admin, the API, and the origin its
# emails and preview links point at.
NEXT_PUBLIC_APP_URL=${values.NEXT_PUBLIC_APP_URL}

# Where READERS find the public site. Used for canonical links, Open Graph
# tags, the sitemap and RSS. Set it when the public site is served from a
# different origin than the app above; otherwise the app's origin is used.
# NEXT_PUBLIC_SITE_URL=https://example.com

${DIAGNOSTICS_BLOCK}`;
}

/** The lines appended to an existing file for the keys it lacks. */
function blockFor(
  values: Values,
  missing: readonly RequiredKey[],
  kind: Kind
): string {
  const lines = missing.map(key =>
    key === "NEXTLY_SECRET"
      ? `${SECRET_COMMENT[kind]}\nNEXTLY_SECRET=${values.NEXTLY_SECRET}`
      : `${key}=${values[key]}`
  );
  return `\n# Nextly (added by create-nextly-app)\n${lines.join("\n")}\n`;
}

/**
 * Write `.env` and `.env.example`, and keep `.env` out of git.
 *
 * A file the project already has is never replaced: every line stays, and only
 * what Nextly needs and the file lacks is appended. Which keys a file has is
 * read with one line-based reader, so `export KEY=`, quoted values, a key named
 * only in a comment and a similarly named variable are all told apart. A value
 * already there is the project's, even when Nextly cannot use it; that is said,
 * naming the key and never printing the value.
 *
 * @param cwd - Working directory
 * @param database - Database configuration
 */
export async function generateEnv(
  cwd: string,
  database: DatabaseConfig
): Promise<EnvGenerationResult> {
  const files: GeneratedFiles = { written: [], changed: [], skipped: [] };
  const warnings: string[] = [];
  const secret = generateNextlySecret();
  const real = valuesFor("real", database, secret);
  // Secrets go into .env only once it is known to stay out of git: ignored by
  // a project rule, and not tracked, which no rule undoes. Anything else,
  // an unknown answer included, withholds them; development runs without
  // NEXTLY_SECRET. Settled before .env is written, so no later failure can
  // leave a secret stageable.
  const exposure = await envExposure(cwd, files);
  const withheld = exposure ? secretKeys(real) : [];

  warnings.push(
    ...(await writeOrMerge(cwd, ".env", real, "real", files, withheld)),
    ...(await writeOrMerge(
      cwd,
      ".env.example",
      valuesFor("example", database, secret),
      "example",
      files,
      []
    ))
  );
  if (exposure) warnings.push(await withheldWarning(cwd, exposure, withheld));
  return { files, warnings };
}

/**
 * The values that are secrets: the generated one, and the typed database URL
 * for any database but SQLite. A driver can read credentials from more places
 * than the URL's password (pg takes `?password=`), so no URL is judged
 * safe by looking at it; SQLite's is a file path, with no credential in it.
 */
function secretKeys(values: Values): RequiredKey[] {
  return values.DB_DIALECT === "sqlite"
    ? ["NEXTLY_SECRET"]
    : ["NEXTLY_SECRET", "DATABASE_URL"];
}

/** Why `.env` could reach git, when it could. */
type Exposure = "tracked" | "unknown" | "unignored";

async function envExposure(
  cwd: string,
  files: GeneratedFiles
): Promise<Exposure | undefined> {
  if (!(await keepEnvOutOfGit(cwd, files))) return "unignored";
  const tracking = await envTracking(cwd);
  return tracking === "untracked" ? undefined : tracking;
}

async function envTracking(
  cwd: string
): Promise<"tracked" | "untracked" | "unknown"> {
  try {
    await execa("git", ["ls-files", "--error-unmatch", "--", ".env"], {
      cwd,
      env: GIT_ENV,
    });
    return "tracked";
  } catch (error) {
    // 1 is "not in the index". Outside any repository nothing is committed
    // from here. Anything else (a corrupt index, a repository git refuses to
    // read) leaves the answer unknown.
    if ((error as { exitCode?: number }).exitCode === 1) return "untracked";
    return (await outsideRepository(cwd, error)) ? "untracked" : "unknown";
  }
}

/** Git's messages in English, so its "not a git repository" can be recognised. */
const GIT_ENV = { LC_ALL: "C" };

/**
 * Whether a git command failed because the folder is in no repository. Git
 * itself is asked, since it finds a repository through a symbolic link that a
 * walk up the folder's own path would miss. Without git, a `.git` above the
 * folder's real path still means one.
 */
async function outsideRepository(
  cwd: string,
  error: unknown
): Promise<boolean> {
  const { stderr, code } = error as { stderr?: string; code?: string };
  if (/not a git repository/i.test(stderr ?? "")) return true;
  if (code !== "ENOENT") return false;
  let dir = await fs.realpath(cwd);
  for (;;) {
    if (await fs.pathExists(path.join(dir, ".git"))) return false;
    const parent = path.dirname(dir);
    if (parent === dir) return true;
    dir = parent;
  }
}

const EXPOSURE: Record<Exposure, string> = {
  tracked:
    ".env is tracked by git, so what it holds is committed whatever .gitignore says. " +
    "Stop tracking it with `git rm --cached .env` and commit that.",
  unknown:
    "Git could not say whether it tracks .env, so it was treated as tracked. " +
    "Check with `git ls-files .env`; if that lists it, stop tracking it with " +
    "`git rm --cached .env` and commit that.",
  unignored:
    ".env is not ignored: .gitignore could not be changed (see above). " +
    "Add `.env` to it first.",
};

/**
 * Says why the secrets were withheld from `.env` and what to do, naming the
 * withheld keys the file still lacks: a key the app already set there was not
 * withheld from it.
 */
async function withheldWarning(
  cwd: string,
  exposure: Exposure,
  withheld: readonly RequiredKey[]
): Promise<string> {
  const text = await fs
    .readFile(path.join(cwd, ".env"), "utf-8")
    .catch(() => "");
  const { defined } = readEnvKeys(text);
  const lacking = withheld.filter(key => !defined.has(key));
  const add = lacking.map(key =>
    key === "NEXTLY_SECRET"
      ? "NEXTLY_SECRET, a random value of at least 32 characters (for example from `openssl rand -base64 32`)"
      : "DATABASE_URL, the URL you entered"
  );
  const then =
    lacking.length > 0
      ? ` ${lacking.join(" and ")} ${lacking.length > 1 ? "were" : "was"} not added to it, so they stay out of git; add ${add.join(", and ")} once that is done. Development runs without NEXTLY_SECRET, and production refuses to start without it.`
      : "";
  return EXPOSURE[exposure] + then;
}

async function writeOrMerge(
  cwd: string,
  name: string,
  values: Values,
  kind: Kind,
  files: GeneratedFiles,
  withheld: readonly RequiredKey[]
): Promise<string[]> {
  const file = path.join(cwd, name);
  // A linked env file is shared with whatever else links to it: appending
  // would put Nextly's keys, the secret among them, in that file too.
  const stat = await fs.lstat(file).catch(absentAsNull);
  if (stat && (stat.isSymbolicLink() || stat.nlink > 1)) {
    return skipLinked(file, name, kind, files);
  }
  // Created exclusively, so a file that appeared since the check is merged
  // into, never truncated.
  if (!stat && withheld.length === 0) {
    if (await createNew(file, fullFile(values, kind))) {
      files.written.push(name);
      return [];
    }
    return mergeInto(file, name, true, values, kind, files, withheld);
  }

  // A file with keys withheld is built the way an existing one is merged, so
  // the withheld keys are left out of a new file as well.
  return mergeInto(file, name, stat !== null, values, kind, files, withheld);
}

/** Only an absent file is null; any other failure to look is not hidden. */
function absentAsNull(error: unknown): null {
  if ((error as { code?: string }).code === "ENOENT") return null;
  throw error;
}

async function createNew(file: string, content: string): Promise<boolean> {
  try {
    await fs.writeFile(file, content, { encoding: "utf-8", flag: "wx" });
    return true;
  } catch (error) {
    if ((error as { code?: string }).code === "EEXIST") return false;
    throw error;
  }
}

/** Appends what the file lacks to it, and says what it holds that Nextly cannot use. */
async function mergeInto(
  file: string,
  name: string,
  exists: boolean,
  values: Values,
  kind: Kind,
  files: GeneratedFiles,
  withheld: readonly RequiredKey[]
): Promise<string[]> {
  const text = exists ? await fs.readFile(file, "utf-8") : "";
  const keys = readEnvKeys(text);
  // Only values this file settles are judged.
  const known = knownValues(keys);
  const pair = databasePair(name, keys, values.DB_DIALECT, kind);
  const added = await appendMissing(file, text, keys, values, kind, [
    ...withheld,
    ...pair.skip,
  ]);
  if (!exists) files.written.push(name);
  else if (added.length > 0) files.changed.push({ path: name, added });
  // A copied example file has to work as a .env, so its database half is
  // judged the same way.
  return [
    ...pair.warnings,
    ...(kind === "real"
      ? checkRealValues(name, known)
      : checkExampleValues(name, known)),
  ];
}

/** Reports a linked env file as skipped, with the lines to add and no values. */
async function skipLinked(
  file: string,
  name: string,
  kind: Kind,
  files: GeneratedFiles
): Promise<string[]> {
  const keys = readEnvKeys(await fs.readFile(file, "utf-8").catch(() => ""));
  const missing = REQUIRED_KEYS.filter(key => !keys.defined.has(key));
  files.skipped.push({
    path: name,
    why: "it is a link to a file shared outside this project, so it was left as it is",
    toAdd:
      missing.length > 0 ? missing.map(key => `${key}=`).join("\n") : undefined,
  });
  // Left alone, but what it holds is still said: git commits a hard link's
  // contents, so a secret in a hard-linked example file goes out with it.
  const known = knownValues(keys);
  return kind === "real"
    ? checkRealValues(name, known)
    : checkExampleValues(name, known);
}

/** Values this file settles: one set from a variable it lacks is filled in where the app runs. */
function knownValues({ defined, unresolved }: EnvKeys): Map<string, string> {
  return new Map([...defined].filter(([key]) => !unresolved.has(key)));
}

const DIALECTS: readonly string[] = ["postgresql", "mysql", "sqlite"];

/**
 * Which half of the database setting to leave out, and what to say. The
 * dialect and the URL are one setting, and a file that has either half is the
 * app's: no dialect is read out of a URL here, so nothing can disagree with
 * how Nextly reads it.
 * - The URL only: Nextly reads the dialect from it, so none is added, which
 *   could contradict it.
 * - DB_DIALECT only: the URL is added when it names the chosen database;
 *   otherwise (another database, a spelling Nextly refuses, a value set
 *   elsewhere) the chosen database's URL would not match, so it is not.
 */
function databasePair(
  name: string,
  { defined, unresolved }: EnvKeys,
  chosen: string,
  kind: Kind
): { skip: RequiredKey[]; warnings: string[] } {
  const dialect = unresolved.has("DB_DIALECT")
    ? undefined
    : defined.get("DB_DIALECT");
  const warnings = dialectWarnings(name, dialect, chosen);
  if (defined.has("DATABASE_URL") && !defined.has("DB_DIALECT")) {
    // An example file's URL is a placeholder, so only .env is asked about.
    if (kind === "example") return { skip: ["DB_DIALECT"], warnings };
    warnings.push(
      `DATABASE_URL in ${name} was already set, so DB_DIALECT was not added: Nextly ` +
        `reads the database from that URL. Make sure it is a ${chosen} URL, the database chosen.`
    );
    return { skip: ["DB_DIALECT"], warnings };
  }
  if (defined.has("DB_DIALECT") && dialect !== chosen) {
    if (dialect === undefined) {
      warnings.push(
        `DB_DIALECT in ${name} is set from a variable this file does not define, so ` +
          "DATABASE_URL was not added beside it."
      );
    }
    return { skip: ["DATABASE_URL"], warnings };
  }
  return { skip: [], warnings };
}

function dialectWarnings(
  name: string,
  dialect: string | undefined,
  chosen: string
): string[] {
  if (!dialect || dialect === chosen) return [];
  if (!DIALECTS.includes(dialect)) {
    return [
      `DB_DIALECT in ${name} is not one Nextly accepts: it takes postgresql, mysql or ` +
        "sqlite. It was left as it is.",
    ];
  }
  return [
    `DB_DIALECT in ${name} is ${dialect}, but ${chosen} was chosen. It was left as it ` +
      `is: set DB_DIALECT and DATABASE_URL for ${chosen}, or run again choosing ${dialect}.`,
  ];
}

/**
 * Appends, after every line the file already has, the required keys it does
 * not define and the diagnostics note when it does not mention the setting.
 * Returns what was added, by name.
 */
async function appendMissing(
  file: string,
  text: string,
  { defined, mentioned }: ReturnType<typeof readEnvKeys>,
  values: Values,
  kind: Kind,
  withheld: readonly RequiredKey[]
): Promise<string[]> {
  const missing = REQUIRED_KEYS.filter(
    key => !defined.has(key) && !withheld.includes(key)
  );
  const addNote = !mentioned.has("NEXTLY_DEV_DIAGNOSTICS");
  if (missing.length === 0 && !addNote) return [];

  const separator = text === "" || text.endsWith("\n") ? "" : "\n";
  const block = missing.length > 0 ? blockFor(values, missing, kind) : "";
  const note = addNote ? `\n${DIAGNOSTICS_BLOCK}` : "";
  await fs.appendFile(file, separator + block + note, "utf-8");
  return [...missing, ...(addNote ? ["the NEXTLY_DEV_DIAGNOSTICS note"] : [])];
}

/**
 * A value already in `.env` that Nextly cannot start on. An empty one counts as
 * set, so nothing is appended after it (dotenv would take the later line, and
 * the file would then say two things); it is named instead.
 */
function checkRealValues(name: string, defined: Map<string, string>): string[] {
  const warnings = REQUIRED_KEYS.filter(
    key => key !== "NEXTLY_SECRET" && defined.get(key) === ""
  ).map(
    key =>
      `${key} in ${name} is empty. It was left as it is; give it a value, since Nextly reads it at start-up.`
  );
  warnings.push(...unreadableUrls(name, defined));
  const secret = defined.get("NEXTLY_SECRET");
  if (secret !== undefined && secret.length < 32) {
    warnings.push(
      `NEXTLY_SECRET in ${name} is shorter than the 32 characters production requires. ` +
        "It was left as it is; replace it, for example with `openssl rand -base64 32`."
    );
  }
  return warnings;
}

/** A real-looking secret already in a file a project commits. */
/**
 * The URLs a file holds that Nextly refuses at start-up: it reads
 * DATABASE_URL and NEXT_PUBLIC_APP_URL as URLs (`new URL` and zod's url(),
 * which agree). Empty values are judged elsewhere: an empty one is a
 * placeholder in an example file.
 */
function unreadableUrls(name: string, defined: Map<string, string>): string[] {
  return (["DATABASE_URL", "NEXT_PUBLIC_APP_URL"] as const)
    .filter(key => {
      const value = defined.get(key);
      return value !== undefined && value !== "" && !URL.canParse(value);
    })
    .map(
      key =>
        `${key} in ${name} is not a URL Nextly can read. It was left as it is; ` +
        "set it to a full URL, such as http://localhost:3000 for the app."
    );
}

function checkExampleValues(
  name: string,
  defined: Map<string, string>
): string[] {
  // A copied example file has to work as a .env.
  const warnings: string[] = unreadableUrls(name, defined);
  const secret = defined.get("NEXTLY_SECRET");
  if (secret !== undefined && !isPlaceholder(secret)) {
    warnings.push(
      `${name} holds a value for NEXTLY_SECRET. An example file should hold a placeholder: ` +
        "empty it, and if the file was ever committed, replace the secret itself."
    );
  }
  if (hasRealPassword(defined.get("DATABASE_URL"))) {
    warnings.push(
      `${name} holds a database password in DATABASE_URL. An example file should hold a ` +
        "placeholder: replace it, and if the file was ever committed, change the password."
    );
  }
  return warnings;
}

function isPlaceholder(value: string): boolean {
  return (
    value === "" ||
    /^<.*>$/.test(value) ||
    /change[-_ ]?me|your[-_ ]|replace|placeholder|example|^x+$/i.test(value)
  );
}

function hasRealPassword(url: string | undefined): boolean {
  if (!url) return false;
  // A URL new URL cannot parse can still show its password in plain sight.
  const raw = URL.canParse(url)
    ? new URL(url).password
    : (/^[a-z][a-z0-9+.-]*:\/\/[^:/@\s]*:([^@\s]*)@/i.exec(url)?.[1] ?? "");
  // new URL keeps a % that decodeURIComponent refuses, such as `pa%ss`; the
  // password is no less real for it, so it is judged as written.
  let password = raw;
  try {
    password = decodeURIComponent(raw);
  } catch {
    // Kept as written.
  }
  return (
    password !== "" &&
    !isPlaceholder(password) &&
    !["password", "pass"].includes(password.toLowerCase())
  );
}

/**
 * Makes sure git ignores `.env`, which holds the real secret: a project's own
 * `.gitignore` might not. Git answers when the project is a repository; a
 * directory that is not one yet is judged from its `.gitignore`. Says whether
 * `.env` is now ignored: a linked `.gitignore` is left alone, so it may not be.
 */
async function keepEnvOutOfGit(
  cwd: string,
  files: GeneratedFiles
): Promise<boolean> {
  if (await isEnvIgnored(cwd)) return true;

  const file = path.join(cwd, ".gitignore");
  // A linked .gitignore is shared with whatever else links to it, and
  // appending would edit theirs too. `lstat` sees a symbolic link, which
  // `pathExists` and `readFile` follow; a hard link is one inode under two
  // names, which only its link count shows.
  const stat = await fs.lstat(file).catch(() => null);
  if (stat && (stat.isSymbolicLink() || stat.nlink > 1)) {
    files.skipped.push({
      path: ".gitignore",
      why: "it is a link to a file shared outside this project, so it was left as it is",
      toAdd: ".env",
    });
    return false;
  }
  const entry =
    "# Local environment: it holds secrets, so it is never committed\n.env\n";
  if (stat) {
    const text = await fs.readFile(file, "utf-8");
    const separator = text === "" || text.endsWith("\n") ? "" : "\n";
    await fs.appendFile(file, `${separator}\n${entry}`, "utf-8");
    files.changed.push({ path: ".gitignore", added: [".env"] });
  } else {
    await fs.writeFile(file, entry, "utf-8");
    files.written.push(".gitignore");
  }
  return true;
}

async function isEnvIgnored(cwd: string): Promise<boolean> {
  try {
    // --no-index asks what the ignore rules say, whether or not the file is
    // tracked: without it a tracked .env is never reported as ignored, and a
    // second rule would be added beside the one already there. Tracking is
    // judged on its own, before anything is written.
    const { stdout } = await execa(
      "git",
      ["check-ignore", "-v", "--no-index", ".env"],
      { cwd, env: GIT_ENV }
    );
    return ignoredByProjectRule(stdout);
  } catch (error) {
    // 1: inside a repository, and not ignored. Any other failure inside one
    // leaves it uncertain, so not ignored. Outside a repository, the
    // project's .gitignore is read instead.
    if ((error as { exitCode?: number }).exitCode === 1) return false;
    if (!(await outsideRepository(cwd, error))) return false;
  }
  const file = path.join(cwd, ".gitignore");
  // Git does not read a .gitignore that is a symbolic link, so its target's
  // rules protect nothing once the folder becomes a repository.
  const stat = await fs.lstat(file).catch(() => null);
  if (!stat || stat.isSymbolicLink()) return false;
  return gitignoreIgnores(await fs.readFile(file, "utf-8"), ".env");
}

/**
 * Whether git's deciding rule for `.env` (`check-ignore -v`:
 * `<source>:<line>:<pattern><TAB><path>`) ignores it from a `.gitignore`.
 * Only a `.gitignore` travels with the project: `.git/info/exclude` and a
 * global excludes file belong to one machine, so on another the secret would
 * be stageable. With `-v`, git also reports a deciding `!` rule, which
 * re-includes the file.
 */
function ignoredByProjectRule(verbose: string): boolean {
  const match = /^(.*):\d+:(.*)\t/.exec(verbose);
  if (!match) return false;
  const [, source, pattern] = match;
  // A global excludes file may be named .gitignore too; git prints its path
  // absolute, and a project's relative.
  return (
    !path.isAbsolute(source) &&
    path.basename(source) === ".gitignore" &&
    !pattern.startsWith("!")
  );
}

/**
 * Whether a root `.gitignore` ignores a file at the project root, for the
 * patterns a root-level file can be matched by: the last matching line wins,
 * and `!` re-includes.
 */
function gitignoreIgnores(text: string, name: string): boolean {
  let ignored = false;
  for (const raw of text.split(/\r?\n/)) {
    // Git drops trailing spaces not escaped with `\`, and keeps leading ones:
    // ` .env` names a file called " .env".
    const line = raw.replace(/(?<!\\) +$/, "");
    if (line === "" || line.startsWith("#")) continue;
    const negated = line.startsWith("!");
    const pattern = line.replace(/^!/, "").replace(/^\//, "");
    // Only a plain name pattern (`*` and `?` at most) is evaluated here. A
    // re-include this reader cannot evaluate exactly might apply to .env, so
    // .env is then not certainly ignored, and the rule is added last, where
    // it decides. A positive pattern it cannot evaluate is simply not counted.
    if (/[/[\\]|\*\*/.test(pattern)) {
      if (negated) return false;
      continue;
    }
    const regex = new RegExp(
      "^" +
        pattern
          .replace(/[.+^${}()|[\]\\]/g, "\\$&")
          .replace(/\*/g, "[^/]*")
          .replace(/\?/g, "[^/]") +
        "$"
    );
    if (regex.test(name)) ignored = !negated;
  }
  return ignored;
}
