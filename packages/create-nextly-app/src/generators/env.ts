import crypto from "crypto";
import path from "path";

import { execa } from "execa";
import fs from "fs-extra";

import type { DatabaseConfig, EnvGenerationResult } from "../types";
import { readEnvKeys } from "../utils/env-file";

import type { GeneratedFiles } from "./generated-files";

/**
 * Generate a cryptographically secure NEXTLY_SECRET.
 */
function generateNextlySecret(): string {
  return crypto.randomBytes(32).toString("base64");
}

/**
 * The diagnostics note, written to a new file and appended to one that does
 * not mention the setting yet.
 *
 * One definition because the two paths write it in different situations and a
 * second copy would let them describe the same setting differently.
 */
const DIAGNOSTICS_BLOCK = `# Development diagnostics (opt-in)
# Uncomment to add a _devDiagnostics field to error responses, carrying the
# log context of an error and the underlying cause, so a failure names itself
# while you build instead of only in the server log.
#
# Left commented on purpose. It is the SECOND of two independent signals — the
# first is NODE_ENV — and the second exists precisely because NODE_ENV is a
# runtime value a deployment can carry by mistake. A default that ships in this
# file would be true in exactly that case, which is the one it guards against.
# NEXTLY_DEV_DIAGNOSTICS=1
`;

/** The values Nextly reads at start-up, which every env file must define. */
const REQUIRED_KEYS = [
  "DB_DIALECT",
  "DATABASE_URL",
  "NEXTLY_SECRET",
  "NEXT_PUBLIC_APP_URL",
] as const;

type RequiredKey = (typeof REQUIRED_KEYS)[number];
type Values = Record<RequiredKey, string>;

/**
 * Which file a set of values is for. `.env` holds the real ones and is never
 * committed; `.env.example` is the file a project commits to say what it
 * needs, so it holds only placeholders and generic examples: the secret is
 * left empty, and the database URL is the generic one rather than a URL the
 * person typed with its password. An empty secret is also refused in
 * production, as a missing one is, so a copied example cannot run a deployment.
 */
type Kind = "real" | "example";

const SECRET_COMMENT: Record<Kind, string> = {
  real: "# Authentication (auto-generated, change if needed)",
  example:
    "# Authentication: a random secret of at least 32 characters, for example\n" +
    "# from `openssl rand -base64 32`. The real one goes in .env, never here.",
};

function valuesFor(
  kind: Kind,
  database: DatabaseConfig,
  secret: string
): Values {
  return {
    DB_DIALECT: database.type,
    DATABASE_URL:
      kind === "real" ? database.connectionUrl : database.envExample,
    NEXTLY_SECRET: kind === "real" ? secret : "",
    NEXT_PUBLIC_APP_URL: "http://localhost:3000",
  };
}

/** A whole env file, for a project that has none. */
function fullFile(values: Values, kind: Kind): string {
  return `# Nextly Configuration
# Generated by create-nextly-app

# Database Configuration
DB_DIALECT=${values.DB_DIALECT}
DATABASE_URL=${values.DATABASE_URL}

${SECRET_COMMENT[kind]}
NEXTLY_SECRET=${values.NEXTLY_SECRET}

# Where the Nextly app itself lives: the admin, the API, and the origin its
# emails and preview links point at.
NEXT_PUBLIC_APP_URL=${values.NEXT_PUBLIC_APP_URL}

# Where READERS find the public site. Used for canonical links, Open Graph
# tags, the sitemap and RSS. Set it when the public site is served from a
# different origin than the app above; otherwise the app's origin is used.
# NEXT_PUBLIC_SITE_URL=https://example.com

${DIAGNOSTICS_BLOCK}`;
}

/** The lines appended to an existing file for the keys it lacks. */
function blockFor(
  values: Values,
  missing: readonly RequiredKey[],
  kind: Kind
): string {
  const lines = missing.map(key =>
    key === "NEXTLY_SECRET"
      ? `${SECRET_COMMENT[kind]}\nNEXTLY_SECRET=${values.NEXTLY_SECRET}`
      : `${key}=${values[key]}`
  );
  return `\n# Nextly (added by create-nextly-app)\n${lines.join("\n")}\n`;
}

/**
 * Write `.env` and `.env.example`, and keep `.env` out of git.
 *
 * A file the project already has is never replaced: every line stays, and only
 * what Nextly needs and the file lacks is appended. Which keys a file has is
 * read with one line-based reader, so `export KEY=`, quoted values, a key named
 * only in a comment and a similarly named variable are all told apart. A value
 * already there is the project's, even when Nextly cannot use it; that is said,
 * naming the key and never printing the value.
 *
 * @param cwd - Working directory
 * @param database - Database configuration
 */
export async function generateEnv(
  cwd: string,
  database: DatabaseConfig
): Promise<EnvGenerationResult> {
  const files: GeneratedFiles = { written: [], changed: [], skipped: [] };
  const warnings: string[] = [];
  const secret = generateNextlySecret();

  for (const [name, kind] of [
    [".env", "real"],
    [".env.example", "example"],
  ] as const) {
    const values = valuesFor(kind, database, secret);
    warnings.push(...(await writeOrMerge(cwd, name, values, kind, files)));
  }
  await keepEnvOutOfGit(cwd, files);
  return { files, warnings };
}

async function writeOrMerge(
  cwd: string,
  name: string,
  values: Values,
  kind: Kind,
  files: GeneratedFiles
): Promise<string[]> {
  const file = path.join(cwd, name);
  if (!(await fs.pathExists(file))) {
    await fs.writeFile(file, fullFile(values, kind), "utf-8");
    files.written.push(name);
    return [];
  }

  const text = await fs.readFile(file, "utf-8");
  const keys = readEnvKeys(text);
  const added = await appendMissing(file, text, keys, values, kind);
  if (added.length > 0) files.changed.push({ path: name, added });
  return kind === "real"
    ? checkRealValues(name, keys.defined)
    : checkExampleValues(name, keys.defined);
}

/**
 * Appends, after every line the file already has, the required keys it does
 * not define and the diagnostics note when it does not mention the setting.
 * Returns what was added, by name.
 */
async function appendMissing(
  file: string,
  text: string,
  { defined, mentioned }: ReturnType<typeof readEnvKeys>,
  values: Values,
  kind: Kind
): Promise<string[]> {
  const missing = REQUIRED_KEYS.filter(key => !defined.has(key));
  const addNote = !mentioned.has("NEXTLY_DEV_DIAGNOSTICS");
  if (missing.length === 0 && !addNote) return [];

  const separator = text === "" || text.endsWith("\n") ? "" : "\n";
  const block = missing.length > 0 ? blockFor(values, missing, kind) : "";
  const note = addNote ? `\n${DIAGNOSTICS_BLOCK}` : "";
  await fs.appendFile(file, separator + block + note, "utf-8");
  return [...missing, ...(addNote ? ["the NEXTLY_DEV_DIAGNOSTICS note"] : [])];
}

/** A value already in `.env` that production would refuse. */
function checkRealValues(name: string, defined: Map<string, string>): string[] {
  const secret = defined.get("NEXTLY_SECRET");
  if (secret === undefined || secret.length >= 32) return [];
  return [
    `NEXTLY_SECRET in ${name} is shorter than the 32 characters production requires. ` +
      "It was left as it is; replace it, for example with `openssl rand -base64 32`.",
  ];
}

/** A real-looking secret already in a file a project commits. */
function checkExampleValues(
  name: string,
  defined: Map<string, string>
): string[] {
  const warnings: string[] = [];
  const secret = defined.get("NEXTLY_SECRET");
  if (secret !== undefined && !isPlaceholder(secret)) {
    warnings.push(
      `${name} holds a value for NEXTLY_SECRET. An example file should hold a placeholder: ` +
        "empty it, and if the file was ever committed, replace the secret itself."
    );
  }
  if (hasRealPassword(defined.get("DATABASE_URL"))) {
    warnings.push(
      `${name} holds a database password in DATABASE_URL. An example file should hold a ` +
        "placeholder: replace it, and if the file was ever committed, change the password."
    );
  }
  return warnings;
}

function isPlaceholder(value: string): boolean {
  return (
    value === "" ||
    /^<.*>$/.test(value) ||
    /change[-_ ]?me|your[-_ ]|replace|placeholder|example|^x+$/i.test(value)
  );
}

function hasRealPassword(url: string | undefined): boolean {
  if (!url) return false;
  try {
    const password = decodeURIComponent(new URL(url).password);
    return (
      password !== "" &&
      !isPlaceholder(password) &&
      !["password", "pass"].includes(password.toLowerCase())
    );
  } catch {
    return false;
  }
}

/**
 * Makes sure git ignores `.env`, which holds the real secret: a project's own
 * `.gitignore` might not. Git answers when the project is a repository; a
 * directory that is not one yet is judged from its `.gitignore`.
 */
async function keepEnvOutOfGit(
  cwd: string,
  files: GeneratedFiles
): Promise<void> {
  if (await isEnvIgnored(cwd)) return;

  const file = path.join(cwd, ".gitignore");
  const entry =
    "# Local environment: it holds secrets, so it is never committed\n.env\n";
  if (await fs.pathExists(file)) {
    const text = await fs.readFile(file, "utf-8");
    const separator = text === "" || text.endsWith("\n") ? "" : "\n";
    await fs.appendFile(file, `${separator}\n${entry}`, "utf-8");
    files.changed.push({ path: ".gitignore", added: [".env"] });
  } else {
    await fs.writeFile(file, entry, "utf-8");
    files.written.push(".gitignore");
  }
}

async function isEnvIgnored(cwd: string): Promise<boolean> {
  try {
    await execa("git", ["check-ignore", "-q", ".env"], { cwd });
    return true;
  } catch (error) {
    // 1: inside a repository, and not ignored. Anything else (not a
    // repository, or no git) falls back to reading the project's .gitignore.
    if ((error as { exitCode?: number }).exitCode === 1) return false;
  }
  const file = path.join(cwd, ".gitignore");
  if (!(await fs.pathExists(file))) return false;
  return gitignoreIgnores(await fs.readFile(file, "utf-8"), ".env");
}

/**
 * Whether a root `.gitignore` ignores a file at the project root, for the
 * patterns a root-level file can be matched by: the last matching line wins,
 * and `!` re-includes.
 */
function gitignoreIgnores(text: string, name: string): boolean {
  let ignored = false;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) continue;
    const negated = line.startsWith("!");
    const pattern = line.replace(/^!/, "").replace(/^\//, "");
    if (pattern.includes("/")) continue;
    const regex = new RegExp(
      "^" +
        pattern
          .replace(/[.+^${}()|[\]\\]/g, "\\$&")
          .replace(/\*/g, "[^/]*")
          .replace(/\?/g, "[^/]") +
        "$"
    );
    if (regex.test(name)) ignored = !negated;
  }
  return ignored;
}
