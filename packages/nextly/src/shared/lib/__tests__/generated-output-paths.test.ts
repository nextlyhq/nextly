import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { afterEach, describe, expect, it } from "vitest";

import {
  DEFAULT_DB_CONFIG,
  DEFAULT_TYPESCRIPT_CONFIG,
} from "../../types/config";
import { TypeGenerator } from "../../../domains/schema/services/type-generator";
import {
  generatedTypesFile,
  generatedZodDir,
  projectUsesSrcLayout,
  retireOldDefaultTypesFile,
} from "../generated-output-paths";

const made: string[] = [];
function project(...dirs: string[]): string {
  const root = mkdtempSync(join(tmpdir(), "nextly-layout-"));
  made.push(root);
  for (const dir of dirs) mkdirSync(join(root, dir), { recursive: true });
  return root;
}
afterEach(() => {
  for (const root of made.splice(0))
    rmSync(root, { recursive: true, force: true });
});

describe("projectUsesSrcLayout — as Next.js decides it", () => {
  it("is true for an app under src/", () => {
    expect(projectUsesSrcLayout(project("src/app"))).toBe(true);
  });

  it("is false for an app at the root, with no src/", () => {
    expect(projectUsesSrcLayout(project("app"))).toBe(false);
  });

  it("is false when a root app/ exists beside src/, since Next.js then ignores src/app", () => {
    expect(projectUsesSrcLayout(project("app", "src/app"))).toBe(false);
  });

  it("counts pages/ as an app directory too", () => {
    expect(projectUsesSrcLayout(project("pages"))).toBe(false);
    expect(projectUsesSrcLayout(project("src/pages"))).toBe(true);
  });
});

describe("generated output follows the project's layout", () => {
  it("keeps the built-in paths in a project under src/", () => {
    const root = project("src/app");

    expect(generatedTypesFile(root, DEFAULT_TYPESCRIPT_CONFIG.outputFile)).toBe(
      resolve(root, DEFAULT_TYPESCRIPT_CONFIG.outputFile)
    );
    expect(generatedZodDir(root, DEFAULT_DB_CONFIG.schemasDir)).toBe(
      resolve(root, DEFAULT_DB_CONFIG.schemasDir, "zod")
    );
  });

  it("drops src/ from the built-in paths in a project without one", () => {
    const root = project("app");

    expect(generatedTypesFile(root, DEFAULT_TYPESCRIPT_CONFIG.outputFile)).toBe(
      resolve(
        root,
        DEFAULT_TYPESCRIPT_CONFIG.outputFile.replace("./src/", "./")
      )
    );
    expect(generatedZodDir(root, DEFAULT_DB_CONFIG.schemasDir)).toBe(
      resolve(root, DEFAULT_DB_CONFIG.schemasDir.replace("./src/", "./"), "zod")
    );
  });

  it("leaves a path the project chose alone, whatever its layout", () => {
    // Only the built-in default guesses at a layout; a configured path is the
    // project's own decision, even one that names a src/ the project lacks.
    const root = project("app");

    expect(generatedTypesFile(root, "./src/custom/types.ts")).toBe(
      resolve(root, "./src/custom/types.ts")
    );
    expect(generatedZodDir(root, "./lib/schemas")).toBe(
      resolve(root, "./lib/schemas", "zod")
    );
  });
});

describe("the default types file is named for Nextly", () => {
  it("writes generated types to nextly-types.ts when the project sets no path", () => {
    const root = project("src/app");

    expect(generatedTypesFile(root, DEFAULT_TYPESCRIPT_CONFIG.outputFile)).toBe(
      resolve(root, "src/types/generated/nextly-types.ts")
    );
  });
});

describe("a payload-types.ts left by the old default", () => {
  // What every version so far has written at the top of the file.
  const GENERATED_HEADER = [
    "/* tslint:disable */",
    "/* eslint-disable */",
    "/**",
    " * This file was automatically generated by Nextly.",
    " * DO NOT MODIFY IT BY HAND. Instead, modify your source collections,",
    " * and run `npx nextly generate:types` to regenerate this file.",
    " */",
    'declare module "nextly" {',
    "  export interface GeneratedTypes extends Config {}",
    "}",
    "",
  ].join("\n");
  const DEFAULT = DEFAULT_TYPESCRIPT_CONFIG.outputFile;

  function appWith(layout: string, dir: string, content: string): string {
    const root = project(layout, dir);
    writeFileSync(join(root, dir, "payload-types.ts"), content);
    return root;
  }
  const oldFile = (root: string, dir = "src/types/generated") =>
    readFileSync(join(root, dir, "payload-types.ts"), "utf-8");
  const settle = (root: string, configured = DEFAULT) =>
    retireOldDefaultTypesFile(root, configured);

  it("becomes a re-export of nextly-types.ts, so imports of either name get the current types", () => {
    const root = appWith("src/app", "src/types/generated", GENERATED_HEADER);

    const notices = settle(root);

    // One declaration of "nextly": a stale copy beside the new file would
    // declare GeneratedTypes twice.
    expect(oldFile(root)).not.toContain("declare module");
    expect(oldFile(root)).toContain('export * from "./nextly-types.js";');
    expect(notices).toHaveLength(1);
    expect(notices[0]).toContain("src/types/generated/payload-types.ts");
    expect(notices[0]).toContain("src/types/generated/nextly-types.ts");
    expect(notices[0]).toMatch(/import/);
  });

  it("recognises the file the current generator writes", () => {
    const generated = new TypeGenerator().generateTypesFile([]).code;
    const root = appWith("src/app", "src/types/generated", generated);

    settle(root);

    expect(oldFile(root)).toContain('export * from "./nextly-types.js";');
  });

  it("recognises a generated file checked out with Windows line endings", () => {
    const root = appWith(
      "src/app",
      "src/types/generated",
      GENERATED_HEADER.replace(/\n/g, "\r\n")
    );

    settle(root);

    expect(oldFile(root)).toContain('export * from "./nextly-types.js";');
  });

  it("says nothing once it is already the re-export", () => {
    const root = appWith("src/app", "src/types/generated", GENERATED_HEADER);
    settle(root);
    const reexport = oldFile(root);

    expect(settle(root)).toEqual([]);
    expect(oldFile(root)).toBe(reexport);
  });

  it("leaves a file Nextly didn't write as it is, and warns about it", () => {
    const own = "export interface Mine { id: string }\n";
    const root = appWith("src/app", "src/types/generated", own);

    const notices = settle(root);

    expect(oldFile(root)).toBe(own);
    expect(notices).toHaveLength(1);
    expect(notices[0]).toContain("src/types/generated/payload-types.ts");
    expect(notices[0]).toContain("nextly-types.ts");
    expect(notices[0]).not.toMatch(/moved/);
  });

  it("leaves a file that only quotes the generated header as it is", () => {
    const own = [
      "// Our types. The old generated file said:",
      "// This file was automatically generated by Nextly.",
      "export interface Mine { id: string }",
      "",
    ].join("\n");
    const root = appWith("src/app", "src/types/generated", own);

    settle(root);

    expect(oldFile(root)).toBe(own);
  });

  it("is left alone when the project names its types file", () => {
    const root = appWith("src/app", "src/types/generated", GENERATED_HEADER);

    expect(settle(root, "./src/types/generated/payload-types.ts")).toEqual([]);
    expect(oldFile(root)).toBe(GENERATED_HEADER);
  });

  it("is found beside the default in an app without src/", () => {
    const root = appWith("app", "types/generated", GENERATED_HEADER);

    const notices = settle(root);

    expect(oldFile(root, "types/generated")).toContain(
      'export * from "./nextly-types.js";'
    );
    expect(notices[0]).toContain("types/generated/nextly-types.ts");
  });

  it("is found at the old src/ path in an app without src/, where earlier versions wrote it", () => {
    // Before generated paths followed the app's layout, the default's src/
    // was written as it stands, even in an app whose code is at the root.
    const root = appWith("app", "src/types/generated", GENERATED_HEADER);

    const notices = settle(root);

    expect(oldFile(root)).toContain(
      'export * from "../../../types/generated/nextly-types.js";'
    );
    expect(notices[0]).toContain("src/types/generated/payload-types.ts");
    expect(notices[0]).toContain("types/generated/nextly-types.ts");
  });

  it("does nothing when there is no old file", () => {
    expect(settle(project("src/app"))).toEqual([]);
  });
});
