/**
 * Where `nextly generate:types` and the other code generators write into the
 * app: the TypeScript types file and the folder of Zod schemas.
 *
 * The built-in defaults name a `src/` folder (`./src/types/generated/...`,
 * `./src/db/schemas/collections`), which suits an app under `src/` and creates
 * a stray one in an app without it. So a path still at its built-in default
 * follows the app's layout, and a path the project configured is used as
 * written: only the default was ever a guess. A project that writes the
 * default's exact text in its config is read as having left it at the default.
 *
 * Every writer of generated output resolves its paths here, so the generators
 * cannot disagree about where a file goes.
 */

import { existsSync, readFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";

import { DEFAULT_DB_CONFIG, DEFAULT_TYPESCRIPT_CONFIG } from "../types/config";

/**
 * Whether the app keeps its code under `src/`, decided as Next.js decides it:
 * an `app/` or `pages/` folder at the root wins, and `src/app` and `src/pages`
 * are then ignored; otherwise `src/` holds the app if it exists.
 */
export function projectUsesSrcLayout(cwd: string): boolean {
  const rootAppDir =
    existsSync(join(cwd, "app")) || existsSync(join(cwd, "pages"));
  return !rootAppDir && existsSync(join(cwd, "src"));
}

/** A built-in default without its leading `src/`, in an app that has none. */
function fitToLayout(
  configured: string,
  builtInDefault: string,
  cwd: string
): string {
  if (configured !== builtInDefault || projectUsesSrcLayout(cwd)) {
    return configured;
  }
  return configured.replace(/^(\.\/)?src\//, "$1");
}

/** The absolute path of the generated TypeScript types file. */
export function generatedTypesFile(cwd: string, configured: string): string {
  return resolve(
    cwd,
    fitToLayout(configured, DEFAULT_TYPESCRIPT_CONFIG.outputFile, cwd)
  );
}

/** The name the default types file had before it was named for Nextly. */
const OLD_DEFAULT_TYPES_FILE = "payload-types.ts";

/**
 * How every types file Nextly generates opens, unchanged in every version so
 * far: what tells a `payload-types.ts` Nextly generated from one the app wrote.
 * Matched at the start of the file only, so app code that quotes it is never
 * taken for generated output.
 */
const GENERATED_TYPES_PREAMBLE = [
  "/* tslint:disable */",
  "/* eslint-disable */",
  "/**",
  " * This file was automatically generated by Nextly.",
  "",
].join("\n");

/**
 * The re-export 0.0.2-alpha.67 and alpha.68 wrote in place of a generated
 * `payload-types.ts`, for one release of imports under the old name. Nextly
 * no longer writes it; this only recognises one a project still has, which
 * compiles as it is (one declaration of `module "nextly"`, in the new file)
 * and can be deleted once nothing imports `payload-types`.
 */
function earlierReleasesReexport(oldFile: string, typesFile: string): string {
  const fromOld = relative(dirname(oldFile), typesFile)
    .split(sep)
    .join("/")
    .replace(/\.ts$/, ".js");
  const target = fromOld.startsWith(".") ? fromOld : `./${fromOld}`;
  return [
    "/**",
    ` * Nextly's generated types are in ${basename(typesFile)}. This file only`,
    " * re-exports them, so imports of payload-types keep compiling; a later",
    ` * release removes it. Import from ${basename(typesFile, ".ts")} instead.`,
    " */",
    `export * from "${target}";`,
    "",
  ].join("\n");
}

/** A path as the developer sees it: relative to the app, with `/` on every OS. */
function shownPath(cwd: string, path: string): string {
  return relative(cwd, path).split(sep).join("/");
}

/**
 * Where an earlier version may have left `payload-types.ts`: beside the new
 * file, and at the default's literal `src/` path, which every version before
 * output paths followed the app's layout wrote even in an app without `src/`.
 */
function oldDefaultTypesFiles(cwd: string, typesFile: string): string[] {
  const literal = resolve(
    cwd,
    dirname(DEFAULT_TYPESCRIPT_CONFIG.outputFile),
    OLD_DEFAULT_TYPES_FILE
  );
  return [
    ...new Set([join(dirname(typesFile), OLD_DEFAULT_TYPES_FILE), literal]),
  ];
}

/**
 * What to tell the developer about each `payload-types.ts` an earlier version
 * left where the default types file went, one message per file it found. It
 * changes no file.
 *
 * Only when the project leaves the types path at its default: a configured
 * path, even the old one, is the project's own and is written as it says.
 * Every file found is left as it is:
 * - the re-export earlier releases wrote compiles, and can be deleted once
 *   imports name the new file;
 * - a file an earlier version generated declares `module "nextly"` a second
 *   time, so TypeScript refuses the two once they differ, or under
 *   `skipLibCheck` silently uses whichever it reaches first. Rewriting it was
 *   a one-release bridge; now the developer is told to delete it;
 * - a file Nextly did not write may be the app's own code.
 */
export function retireOldDefaultTypesFile(
  cwd: string,
  configured: string
): string[] {
  if (configured !== DEFAULT_TYPESCRIPT_CONFIG.outputFile) return [];

  const typesFile = generatedTypesFile(cwd, configured);
  const notices: string[] = [];
  for (const oldFile of oldDefaultTypesFiles(cwd, typesFile)) {
    if (!existsSync(oldFile)) continue;

    // A checkout with Windows line endings still reads as Nextly's.
    const content = readFileSync(oldFile, "utf-8").replace(/\r\n/g, "\n");
    const oldShown = shownPath(cwd, oldFile);
    const newShown = shownPath(cwd, typesFile);

    if (content === earlierReleasesReexport(oldFile, typesFile)) {
      notices.push(
        `${oldShown} only re-exports ${newShown}, and Nextly no longer ` +
          `writes it. Once nothing imports payload-types, delete it: import ` +
          `from nextly-types instead.`
      );
      continue;
    }

    if (!content.startsWith(GENERATED_TYPES_PREAMBLE)) {
      notices.push(
        `${oldShown} was not written by Nextly, so it was left as it is. ` +
          `Nextly's generated types now go to ${newShown}. If ${oldShown} ` +
          `also declares module "nextly", the two clash, and TypeScript may ` +
          `use its types instead of the new ones: rename or remove it.`
      );
      continue;
    }

    notices.push(
      `${oldShown} holds types an earlier version of Nextly generated, and is ` +
        `no longer updated: generated types now go to ${newShown}. Both ` +
        `declare module "nextly", so they clash, and TypeScript may use the ` +
        `old types. Delete ${oldShown} and change imports of payload-types to ` +
        `nextly-types. To keep the old name, set typescript.outputFile in ` +
        `your Nextly config.`
    );
  }
  return notices;
}

/** The absolute path of the folder generated Zod schemas are written to. */
export function generatedZodDir(cwd: string, schemasDir: string): string {
  return resolve(
    cwd,
    fitToLayout(schemasDir, DEFAULT_DB_CONFIG.schemasDir, cwd),
    "zod"
  );
}
