/**
 * Where `nextly generate:types` and the other code generators write into the
 * app: the TypeScript types file and the folder of Zod schemas.
 *
 * The built-in defaults name a `src/` folder (`./src/types/generated/...`,
 * `./src/db/schemas/collections`), which suits an app under `src/` and creates
 * a stray one in an app without it. So a path still at its built-in default
 * follows the app's layout, and a path the project configured is used as
 * written: only the default was ever a guess. A project that writes the
 * default's exact text in its config is read as having left it at the default.
 *
 * Every writer of generated output resolves its paths here, so the generators
 * cannot disagree about where a file goes.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";

import { DEFAULT_DB_CONFIG, DEFAULT_TYPESCRIPT_CONFIG } from "../types/config";

/**
 * Whether the app keeps its code under `src/`, decided as Next.js decides it:
 * an `app/` or `pages/` folder at the root wins, and `src/app` and `src/pages`
 * are then ignored; otherwise `src/` holds the app if it exists.
 */
export function projectUsesSrcLayout(cwd: string): boolean {
  const rootAppDir =
    existsSync(join(cwd, "app")) || existsSync(join(cwd, "pages"));
  return !rootAppDir && existsSync(join(cwd, "src"));
}

/** A built-in default without its leading `src/`, in an app that has none. */
function fitToLayout(
  configured: string,
  builtInDefault: string,
  cwd: string
): string {
  if (configured !== builtInDefault || projectUsesSrcLayout(cwd)) {
    return configured;
  }
  return configured.replace(/^(\.\/)?src\//, "$1");
}

/** The absolute path of the generated TypeScript types file. */
export function generatedTypesFile(cwd: string, configured: string): string {
  return resolve(
    cwd,
    fitToLayout(configured, DEFAULT_TYPESCRIPT_CONFIG.outputFile, cwd)
  );
}

/** The name the default types file had before it was named for Nextly. */
const OLD_DEFAULT_TYPES_FILE = "payload-types.ts";

/**
 * The line every types file Nextly generates opens with, in every version so
 * far: what tells a `payload-types.ts` Nextly wrote from one the app wrote.
 */
const GENERATED_TYPES_HEADER =
  "This file was automatically generated by Nextly.";

/**
 * What a generated `payload-types.ts` becomes: a re-export of the new file, so
 * imports of either name compile against the current types while only one
 * file declares `module "nextly"`. Two declarations of `GeneratedTypes` are
 * refused by TypeScript as soon as they differ. The `.js` spelling resolves
 * under `nodenext` as well as `bundler`. It does not carry the generated
 * header, so a later run sees it is already settled.
 */
function reexportOfTypesFile(typesFile: string): string {
  const target = `./${basename(typesFile).replace(/\.ts$/, ".js")}`;
  return [
    "/**",
    ` * Nextly's generated types are in ${basename(typesFile)}. This file only`,
    " * re-exports them, so imports of payload-types keep compiling; a later",
    ` * release removes it. Import from ${basename(typesFile, ".ts")} instead.`,
    " */",
    `export * from "${target}";`,
    "",
  ].join("\n");
}

/** A path as the developer sees it: relative to the app, with `/` on every OS. */
function shownPath(cwd: string, path: string): string {
  return relative(cwd, path).split(sep).join("/");
}

/**
 * Settles the `payload-types.ts` an earlier version wrote where the default
 * types file now goes, and returns what to tell the developer, if anything.
 *
 * Only when the project leaves the types path at its default: a configured
 * path, even the old one, is the project's own and is written as it says. A
 * `payload-types.ts` Nextly generated becomes a re-export of the new file. One
 * Nextly did not write is left as it is, with a warning, since it may be the
 * app's own code.
 */
export function retireOldDefaultTypesFile(
  cwd: string,
  configured: string
): string | undefined {
  if (configured !== DEFAULT_TYPESCRIPT_CONFIG.outputFile) return undefined;

  const typesFile = generatedTypesFile(cwd, configured);
  const oldFile = join(dirname(typesFile), OLD_DEFAULT_TYPES_FILE);
  if (!existsSync(oldFile)) return undefined;

  const reexport = reexportOfTypesFile(typesFile);
  const content = readFileSync(oldFile, "utf-8");
  if (content === reexport) return undefined;

  const oldShown = shownPath(cwd, oldFile);
  const newShown = shownPath(cwd, typesFile);
  if (!content.includes(GENERATED_TYPES_HEADER)) {
    return (
      `${oldShown} was not written by Nextly, so it was left as it is. ` +
      `Nextly's generated types now go to ${newShown}. If ${oldShown} also ` +
      `declares module "nextly", TypeScript will report that the two clash: ` +
      `rename or remove it.`
    );
  }

  writeFileSync(oldFile, reexport, "utf-8");
  return (
    `Generated types moved from ${oldShown} to ${newShown}, the name Nextly ` +
    `now uses by default. ${oldShown} now only re-exports the new file, so ` +
    `existing imports keep compiling until a later release removes it: change ` +
    `imports of payload-types to nextly-types. To keep the old name, set ` +
    `typescript.outputFile in your Nextly config.`
  );
}

/** The absolute path of the folder generated Zod schemas are written to. */
export function generatedZodDir(cwd: string, schemasDir: string): string {
  return resolve(
    cwd,
    fitToLayout(schemasDir, DEFAULT_DB_CONFIG.schemasDir, cwd),
    "zod"
  );
}
