/**
 * An installed plugin that is disabled keeps its tables and gains its new
 * migration module at a boot that migrates, while none of its other code
 * runs — and works again once enabled.
 *
 * `enabled: false` is a behaviour switch, not a storage one: the compiled
 * schema still holds the plugin's tables, so a boot that skipped a disabled
 * plugin's modules would hold a shape the model says is there and the
 * database does not. The boot must therefore apply the new module while the
 * plugin is disabled, and mount nothing of its behaviour — no `init`, no
 * route — until it is enabled again.
 *
 * The scenario runs across three boots on one database: installed at its
 * first module while enabled, disabled while a second module ships (the boot
 * migrates, and applies it), enabled again while a third ships. The third
 * boot's `init` reads the table that boot's own migration creates, so a boot
 * that initialised plugins before its migrations fails there rather than
 * passing: migrations before plugins is what lets that read succeed.
 *
 * The modules are generated by the real generator, the adapter is a real one
 * over a throwaway database, and the boots run the real `migrateCore` — only
 * the config loader is faked, exactly as the uninstall sibling does.
 *
 * @module cli/commands/__tests__/plugin-disabled-boot-migrations.integration
 */
