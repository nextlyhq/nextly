const PLUGIN = "@acme/bm";
const PREFIX = "bm";

const notes = defineTable("notes", {
  id: col.id(),
  body: col.shortText({ nullable: true }),
});
const tags = defineTable("tags", {
  id: col.id(),
  label: col.shortText({ nullable: true }),
});
const extras = defineTable("extras", {
  id: col.id(),
  mark: col.shortText({ nullable: true }),
});

/** The row the plugin's `init` writes once it is enabled again. */
const INIT_ROW_ID = "bm-init-1";

/**
 * The row installed at v1, before the plugin was ever disabled: the later
 * boots must still find it, since an exists() check alone cannot tell a kept
 * table from one a boot dropped and recreated empty.
 */
const SENTINEL_ID = "bm-sentinel-1";

/**
 * How many times each phase's `init` has run across the scenario's boots.
 *
 * Two counters because the phases boot different fixtures of one plugin: the
 * disabled boot's fixture carries its own observable `init`, so a regression
 * that initialised disabled plugins bumps a counter the disabled phase
 * asserts stayed at zero, rather than passing on a fixture with no `init` at
 * all.
 */
let enabledInitRuns = 0;
let disabledInitRuns = 0;

const statusRoute = {
  method: "GET" as const,
  path: "/status",
  public: true,
  handler: async () => Response.json({ ok: true }),
};

/**
 * The plugin as each phase boots it. `tables` names only what that phase's
 * shipped modules create — as a plugin upgrade ships them — so a table's
 * declaration arrives with the module that builds it: the final boot
 * declares `extras` for the first time, and a boot that kept the disabled
 * phase's declarations has nothing to compile it from. `init` names that
 * phase's fixture: the enabled boot's reads its own pending module's table,
 * which is what fails when a boot initialises plugins before its migrations,
 * and the disabled boot's counts its runs, which is what fails when a
 * disabled plugin's code runs at all.
 */
function pluginWith(
  migrations: PluginMigration[],
  opts: {
    enabled: boolean;
    schemaVersion: number;
    tables: ReturnType<typeof defineTable>[];
    init?: "enabled" | "disabled";
    route?: boolean;
  }
) {
  return definePlugin({
    name: PLUGIN,
    version: "1.0.0",
    nextly: ">=0.0.0",
    enabled: opts.enabled,
    schemaVersion: opts.schemaVersion,
    ...(opts.init === "enabled"
      ? {
          init: async (ctx: PluginContext) => {
            enabledInitRuns += 1;
            // The table the boot's own pending module creates. Reaching the
            // row below proves the migrations ran first; a boot that
            // initialised plugins before them fails the select instead.
            await ctx.db.select(extras).all();
            // Written through the plugin's own surface, so the schema the
            // migrations laid out serves it again once it is enabled.
            await ctx.db.insert(notes, {
              id: INIT_ROW_ID,
              body: "written once enabled",
            });
          },
        }
      : opts.init === "disabled"
        ? {
            init: async (ctx: PluginContext) => {
              disabledInitRuns += 1;
              // A read the table exists to answer, so the callback is the
              // `init` the plugin would have run: a boot that initialises
              // disabled plugins runs it, bumps the counter, and fails the
              // phase's assertion below.
              await ctx.db.select(notes).all();
            },
          }
        : {}),
    contributes: {
      schema: {
        prefix: PREFIX,
        tables: opts.tables,
        migrations,
      },
      ...(opts.route ? { routes: [statusRoute] } : {}),
    },
  }) as unknown;
}

/** The plugin's tables compiled for every dialect by the real builder. */
async function tablesByDialect(tables: ReturnType<typeof defineTable>[]) {
  const out = {} as Parameters<
    typeof buildPluginMigration
  >[0]["tablesByDialect"];
  for (const dialect of ALL) {
    const built = await buildExtensionSchema({
      dialect,
      coreTableNames: CORE_TABLE_NAMES,
      entities: [],
      pluginPrefixes: new Map([[PLUGIN, PREFIX]]),
      plugins: [{ owner: { kind: "plugin", id: PLUGIN }, tables }],
    });
    out[dialect] = built.specs;
  }
  return out;
}

/** Three modules: `notes` creates bm__notes, `tags` bm__tags, `extras` bm__extras. */
async function generateModules(): Promise<PluginMigration[]> {
  const first = buildPluginMigration({
    pluginName: PLUGIN,
    schemaVersion: 1,
    name: "notes",
    now: new Date(Date.UTC(2026, 10, 3, 10, 0, 0)),
    tablesByDialect: await tablesByDialect([notes]),
    existing: [],
  });
  if (!first) throw new Error("no first module generated");
  const second = buildPluginMigration({
    pluginName: PLUGIN,
    schemaVersion: 2,
    name: "tags",
    now: new Date(Date.UTC(2026, 10, 3, 11, 0, 0)),
    tablesByDialect: await tablesByDialect([notes, tags]),
    existing: [first.module],
  });
  if (!second) throw new Error("no second module generated");
  const third = buildPluginMigration({
    pluginName: PLUGIN,
    schemaVersion: 3,
    name: "extras",
    now: new Date(Date.UTC(2026, 10, 3, 12, 0, 0)),
    tablesByDialect: await tablesByDialect([notes, tags, extras]),
    existing: [first.module, second.module],
  });
  if (!third) throw new Error("no third module generated");
  return [first.module, second.module, third.module];
}

let modules: PluginMigration[] = [];

/** The ledger key of one of the plugin's modules. */
function key(migration: PluginMigration): string {
  return qualifiedFilename(PLUGIN, migration.name);
}

/**
 * What one production boot migrates on: the raw settings this scenario turns
 * on, against the test's adapter. The migrations directory is empty — the
 * app ships no files — so every applied module below is the plugin's.
 */
let migrationsDir = "";

/**
 * Puts the process back between phases: what a boot or a test may leave —
 * production mode, the gate's pending boot or refusal, the plugin teardown
 * list, the registered container, the route and hook registries and the
 * cached Direct API instance — is dropped, and production mode is stubbed
 * for the next boot.
 *
 * The boot-migrations gate is INSPECTED, not just wiped: a gate a boot left
 * pending, or a refusal it recorded, is a failure this test surfaces, not
 * state the reset would silently wipe. The reset runs even when the
 * inspection throws, so the failure is reported where it happened while the
 * next phase or test starts from a clean gate instead of inheriting it.
 */
function rebootProcessState(): void {
  vi.unstubAllEnvs();
  _resetEnvCache();
  resetPluginRouteRegistry();
  resetHookRegistry();
  try {
    assertBootMigrationsSettled();
  } finally {
    _resetBootMigrationsGateForTest();
  }
}

/** What the environment said before any test changed it. */
const NODE_ENV_AT_START = process.env.NODE_ENV;

describe.each(getConfiguredTestDialects())(
  "a disabled plugin's new migration at a boot that migrates (%s)",
  dialect => {
    let handle: TestNextly | undefined;
    const db = () => handle!.adapter.getDrizzle();
    const exists = (table: string) => handle!.adapter.tableExists(table);

    /**
     * The modules the ledger records applied, as SORTED qualified filenames.
     *
     * The ledger's row order is the dialect's read order, not the order the
     * modules applied in, so a comparison against these keys must be order
     * independent: which modules applied is this test's subject, and the
     * application order is another suite's.
     */
    async function appliedKeys(): Promise<string[]> {
      const rows = await new SchemaEventsRepository(
        handle!.adapter.getDrizzle(),
        dialect
      ).listFileApplies();
      return [...appliedPluginShas(rows).keys()].sort();
    }

    /** The config one production boot is started with. */
    function bootConfig(): Record<string, unknown> {
      return {
        adapter: run.adapter,
        basePath: handle!.basePath,
        imageProcessor: getImageProcessor(),
        hookRegistry: getHookRegistry(),
        logger: createLogger({ quiet: true }),
        plugins: [run.plugin],
        db: {
          runMigrationsOnBoot: true,
          migrationsDir,
          uiSchemaFile: join(migrationsDir, "ui-schema.json"),
        },
      };
    }

    beforeEach(async () => {
      if (modules.length === 0) modules = await generateModules();
      migrationsDir = mkdtempSync(join(tmpdir(), "nextly-disabled-boot-"));
      rebootProcessState();
      handle = await createTestNextly(dialect === "sqlite" ? {} : { dialect });
      await reconcileCore({
        db: db(),
        dialect,
        logger: { info: () => {}, warn: () => {} },
      });
      enabledInitRuns = 0;
      disabledInitRuns = 0;
      run.dialect = dialect;
      run.adapter = handle.adapter;
    });

    afterEach(async () => {
      // The inspection's failure must not skip the teardown it precedes: a
      // boot whose regression refused migrations still has its throwaway
      // database dropped, its connection closed and its directory removed
      // before the error surfaces, so one phase's regression fails its own
      // test rather than every test after it.
      try {
        rebootProcessState();
      } finally {
        await handle?.destroy();
        handle = undefined;
        rmSync(migrationsDir, { recursive: true, force: true });
      }
    });

    const context = {
      logger: createLogger({ quiet: true }),
    } as unknown as CommandContext;

    /** The rows the sentinel's id selects, read back per dialect. */
    const sentinelRows = async () =>
      handle!.adapter.executeQuery(
        `SELECT id FROM bm__notes WHERE id = '${SENTINEL_ID}'`
      );

    it("applies the new module while disabled, mounts none of its behaviour, and works again once enabled", async () => {
      // Installed at its first module, enabled: the record the disabled boot
      // reads, and the state its other two modules build on. Only the
      // installed module's table is declared — each phase declares exactly
      // what its shipped modules create, as a plugin upgrade ships them.
      run.plugin = pluginWith([modules[0]], {
        enabled: true,
        schemaVersion: 1,
        tables: [notes],
      });
      await runPluginInstall(PLUGIN, {}, context);

      expect(await exists("bm__notes")).toBe(true);
      // The data the install leaves behind, written so the later boots can be
      // told a kept table from one dropped and recreated empty.
      await handle!.adapter.executeQuery(
        `INSERT INTO bm__notes (id, body) VALUES ('${SENTINEL_ID}', 'installed before the plugin was disabled')`
      );
      expect(await sentinelRows()).toHaveLength(1);
      // Only the installed module's table: nothing of the later modules has
      // been created by an install that never saw them.
      expect(await exists("bm__tags")).toBe(false);
      expect(await exists("bm__extras")).toBe(false);
      expect(await appliedKeys()).toEqual([key(modules[0])]);
      expect(enabledInitRuns).toBe(0);
      expect(disabledInitRuns).toBe(0);

      // Disabled, shipping its second module, booted with migrations on. The
      // fixture declares only notes and tags — extras is still undeclared —
      // and carries its own observable `init`, so a boot that initialised
      // disabled plugins would bump its counter and fail the assertion below,
      // rather than passing on a fixture with no `init` at all.
      run.plugin = pluginWith([modules[0], modules[1]], {
        enabled: false,
        schemaVersion: 2,
        tables: [notes, tags],
        init: "disabled",
        route: true,
      });
      await destroyRegisteredPlugins();
      clearServices();
      vi.stubEnv("NODE_ENV", "production");
      vi.stubEnv("NEXT_PUBLIC_APP_URL", "http://localhost:3000");
      _resetEnvCache();

      await registerServices(bootConfig() as never);

      // The new module applied at the boot, while the plugin was disabled.
      // Both sides sorted: the ledger's row order is the dialect's.
      expect(await exists("bm__tags")).toBe(true);
      expect(await appliedKeys()).toEqual(
        [key(modules[0]), key(modules[1])].sort()
      );
      // Its tables kept, and the row installed at v1 is still in them —
      // disabling changed nothing about storage.
      expect(await exists("bm__notes")).toBe(true);
      expect(await sentinelRows()).toHaveLength(1);
      // None of its behaviour ran: the `init` the disabled fixture carries
      // never fired, and its route never mounted.
      expect(disabledInitRuns).toBe(0);
      expect(enabledInitRuns).toBe(0);
      expect(
        getPluginRouteRegistry()
          .list()
          .filter(registered => registered.pluginName === PLUGIN)
      ).toEqual([]);

      // Enabled again, shipping its third module and declaring its table for
      // the first time, booted with migrations on. The `init` on this boot
      // reads the table that boot's migration creates, so the assertions
      // below are what "migrations before plugins initialise" lets succeed.
      run.plugin = pluginWith(modules, {
        enabled: true,
        schemaVersion: 3,
        tables: [notes, tags, extras],
        init: "enabled",
        route: true,
      });
      await destroyRegisteredPlugins();
      clearServices();
      vi.stubEnv("NODE_ENV", "production");
      vi.stubEnv("NEXT_PUBLIC_APP_URL", "http://localhost:3000");
      _resetEnvCache();

      await registerServices(bootConfig() as never);

      // Its code runs again, against the schema all three modules laid out,
      // and the disabled phase's `init` never ran anywhere.
      expect(enabledInitRuns).toBe(1);
      expect(disabledInitRuns).toBe(0);
      expect(await exists("bm__extras")).toBe(true);
      expect(await appliedKeys()).toEqual(
        [key(modules[0]), key(modules[1]), key(modules[2])].sort()
      );
      const written = await handle!.adapter.executeQuery(
        `SELECT id FROM bm__notes WHERE id = '${INIT_ROW_ID}'`
      );
      expect(written).toHaveLength(1);
      // The row installed at v1 survived both boots beside the one `init`
      // wrote: the table serves the plugin's old data and its new code.
      expect(await sentinelRows()).toHaveLength(1);
      // And its route mounts again.
      expect(
        getPluginRouteRegistry()
          .list()
          .filter(registered => registered.pluginName === PLUGIN)
          .map(registered => registered.fullPath)
      ).toEqual([`/plugins/${PLUGIN}/status`]);
    }, 120_000);
  }
);

describe("the process state a test leaves", () => {
  it("does not reach the next test", () => {
    expect(process.env.NODE_ENV).toBe(NODE_ENV_AT_START);
    // The last afterEach inspected and reset the gate; nothing of this file
    // left a pending boot or a refusal behind for the next one to inherit.
    expect(() => assertBootMigrationsSettled()).not.toThrow();
    expect(getPluginRouteRegistry().list()).toEqual([]);
  });
});
