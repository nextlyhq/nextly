/**
 * A plugin module whose run stopped — the process killed — after its
 * statements committed and before it was recorded, or before its first
 * change, on every configured dialect.
 *
 * A killed process records no outcome: its ledger row stays `in_progress`.
 * Each test builds exactly that state — the module's statements run, or not,
 * and its attempt started through the ledger's own repository — and then
 * migrates again:
 *
 * - a module that changes only the schema, standing at its result, is
 *   recorded applied without running again: the schema is its whole effect;
 * - one that also changes rows is refused, naming it: its INSERT may not
 *   have run;
 * - one whose result is its start is refused: the schema cannot show that it
 *   ran;
 * - one stopped before its first change is refused when it runs outside a
 *   transaction, and on MySQL, and runs again in a transaction on PostgreSQL
 *   and SQLite, where a stopped run left nothing.
 *
 * The modules are generated by the real generator from the DSL.
 */
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { buildExtensionSchema } from "../../../domains/schema/extension/build-extension-schema";
import { col, defineTable } from "../../../domains/schema/extension/dsl";
import { getSchemaEventsDdl } from "../../../domains/schema/events/schema-events-ddl";
import { SchemaEventsRepository } from "../../../domains/schema/events/schema-events-repository";
import { buildPluginMigration } from "../../../domains/schema/migrate-create/generate-plugin";
import {
  migrationChecksum,
  pluginModuleStatements,
  type PluginMigration,
} from "../../../domains/schema/migrate/plugin/plugin-migration";
import {
  createTestNextly,
  getConfiguredTestDialects,
  type TestNextly,
} from "../../../plugins/test-nextly";
import { CORE_TABLE_NAMES } from "../../../schemas/index";
import { createLogger } from "../../utils/logger";
import { runPluginPhase } from "../migrate";

const ALL = ["postgresql", "mysql", "sqlite"] as const;
const PLUGIN = "nsr";
const TABLE = `${PLUGIN}__notes`;

/** The plugin's first module, creating its table, as the generator writes it. */
async function createNotes(): Promise<PluginMigration> {
  const notes = defineTable("notes", { id: col.id(), label: col.shortText() });
  const tablesByDialect = {} as Parameters<
    typeof buildPluginMigration
  >[0]["tablesByDialect"];
  for (const dialect of ALL) {
    const built = await buildExtensionSchema({
      dialect,
      coreTableNames: CORE_TABLE_NAMES,
      entities: [],
      pluginPrefixes: new Map([[PLUGIN, PLUGIN]]),
      plugins: [{ owner: { kind: "plugin", id: PLUGIN }, tables: [notes] }],
    });
    tablesByDialect[dialect] = built.specs;
  }
  const built = buildPluginMigration({
    pluginName: PLUGIN,
    schemaVersion: 1,
    name: "notes",
    now: new Date(Date.UTC(2026, 9, 1, 10, 0, 0)),
    tablesByDialect,
    existing: [],
  });
  if (!built) throw new Error("no module generated");
  return built.module;
}

/** `base` resealed with other statements, and outside a transaction if asked. */
function variant(
  base: PluginMigration,
  over: {
    name?: string;
    up?: (dialect: (typeof ALL)[number]) => string[];
    outside?: boolean;
    sides?: Pick<PluginMigration, "before" | "snapshot">;
  }
): PluginMigration {
  const { checksum: _generated, ...content } = base;
  const next = {
    ...content,
    ...(over.name === undefined ? {} : { name: over.name }),
    ...(over.sides ?? {}),
    ...(over.outside === true ? { transaction: false } : {}),
    dialects: Object.fromEntries(
      ALL.map(dialect => [
        dialect,
        {
          up: over.up?.(dialect) ?? base.dialects[dialect].up,
          down: base.dialects[dialect].down,
        },
      ])
    ) as PluginMigration["dialects"],
  };
  return { ...next, checksum: migrationChecksum(next) };
}

describe.each(getConfiguredTestDialects())(
  "a plugin module whose run stopped (%s)",
  dialect => {
    let handle: TestNextly;

    beforeEach(async () => {
      handle = await createTestNextly(dialect === "sqlite" ? {} : { dialect });
      if (!(await handle.adapter.tableExists("nextly_schema_events"))) {
        for (const statement of getSchemaEventsDdl(dialect)) {
          await handle.adapter.executeQuery(statement);
        }
      }
    });

    afterEach(async () => {
      await handle?.adapter.executeQuery(`DROP TABLE IF EXISTS ${TABLE}`);
      await handle?.destroy();
    });

    const repo = () =>
      new SchemaEventsRepository(handle.adapter.getDrizzle(), dialect);
    const key = (module: PluginMigration) => `plugin:${PLUGIN}/${module.name}`;

    /** The newest ledger status of a module. */
    async function newestStatus(module: PluginMigration): Promise<string> {
      const rows = await repo().findFileApplies(key(module));
      const newest = [...rows].sort(
        (a, b) => +new Date(b.startedAt) - +new Date(a.startedAt)
      )[0];
      return newest?.status ?? "none";
    }

    /**
     * The state a process killed during the module's run leaves: its attempt
     * started and never finished, and — when `committed` — its statements
     * run and kept, as MySQL keeps them, or as a module run outside a
     * transaction does.
     */
    async function stopped(
      module: PluginMigration,
      committed: boolean
    ): Promise<void> {
      if (committed) {
        for (const statement of pluginModuleStatements(module, dialect, "up")) {
          await handle.adapter.executeQuery(statement);
        }
      }
      await repo().recordStart({
        eventType: "file_apply",
        source: "cli-migrate",
        filename: key(module),
        sha256: module.checksum,
      });
    }

    function migrate(migrations: PluginMigration[]) {
      return runPluginPhase({
        extensionSchema: undefined,
        dialect,
        db: handle.adapter.getDrizzle(),
        adapter: handle.adapter as unknown as Parameters<
          typeof runPluginPhase
        >[0]["adapter"],
        migrationsDir: "unused",
        logger: createLogger({ quiet: true }),
        pluginMigrationSets: [
          { pluginName: PLUGIN, pluginVersion: "1.0.0", migrations },
        ],
      });
    }

    async function rows(): Promise<string[]> {
      const found = (await handle.adapter.executeQuery(
        `SELECT id FROM ${TABLE}`
      )) as Array<{ id: string }>;
      return found.map(row => row.id);
    }

    it("records a module that changes only the schema, stopped after its statements committed, without running it again", async () => {
      const module = variant(await createNotes(), { outside: true });
      await stopped(module, true);

      await expect(migrate([module])).resolves.toMatchObject({
        applied: 0,
        adopted: 1,
      });
      expect(await newestStatus(module)).toBe("applied");
      expect(await handle.adapter.tableExists(TABLE)).toBe(true);
    });

    it("refuses a module that also changes rows, stopped after its statements committed, naming it", async () => {
      const notes = await createNotes();
      const module = variant(notes, {
        outside: true,
        up: d => [
          ...notes.dialects[d].up,
          `INSERT INTO ${TABLE} (id, label) VALUES ('seed', 'Seed')`,
        ],
      });
      await stopped(module, true);

      await expect(migrate([module])).rejects.toMatchObject({
        code: "NEXTLY_MIGRATION_PARTIALLY_APPLIED",
        logContext: { source: key(module) },
      });
      expect(await newestStatus(module)).toBe("in_progress");
      // Neither recorded nor run again: the seed is there once.
      expect(await rows()).toEqual(["seed"]);
    });

    it("refuses a module whose result is its start, stopped after its statements committed, naming it", async () => {
      const notes = await createNotes();
      await migrate([notes]);
      // Creates an index and drops it again: no snapshot can show it ran.
      const rebuilt = variant(notes, {
        name: "20261002_100000_000_rebuild",
        outside: true,
        sides: { before: notes.snapshot, snapshot: notes.snapshot },
        up: d => [
          `CREATE INDEX nsr_tmp ON ${TABLE} (label)`,
          d === "mysql"
            ? `DROP INDEX nsr_tmp ON ${TABLE}`
            : "DROP INDEX nsr_tmp",
        ],
      });
      await stopped(rebuilt, true);

      await expect(migrate([notes, rebuilt])).rejects.toMatchObject({
        code: "NEXTLY_MIGRATION_PARTIALLY_APPLIED",
        logContext: { source: key(rebuilt) },
      });
      expect(await newestStatus(rebuilt)).toBe("in_progress");
    });

    it("refuses a module run outside a transaction stopped before its first change, naming it", async () => {
      const module = variant(await createNotes(), { outside: true });
      await stopped(module, false);

      await expect(migrate([module])).rejects.toMatchObject({
        code: "NEXTLY_MIGRATION_PARTIALLY_APPLIED",
        logContext: { source: key(module) },
      });
      expect(await handle.adapter.tableExists(TABLE)).toBe(false);
    });

    it("runs again a module run in a transaction stopped before its first change, except on MySQL", async () => {
      const module = await createNotes();
      await stopped(module, false);

      if (dialect === "mysql") {
        // MySQL commits schema statements as they run, so the attempt may
        // have left some of them: refused, as one run outside a transaction.
        await expect(migrate([module])).rejects.toMatchObject({
          code: "NEXTLY_MIGRATION_PARTIALLY_APPLIED",
          logContext: { source: key(module) },
        });
        expect(await handle.adapter.tableExists(TABLE)).toBe(false);
        return;
      }
      await expect(migrate([module])).resolves.toMatchObject({ applied: 1 });
      expect(await newestStatus(module)).toBe("applied");
      expect(await handle.adapter.tableExists(TABLE)).toBe(true);
    });

    it.runIf(dialect === "mysql")(
      "records on MySQL a module run in a transaction that changes only the schema, stopped after its statements committed",
      async () => {
        const module = await createNotes();
        await stopped(module, true);

        await expect(migrate([module])).resolves.toMatchObject({
          applied: 0,
          adopted: 1,
        });
        expect(await newestStatus(module)).toBe("applied");
      }
    );
  }
);
