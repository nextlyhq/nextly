/**
 * A plugin's hand-written rename, applied by the plugin phase on every
 * configured dialect.
 *
 * The generator refuses to write a rename — its diff reads one as a drop and
 * a create, and writing it would lose the table's rows — and offers a blank
 * module that records the declared change for SQL the author writes
 * (`migrate:create --plugin --blank`). What only a database can prove is the
 * point of that refusal: the module's RENAME applies, the rows the table
 * already held are still there under the new name, and the ledger and the
 * owner registry record the module against the new name.
 *
 * Each case reads the outcome back from the database — the tables, their
 * columns, the rows, the ledger and the owner registry — rather than from
 * what the phase returned.
 */
import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { buildExtensionSchema } from "../../../domains/schema/extension/build-extension-schema";
import { col, defineTable } from "../../../domains/schema/extension/dsl";
import { getSchemaEventsDdl } from "../../../domains/schema/events/schema-events-ddl";
import { SchemaEventsRepository } from "../../../domains/schema/events/schema-events-repository";
import {
  buildBlankPluginMigration,
  buildPluginMigration,
} from "../../../domains/schema/migrate-create/generate-plugin";
import {
  compareModuleNames,
  migrationChecksum,
  type PluginMigration,
} from "../../../domains/schema/migrate/plugin/plugin-migration";
import { SchemaOwnersRepository } from "../../../domains/schema/ownership/schema-owners-repository";
import {
  createTestNextly,
  getConfiguredTestDialects,
  type TestNextly,
} from "../../../plugins/test-nextly";
import { CORE_TABLE_NAMES } from "../../../schemas/index";
import { createLogger } from "../../utils/logger";
import { runPluginPhase } from "../migrate";

const ALL = ["postgresql", "mysql", "sqlite"] as const;
type Dialect = (typeof ALL)[number];

/** The plugin's table as its first module declares it. */
const clients = defineTable("clients", {
  id: col.id(),
  label: col.shortText({ nullable: true }),
});
/** The same table under the name a later declaration renames it to. */
const customers = defineTable("customers", {
  id: col.id(),
  label: col.shortText({ nullable: true }),
});
/** The same table with one column renamed instead. */
const notedEvents = defineTable("events", {
  id: col.id(),
  note: col.shortText({ nullable: true }),
});
const titledEvents = defineTable("events", {
  id: col.id(),
  title: col.shortText({ nullable: true }),
});

/** The plugin's declared tables, compiled per dialect by the real builder. */
async function tablesByDialect(
  plugin: string,
  defs: ReturnType<typeof defineTable>[]
) {
  const out = {} as Parameters<
    typeof buildPluginMigration
  >[0]["tablesByDialect"];
  for (const dialect of ALL) {
    const built = await buildExtensionSchema({
      dialect,
      coreTableNames: CORE_TABLE_NAMES,
      entities: [],
      pluginPrefixes: new Map([[plugin, plugin]]),
      plugins: [{ owner: { kind: "plugin", id: plugin }, tables: defs }],
    });
    out[dialect] = built.specs;
  }
  return out;
}

/** The plugin's first module, generated by the real generator. */
async function firstModule(
  plugin: string,
  defs: ReturnType<typeof defineTable>[]
): Promise<PluginMigration> {
  const built = buildPluginMigration({
    pluginName: plugin,
    schemaVersion: 1,
    name: "v1",
    now: new Date(Date.UTC(2026, 10, 10, 10, 0, 0)),
    tablesByDialect: await tablesByDialect(plugin, defs),
    existing: [],
  });
  if (!built) throw new Error(`no module generated for ${plugin}`);
  return built.module;
}

/** A blank module with the author's SQL in place of its empty lists. */
function written(
  blank: PluginMigration,
  sql: (dialect: Dialect) => { up: string[]; down: string[] }
): PluginMigration {
  const { checksum: _sealed, ...content } = blank;
  for (const dialect of ALL) {
    content.dialects = { ...content.dialects, [dialect]: sql(dialect) };
  }
  return { ...content, checksum: migrationChecksum(content) };
}

/** `name` quoted as `dialect` quotes a name. */
function quoted(dialect: Dialect, name: string): string {
  return dialect === "mysql" ? `\`${name}\`` : `"${name}"`;
}

describe.each(getConfiguredTestDialects())(
  "a plugin's hand-written rename (%s)",
  dialect => {
    let handle: TestNextly;

    beforeAll(async () => {
      handle = await createTestNextly(dialect === "sqlite" ? {} : { dialect });
      if (!(await handle.adapter.tableExists("nextly_schema_events"))) {
        for (const statement of getSchemaEventsDdl(dialect)) {
          await handle.adapter.executeQuery(statement);
        }
      }
    });

    afterAll(async () => {
      await handle?.destroy();
    });

    function runPhase(plugin: string, migrations: PluginMigration[]) {
      return runPluginPhase({
        extensionSchema: undefined,
        dialect,
        db: handle.adapter.getDrizzle(),
        adapter: handle.adapter as unknown as Parameters<
          typeof runPluginPhase
        >[0]["adapter"],
        migrationsDir: "unused",
        logger: createLogger({ quiet: true }),
        pluginMigrationSets: [
          { pluginName: plugin, pluginVersion: "1.0.0", migrations },
        ],
      });
    }

    function owners() {
      return new SchemaOwnersRepository(handle.adapter.getDrizzle(), dialect);
    }

    // In the plugin's run order: the ledger is read unordered, and rows of
    // one run can share a start time at the server's timestamp precision.
    async function ledgerFor(plugin: string) {
      const prefix = `plugin:${plugin}/`;
      return (
        await new SchemaEventsRepository(
          handle.adapter.getDrizzle(),
          dialect
        ).listFileApplies()
      )
        .filter(row => (row.filename ?? "").startsWith(prefix))
        .sort((a, b) =>
          compareModuleNames(
            (a.filename ?? "").slice(prefix.length),
            (b.filename ?? "").slice(prefix.length)
          )
        );
    }

    async function columnsOf(table: string): Promise<string[]> {
      const rows = (await handle.adapter.executeQuery(
        dialect === "sqlite"
          ? `SELECT name FROM pragma_table_info('${table}')`
          : `SELECT column_name AS name FROM information_schema.columns WHERE table_name = '${table}'${dialect === "mysql" ? " AND table_schema = DATABASE()" : ""}`
      )) as Array<Record<string, unknown>>;
      return rows.map(row => String(row.name ?? row.NAME)).sort();
    }

    it("renames a table, and the rows move with it", async () => {
      const plugin = "rnt";
      const v1 = await firstModule(plugin, [clients]);
      await runPhase(plugin, [v1]);
      await handle.adapter.executeQuery(
        `INSERT INTO ${quoted(dialect, "rnt__clients")} (id, label) VALUES ('c1', 'first'), ('c2', 'second')`
      );

      // Generated, the rename reads as a drop and a create, and generation
      // refuses it — the rename is the author's to write.
      const renamed = await tablesByDialect(plugin, [customers]);
      expect(() =>
        buildPluginMigration({
          pluginName: plugin,
          schemaVersion: 2,
          name: "rename_clients",
          now: new Date(Date.UTC(2026, 10, 10, 11, 0, 0)),
          tablesByDialect: renamed,
          existing: [v1],
        })
      ).toThrow(
        expect.objectContaining({
          code: "PLUGIN_MIGRATION_DROPS_CREATED_SCHEMA",
        })
      );

      const blank = buildBlankPluginMigration({
        pluginName: plugin,
        schemaVersion: 2,
        name: "rename_clients",
        now: new Date(Date.UTC(2026, 10, 10, 11, 0, 0)),
        tablesByDialect: renamed,
        existing: [v1],
      });
      const rename = written(blank, d => ({
        up: [
          `ALTER TABLE ${quoted(d, "rnt__clients")} RENAME TO ${quoted(d, "rnt__customers")}`,
        ],
        down: [
          `ALTER TABLE ${quoted(d, "rnt__customers")} RENAME TO ${quoted(d, "rnt__clients")}`,
        ],
      }));

      const outcome = await runPhase(plugin, [v1, rename]);
      expect(outcome).toMatchObject({ applied: 1, adopted: 0, skipped: 1 });

      // The rename ran as a rename: one table gone, the other holding every
      // row the first one had.
      expect(await handle.adapter.tableExists("rnt__clients")).toBe(false);
      expect(await handle.adapter.tableExists("rnt__customers")).toBe(true);
      expect(
        await handle.adapter.executeQuery(
          `SELECT id, label FROM ${quoted(dialect, "rnt__customers")} ORDER BY id`
        )
      ).toEqual([
        { id: "c1", label: "first" },
        { id: "c2", label: "second" },
      ]);

      expect((await ledgerFor(plugin)).map(row => row.filename)).toEqual([
        `plugin:rnt/${v1.name}`,
        `plugin:rnt/${rename.name}`,
      ]);
      const owner = (await owners().read(["rnt__customers"])).find(
        record => (record.elementKind ?? "table") === "table"
      );
      expect(owner?.ownerId).toBe(plugin);
    });

    it("renames a column, and the rows keep their values", async () => {
      const plugin = "rnc";
      const v1 = await firstModule(plugin, [notedEvents]);
      await runPhase(plugin, [v1]);
      await handle.adapter.executeQuery(
        `INSERT INTO ${quoted(dialect, "rnc__events")} (id, note) VALUES ('e1', 'first'), ('e2', 'second')`
      );

      const renamed = await tablesByDialect(plugin, [titledEvents]);
      expect(() =>
        buildPluginMigration({
          pluginName: plugin,
          schemaVersion: 2,
          name: "rename_note",
          now: new Date(Date.UTC(2026, 10, 10, 11, 0, 0)),
          tablesByDialect: renamed,
          existing: [v1],
        })
      ).toThrow(
        expect.objectContaining({
          code: "PLUGIN_MIGRATION_DROPS_CREATED_SCHEMA",
        })
      );

      const blank = buildBlankPluginMigration({
        pluginName: plugin,
        schemaVersion: 2,
        name: "rename_note",
        now: new Date(Date.UTC(2026, 10, 10, 11, 0, 0)),
        tablesByDialect: renamed,
        existing: [v1],
      });
      const rename = written(blank, d => ({
        up: [
          `ALTER TABLE ${quoted(d, "rnc__events")} RENAME COLUMN ${quoted(d, "note")} TO ${quoted(d, "title")}`,
        ],
        down: [
          `ALTER TABLE ${quoted(d, "rnc__events")} RENAME COLUMN ${quoted(d, "title")} TO ${quoted(d, "note")}`,
        ],
      }));

      const outcome = await runPhase(plugin, [v1, rename]);
      expect(outcome).toMatchObject({ applied: 1, adopted: 0, skipped: 1 });

      // A rename, not an add: the old name is gone, and the rows carry their
      // values under the new one.
      expect(await columnsOf("rnc__events")).toEqual(["id", "title"]);
      expect(
        await handle.adapter.executeQuery(
          `SELECT id, title FROM ${quoted(dialect, "rnc__events")} ORDER BY id`
        )
      ).toEqual([
        { id: "e1", title: "first" },
        { id: "e2", title: "second" },
      ]);

      expect((await ledgerFor(plugin)).map(row => row.filename)).toEqual([
        `plugin:rnc/${v1.name}`,
        `plugin:rnc/${rename.name}`,
      ]);
    });
  }
);
