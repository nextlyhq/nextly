/**
 * Where `generate:types` writes when a project sets no path, and what happens
 * to the file the old default named.
 *
 * The default file is named for Nextly. A project that left the setting out
 * still has the `payload-types.ts` an earlier version wrote; both files would
 * augment `GeneratedTypes`, which TypeScript refuses once they differ, so the
 * old one becomes a re-export of the new one and the run says so.
 *
 * Driven through `runGenerateTypes` itself, with only the config loader
 * replaced, so the path the command resolves is part of what is tested.
 */
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { Command } from "commander";
import { afterEach, describe, expect, it, vi } from "vitest";

import { DEFAULT_TYPESCRIPT_CONFIG } from "../../../shared/types/config";

const loadConfig = vi.hoisted(() => vi.fn());
vi.mock("../../utils/config-loader", () => ({ loadConfig }));

const { runGenerateTypes, registerGenerateTypesCommand } = await import(
  "../generate-types"
);
const { createContext } = await import("../../program");

const dirs: string[] = [];

afterEach(async () => {
  loadConfig.mockReset();
  await Promise.all(
    dirs.splice(0).map(dir => rm(dir, { recursive: true, force: true }))
  );
});

/** An app under src/ whose config leaves the types path at its default. */
async function appWithDefaultPath(): Promise<string> {
  const cwd = await mkdtemp(join(tmpdir(), "nextly-types-default-"));
  dirs.push(cwd);
  await mkdir(join(cwd, "src/app"), { recursive: true });
  loadConfig.mockResolvedValue({
    configPath: "nextly.config.ts",
    config: {
      collections: [],
      singles: [],
      fieldGroups: [],
      users: { fields: [{ name: "nickname", type: "text" }] },
      plugins: [],
      typescript: { ...DEFAULT_TYPESCRIPT_CONFIG },
      db: { schemasDir: "./src/db/schemas/collections" },
    },
  });
  return cwd;
}

const generatedDir = (cwd: string) => join(cwd, "src/types/generated");

describe("generate:types with no types path set", () => {
  it("writes nextly-types.ts", async () => {
    const cwd = await appWithDefaultPath();

    await runGenerateTypes(
      { cwd, quiet: true, zod: false },
      createContext({ quiet: true, cwd })
    );

    const written = await readFile(
      join(generatedDir(cwd), "nextly-types.ts"),
      "utf-8"
    );
    expect(written).toContain(
      "This file was automatically generated by Nextly."
    );
  });

  it("turns the payload-types.ts it wrote before into a re-export, and says it moved", async () => {
    const cwd = await appWithDefaultPath();
    await mkdir(generatedDir(cwd), { recursive: true });
    await writeFile(
      join(generatedDir(cwd), "payload-types.ts"),
      "/**\n * This file was automatically generated by Nextly.\n */\n" +
        'declare module "nextly" {\n  export interface GeneratedTypes extends Config {}\n}\n'
    );
    const context = createContext({ quiet: true, cwd });
    const warn = vi.spyOn(context.logger, "warn");

    await runGenerateTypes({ cwd, quiet: true, zod: false }, context);

    const old = await readFile(
      join(generatedDir(cwd), "payload-types.ts"),
      "utf-8"
    );
    expect(old).toContain('export * from "./nextly-types.js";');
    expect(old).not.toContain("declare module");
    await expect(
      readFile(join(generatedDir(cwd), "nextly-types.ts"), "utf-8")
    ).resolves.toContain("declare module");
    expect(warn.mock.calls.flat().join("\n")).toContain("payload-types.ts");
  });
});

describe("generate:types --help", () => {
  it("names the default types file", () => {
    const program = new Command();
    registerGenerateTypesCommand(program);
    const command = program.commands.find(c => c.name() === "generate:types");

    expect(command?.helpInformation()).toContain(
      DEFAULT_TYPESCRIPT_CONFIG.outputFile
    );
    expect(DEFAULT_TYPESCRIPT_CONFIG.outputFile).toMatch(/\/nextly-types\.ts$/);
  });
});
