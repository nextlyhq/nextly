const ALL = ["postgresql", "mysql", "sqlite"] as const;
const PLUGIN = "btp";
/** A table of no plugin's, which the part-way module creates before it meets the held one. */
const OTHER = "btp_other";

const quiet = createLogger({ quiet: true });

/** The consent a rollback dropping the module's column takes. */
const CONSENT: DataLossConsent = {
  given: { from: "flag", targets: "all" },
  earlier: [],
  ignored: [],
};

/** The plugin's tables compiled for every dialect by the real builder. */
async function tablesByDialect(
  tables: ReturnType<typeof defineTable>[]
): Promise<Parameters<typeof buildPluginMigration>[0]["tablesByDialect"]> {
  const out = {} as Parameters<
    typeof buildPluginMigration
  >[0]["tablesByDialect"];
  for (const dialect of ALL) {
    const built = await buildExtensionSchema({
      dialect,
      coreTableNames: CORE_TABLE_NAMES,
      entities: [],
      pluginPrefixes: new Map([[PLUGIN, PLUGIN]]),
      plugins: [{ owner: { kind: "plugin", id: PLUGIN }, tables }],
    });
    out[dialect] = built.specs;
  }
  return out;
}

/**
 * The plugin's two modules, generated by the real generator: the first creates its `notes` table,
 * the second adds a column to it, which waits while the table is held.
 */
async function generatedModules(): Promise<{
  create: PluginMigration;
  addColumn: PluginMigration;
}> {
  const notes = defineTable("notes", {
    id: col.id(),
    label: col.shortText(),
  });
  const withExtra = defineTable("notes", {
    id: col.id(),
    label: col.shortText(),
    extra: col.shortText({ nullable: true }),
  });
  const create = buildPluginMigration({
    pluginName: PLUGIN,
    schemaVersion: 1,
    name: "notes",
    now: new Date(Date.UTC(2026, 10, 13, 10, 0, 0)),
    tablesByDialect: await tablesByDialect([notes]),
    existing: [],
  });
  if (create === null) throw new Error("no first module generated");
  const addColumn = buildPluginMigration({
    pluginName: PLUGIN,
    schemaVersion: 2,
    name: "extra",
    now: new Date(Date.UTC(2026, 10, 13, 10, 0, 1)),
    tablesByDialect: await tablesByDialect([withExtra]),
    existing: [create.module],
  });
  if (addColumn === null) throw new Error("no second module generated");
  return { create: create.module, addColumn: addColumn.module };
}

/**
 * `module` with `first` run before its own statements, sealed again; outside a transaction unless
 * `inTransaction`.
 */
function withFirstStatement(
  module: PluginMigration,
  first: string,
  inTransaction: boolean
): PluginMigration {
  const { checksum: _sealed, transaction: _mode, ...rest } = module;
  const content = {
    ...rest,
    ...(inTransaction ? {} : { transaction: false as const }),
    dialects: Object.fromEntries(
      ALL.map(dialect => [
        dialect,
        {
          up: [first, ...module.dialects[dialect].up],
          down: module.dialects[dialect].down,
        },
      ])
    ) as PluginMigration["dialects"],
  };
  return { ...content, checksum: migrationChecksum(content) };
}

let modules: Awaited<ReturnType<typeof generatedModules>>;

beforeAll(async () => {
  modules = await generatedModules();
});

describe.each(LOCK_DIALECTS)(
  "a plugin module meeting a busy table on %s",
  dialect => {
    let world: LockWorld;
    let adapter: DrizzleAdapter;
    let holderAdapter: DrizzleAdapter;
    let free: () => void = () => {};
    let holding: Promise<unknown> = Promise.resolve();
    let notices: string[];

    /** The plugin's table, as the generated module names it on this dialect. */
    const notesTable = (): string => {
      const name = modules.create.snapshot[dialect]?.tables[0]?.name;
      if (name === undefined) throw new Error("the module names no table");
      return name;
    };

    beforeEach(async () => {
      world = await lockWorld(dialect, { fresh: true });
      adapter = await world.connect({ poolMax: 6 });
      holderAdapter = await world.connect({ poolMax: 2 });
      // The owner registry from its own definition, pushed as `nextly migrate`'s core push makes
      // it, before anything else is on the database for the push to weigh.
      await freshPushSchema(dialect, adapter.getDrizzle(), {
        ...schemaOwnersTables(dialect),
      });
      for (const statement of getSchemaEventsDdl(dialect)) {
        await adapter.executeQuery(statement);
      }
      notices = [];
    });

    afterEach(async () => {
      // A spy on a prototype would reach the next test's runs.
      vi.restoreAllMocks();
      free();
      await holding.catch(() => {});
      await holderAdapter.disconnect();
      await adapter.disconnect();
      await world.dispose();
    });

    /**
     * The second session holds the plugin's table until `free()`: on PostgreSQL and MySQL an open
     * transaction that has read it, on SQLite an open write transaction.
     */
    async function holdTheTable(): Promise<void> {
      let held: () => void = () => {};
      const isHeld = new Promise<void>(resolve => {
        held = resolve;
      });
      const freed = new Promise<void>(resolve => {
        free = resolve;
      });
      const table = notesTable();
      holding = holderAdapter.transaction(async ctx => {
        await ctx.queryStatement(
          dialect === "sqlite"
            ? sql.raw(
                `INSERT INTO ${table} (id, label) VALUES ('held', 'held') RETURNING id`
              )
            : sql.raw(`SELECT id FROM ${table}`)
        );
        held();
        await freed;
      });
      await isHeld;
    }

    /**
     * Holds the table for the module recorded as `filename`: on the servers now, on SQLite once
     * the module's attempt is recorded, since the holder holds the whole database there.
     * `onHeld` runs once the hold starts.
     */
    async function holdForModule(
      filename: string,
      onHeld: () => void = () => {}
    ): Promise<void> {
      if (dialect !== "sqlite") {
        await holdTheTable();
        onHeld();
        return;
      }
      const recordStart = SchemaEventsRepository.prototype.recordStart;
      let started = false;
      vi.spyOn(
        SchemaEventsRepository.prototype,
        "recordStart"
      ).mockImplementation(async function (
        this: SchemaEventsRepository,
        input
      ) {
        const id = await recordStart.call(this, input);
        if (!started && input.filename === filename) {
          started = true;
          await holdTheTable();
          onHeld();
        }
        return id;
      });
    }

    /**
     * Holds the table once the statement starting `prefix` has run: on SQLite, whose holder holds
     * the whole database, the hold starts only then (statements outside a transaction run through
     * the adapter one at a time); on the servers it starts now.
     */
    async function holdAfter(prefix: string): Promise<void> {
      if (dialect !== "sqlite") {
        await holdTheTable();
        return;
      }
      const run = adapter.executeQuery.bind(adapter);
      vi.spyOn(adapter, "executeQuery").mockImplementation(
        async (statement, params) => {
          const rows = await run(statement, params);
          if (statement.startsWith(prefix)) await holdTheTable();
          return rows;
        }
      );
    }

    /** The plugin phase over `migrations`, with `bounds`, each try's notice kept. */
    function migratePlugin(
      migrations: PluginMigration[],
      bounds: BusyTableBounds
    ) {
      return runPluginPhase({
        extensionSchema: undefined,
        dialect,
        db: adapter.getDrizzle(),
        adapter: adapter as unknown as Parameters<
          typeof runPluginPhase
        >[0]["adapter"],
        migrationsDir: "unused",
        logger: quiet,
        pluginMigrationSets: [
          { pluginName: PLUGIN, pluginVersion: "1.0.0", migrations },
        ],
        busyTable: { bounds, notify: line => notices.push(line) },
      });
    }

    async function columnsOf(table: string): Promise<string[]> {
      const rows = await adapter.executeQuery<{ name: string }>(
        dialect === "sqlite"
          ? `SELECT name FROM pragma_table_info('${table}')`
          : dialect === "mysql"
            ? `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = '${table}'`
            : `SELECT column_name AS name FROM information_schema.columns WHERE table_name = '${table}'`
      );
      return rows.map(row => row.name).sort();
    }

    /** A module's `file_apply` statuses, oldest first. */
    async function statuses(filename: string): Promise<string[]> {
      const repo = new SchemaEventsRepository(adapter.getDrizzle(), dialect);
      const rows = await repo.findFileApplies(filename);
      return [...rows]
        .sort((a, b) => +new Date(a.startedAt) - +new Date(b.startedAt))
        .map(row => row.status);
    }

    const ADD_COLUMN = () => qualifiedFilename(PLUGIN, modules.addColumn.name);

    it("applies a module once when the holder ends during the second pause", async () => {
      await migratePlugin([modules.create], { tryMs: 1_000, totalMs: 20_000 });
      let freeing: Promise<void> = Promise.resolve();
      // Tries at 0, 2 and 5 seconds: the second pause runs from 3 to 5.
      await holdForModule(ADD_COLUMN(), () => {
        freeing = sleep(3_500).then(() => free());
      });

      const outcome = await migratePlugin([modules.create, modules.addColumn], {
        tryMs: 1_000,
        totalMs: 20_000,
      });
      await freeing;

      expect(outcome).toMatchObject({ applied: 1, skipped: 1 });
      expect(notices).toHaveLength(2);
      expect(await columnsOf(notesTable())).toEqual(["extra", "id", "label"]);
      expect(await statuses(ADD_COLUMN())).toEqual(["applied"]);
    });

    it("names the plugin modules the run applied before an app file a busy table stops", async () => {
      const bounds = { tryMs: 1_000, totalMs: 3_000 };
      const outcome = await migratePlugin([modules.create], bounds);
      expect(outcome.ran).toHaveLength(1);
      expect(outcome.ran[0]).toContain(modules.create.name);

      const dir = mkdtempSync(join(tmpdir(), "nextly-btp-app-"));
      try {
        mkdirSync(join(dir, "migrations"));
        writeFileSync(
          join(dir, "migrations", "20261113_000001_000_btp_app.sql"),
          `-- Migration: btp_app\n\n-- UP\nALTER TABLE ${notesTable()} ADD COLUMN app_col integer;\n\n-- DOWN\n`
        );
        await holdTheTable();
        const stopped = await runFileMigrations({
          adapter: adapter as unknown as Parameters<
            typeof runFileMigrations
          >[0]["adapter"],
          db: adapter.getDrizzle(),
          dialect,
          migrationsDir: join(dir, "migrations"),
          logger: quiet,
          busyTable: { bounds, notify: line => notices.push(line) },
          appliedBefore: outcome.ran,
        }).catch((error: unknown) => error);

        expect(stopped).toMatchObject({
          code: "NEXTLY_TABLE_BUSY",
          logContext: { stop: { appliedBefore: [...outcome.ran] } },
        });
        expect(String((stopped as Error).message)).toContain(outcome.ran[0]);
      } finally {
        rmSync(dir, { recursive: true, force: true });
      }
    });

    it("stops with the table busy and nothing changed, and the next run applies the module with no refusal", async () => {
      await migratePlugin([modules.create], { tryMs: 1_000, totalMs: 3_000 });
      await holdForModule(ADD_COLUMN());

      const stopped = await migratePlugin([modules.create, modules.addColumn], {
        tryMs: 1_000,
        totalMs: 3_000,
      }).catch((error: unknown) => error);

      expect(stopped).toMatchObject({
        code: "NEXTLY_TABLE_BUSY",
        logContext: { stop: { outcome: { kind: "nothing-changed" } } },
      });
      expect(String((stopped as Error).message)).toContain(ADD_COLUMN());
      expect(String((stopped as Error).message)).toContain("nothing changed");
      // A notice for every try but the last, whose end the stop reports.
      const { tries } = (stopped as { logContext: { stop: { tries: number } } })
        .logContext.stop;
      expect(notices).toHaveLength(tries - 1);
      expect(await columnsOf(notesTable())).toEqual(["id", "label"]);

      free();
      await holding;
      const next = await migratePlugin([modules.create, modules.addColumn], {
        tryMs: 1_000,
        totalMs: 3_000,
      });

      expect(next).toMatchObject({ applied: 1 });
      expect(await columnsOf(notesTable())).toEqual(["extra", "id", "label"]);
      // Ended with nothing applied, which resolves the attempt. On SQLite the holder still held
      // the whole database when the attempt ended, so its outcome could not be written; an
      // attempt left so in a transaction there is not refused, its failure having been undone
      // whole.
      expect(await statuses(ADD_COLUMN())).toEqual(
        dialect === "sqlite"
          ? ["in_progress", "applied"]
          : ["nothing_applied", "applied"]
      );
    });

    it(`stops a module part-way, naming the committed statement by position, and the next run refuses it by name (${dialect === "mysql" ? "in a transaction" : "outside a transaction"})`, async () => {
      await migratePlugin([modules.create], { tryMs: 1_000, totalMs: 3_000 });
      const createOther = `CREATE TABLE ${OTHER} (id integer)`;
      // MySQL commits a schema statement as it runs, so a module in a transaction stops
      // part-way there; elsewhere only a module run outside one does.
      const partWay = withFirstStatement(
        modules.addColumn,
        createOther,
        dialect === "mysql"
      );
      const filename = qualifiedFilename(PLUGIN, partWay.name);
      await holdAfter(createOther);

      const stopped = await migratePlugin([modules.create, partWay], {
        tryMs: 1_000,
        totalMs: 3_000,
      }).catch((error: unknown) => error);

      expect(stopped).toMatchObject({
        code: "NEXTLY_TABLE_BUSY",
        logContext: {
          stop: { outcome: { kind: "part-way", committed: [1] } },
        },
      });
      const message = String((stopped as Error).message);
      expect(message).toContain("Statement 1 had committed");
      // Named by position only: a statement's text can hold a literal value.
      expect(message).not.toMatch(/CREATE TABLE|ALTER|ADD COLUMN|btp_other/i);
      expect(await statuses(filename)).not.toContain("applied");
      expect(await columnsOf(notesTable())).toEqual(["id", "label"]);

      free();
      await holding;
      await expect(
        migratePlugin([modules.create, partWay], {
          tryMs: 1_000,
          totalMs: 3_000,
        })
      ).rejects.toMatchObject({
        code: "NEXTLY_MIGRATION_PARTIALLY_APPLIED",
        message: expect.stringContaining(filename) as unknown,
      });
      expect(await statuses(filename)).not.toContain("applied");
      await adapter.executeQuery(`DROP TABLE IF EXISTS ${OTHER}`);
    });

    it("stops migrate:down --plugin with the table busy", async () => {
      await migratePlugin([modules.create, modules.addColumn], {
        tryMs: 1_000,
        totalMs: 3_000,
      });
      await holdTheTable();

      const stopped = await migrateDownCore({
        ...(await downDatabaseDeps({
          adapter,
          dialect,
          plugin: {
            name: PLUGIN,
            migrations: [modules.create, modules.addColumn],
          },
          command: "migrate:down",
          busyTable: {
            bounds: { tryMs: 1_000, totalMs: 3_000 },
            notify: line => notices.push(line),
          },
        })),
        nodeEnv: "test",
        logger: quiet,
        options: {
          step: 1,
          consent: CONSENT,
          yes: false,
          dryRun: false,
          plugin: PLUGIN,
        },
        fileExists: () => Promise.resolve(true),
        readDownSql: filename =>
          Promise.resolve(
            pluginModuleDown({
              pluginName: PLUGIN,
              migrations: [modules.create, modules.addColumn],
              filename,
              recordedSha: modules.addColumn.checksum,
              dialect,
            })
          ),
        // The schema lock's row is a write, which SQLite's holder would keep waiting; the lock
        // and the tries together are covered by the lock's own suites.
        withLock: async (_adapter, _dialect, work) => ({
          ran: true as const,
          value: await work(),
        }),
      }).catch((error: unknown) => error);

      expect(stopped).toMatchObject({ code: "NEXTLY_TABLE_BUSY" });
      expect(String((stopped as Error).message)).toContain(ADD_COLUMN());
      expect(await columnsOf(notesTable())).toEqual(["extra", "id", "label"]);
    });
  },
  90_000
);
