/**
 * The sync service writes the generated types file too, so it reports the
 * `payload-types.ts` the old default left the same way `generate:types` does:
 * left as it is, with what to do about it, so a project synced before it ever
 * runs that command still hears that the old file clashes.
 */
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import type { DrizzleAdapter } from "@nextlyhq/adapter-drizzle";
import { afterEach, describe, expect, it, vi } from "vitest";

import { defineCollection } from "../../../../collections/config/define-collection";
import { text } from "../../../../collections/fields/helpers";
import type { Logger } from "../../../../services/shared";
import {
  DEFAULT_TYPESCRIPT_CONFIG,
  type SanitizedNextlyConfig,
} from "../../../../shared/types/config";
import { CollectionSyncService } from "../collection-sync-service";

const made: string[] = [];
afterEach(() => {
  for (const dir of made.splice(0))
    rmSync(dir, { recursive: true, force: true });
});

/** Type generation reads only the adapter's dialect; nothing touches a database. */
const adapter = {
  getCapabilities: () => ({ dialect: "sqlite" }),
} as unknown as DrizzleAdapter;

function logger(): Logger {
  return { debug: vi.fn(), info: vi.fn(), warn: vi.fn(), error: vi.fn() };
}

describe("CollectionSyncService.generateTypesOnly with no types path set", () => {
  it("leaves the old default's generated payload-types.ts as it is, and warns", async () => {
    const cwd = mkdtempSync(join(tmpdir(), "nextly-sync-types-"));
    made.push(cwd);
    const dir = join(cwd, "src/types/generated");
    mkdirSync(join(cwd, "src/app"), { recursive: true });
    mkdirSync(dir, { recursive: true });
    const generated =
      "/* tslint:disable */\n/* eslint-disable */\n/**\n * This file was automatically generated by Nextly.\n */\n";
    writeFileSync(join(dir, "payload-types.ts"), generated);
    const log = logger();
    const config = {
      collections: [
        defineCollection({ slug: "posts", fields: [text({ name: "title" })] }),
      ],
      typescript: { ...DEFAULT_TYPESCRIPT_CONFIG },
    } as unknown as SanitizedNextlyConfig;

    const written = await new CollectionSyncService(
      adapter,
      log
    ).generateTypesOnly(config, { cwd });

    expect(written).toBe(join(dir, "nextly-types.ts"));
    expect(readFileSync(join(dir, "payload-types.ts"), "utf-8")).toBe(
      generated
    );
    const said = vi.mocked(log.warn).mock.calls.flat().join("\n");
    expect(said).toContain("payload-types.ts");
    expect(said).toMatch(/delete/i);
  });
});
