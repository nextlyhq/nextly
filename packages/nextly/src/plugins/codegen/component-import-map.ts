/**
 * Admin component import map.
 *
 * Generates a TypeScript module that statically imports every plugin admin
 * component the admin can resolve by string — pages, settings and
 * per-collection views from `contributes.admin`, the header/schema-builder/
 * form-toolbar slots, and field-type editor components from
 * `contributes.fieldTypes` — and registers them via `registerComponents`.
 * Importing this generated module from the admin shell makes plugin React
 * components load with **no manual host imports** and **no run-once
 * dynamic-import race** (the P5 gap) — completing the string-path component
 * registry.
 *
 * Menu items carry only a route (`to`), not a component, so they contribute no
 * paths. A widget contributes one only where it SHIPS a component: the
 * declarative archetypes name an archetype and a query, and the host draws them
 * from the result, so there is no module to import.
 *
 * Pure — no IO. The CLI writes the returned string to a generated file.
 *
 * @module plugins/codegen/component-import-map
 */

import { dirname, join, relative, sep } from "node:path";

import type {
  ComponentPath,
  PluginAdminContributions,
} from "../admin-contributions";
import { pluginOwner } from "../dashboard-declarations";
import { collectDeclarations } from "../declarations";
import type { PluginDefinition } from "../plugin-context";

import { isPageBuilderActive, PAGE_BUILDER_PLUGIN } from "./block-manifest";

/** What a component in the map is for, as a fault about it names it. */
export type ComponentMapUse =
  | "widget"
  | "page"
  | "settings"
  | "collection view"
  | "document view"
  | "slot"
  | "field type"
  | "block editor"
  | "block editor entry";

/**
 * One component the generated map registers: its path, who declared it, and
 * what it is for. A widget's entry also names the widget, so a refusal can
 * say which card is affected.
 */
export interface ComponentMapEntry {
  readonly path: string;
  /** `plugin "<name>"`, as every widget fault names its owner. */
  readonly owner: string;
  readonly use: ComponentMapUse;
  /** The widget's id, for a `widget` entry. */
  readonly widget?: string;
}

/** Filename of the generated admin component import map. */
export const COMPONENT_IMPORT_MAP_FILENAME =
  "plugin-admin-imports.generated.ts";

const HEADER = [
  "/* AUTO-GENERATED by `nextly generate:types` — DO NOT EDIT.",
  " * Statically registers the plugin admin components the admin resolves by",
  " * string (pages, settings, views, slots, field-type editors) so they load",
  " * without manual host imports. */",
].join("\n");

/**
 * Header, schema-builder and form-toolbar slots. They render through the
 * same registry from surfaces the plugin does not own, so they need the
 * map's import as much as a page does.
 */
function collectAdminSlotPaths(admin: PluginAdminContributions): string[] {
  // `header.slot` supersedes the deprecated top-level spelling; both are
  // read exactly as admin-meta reads them.
  const headerSlot = admin.header?.slot ?? admin.headerSlot;
  return [
    headerSlot,
    admin.schemaBuilderSlot,
    admin.entryFormToolbarSlot,
  ].filter((path): path is ComponentPath => Boolean(path));
}

/**
 * Collect every admin `ComponentPath` a plugin contributes that the admin
 * can resolve by string: pages, settings, per-collection views, header and
 * schema-builder and form-toolbar slots, and field-type editor components.
 * Behavioral UI (everything but field types) exists only for an ENABLED
 * plugin; field-type editors are collected regardless, because a disabled
 * plugin keeps its collections and their fields — admin-meta serializes
 * their types for exactly that reason, and a retained field renders empty
 * without its editor module.
 *
 * The set must stay a superset of what `buildPluginAdminMeta` exposes: the
 * browser resolves each of those strings through the component registry, and
 * the generated map is the only guaranteed importer of the modules behind
 * them — the registry's runtime fallback cannot resolve a bare package
 * specifier in a bundled browser. The parity test beside this module fails
 * when admin-meta grows a path kind this collector has not learned.
 */
export function collectAdminComponentEntries(
  plugin: PluginDefinition
): ComponentMapEntry[] {
  // Field-type editor components live under `contributes` rather than
  // `contributes.admin` because that is where a type is declared, but they
  // are admin components in every other sense: the entry form resolves the
  // string through the same registry a page or settings view uses. A plugin
  // contributing only field types — the page builder, whose one component is
  // its blocks control — contributes no pages, settings or views, so without
  // this the generated map imports nothing of it and the field can only
  // render through a fallback that cannot fire.
  //
  // Collected for a DISABLED plugin too, where the block-editor collector
  // below drops everything once the page builder is disabled. The two rules
  // read as opposed and are not: a retained collection still renders its
  // fields, so their editors still mount and still need their modules, while
  // a block editor has no registry to land in once the page builder stops
  // booting, so importing one would pull in a bundle for a feature that
  // cannot run. Field types follow what still RENDERS; block editors follow
  // what still RUNS.
  const owner = pluginOwner(plugin);
  const fieldTypes = (plugin.contributes?.fieldTypes ?? []).map(fieldType =>
    entry(fieldType.component, owner, "field type")
  );

  if (plugin.enabled === false) return fieldTypes;
  return [
    ...fieldTypes,
    ...collectAdminEntries(plugin.contributes?.admin, owner),
    ...collectDeclaredWidgetEntries(plugin.contributes?.dashboard, owner),
  ];
}

/**
 * The paths alone, for the parity test against admin-meta and anything that
 * asks only which components exist. Derived from the entries, so the two
 * cannot list different components.
 */
export function collectAdminComponentPaths(plugin: PluginDefinition): string[] {
  return collectAdminComponentEntries(plugin).map(each => each.path);
}

const entry = (
  path: string,
  owner: string,
  use: ComponentMapUse
): ComponentMapEntry => ({ path, owner, use });

/** Every component an enabled plugin's `contributes.admin` names. */
function collectAdminEntries(
  admin: PluginAdminContributions | undefined,
  owner: string
): ComponentMapEntry[] {
  if (!admin) return [];
  const tagged = (use: ComponentMapUse) => (path: string) =>
    entry(path, owner, use);
  return [
    ...(admin.pages ?? []).map(page => entry(page.component, owner, "page")),
    ...(admin.settings
      ? [entry(admin.settings.component, owner, "settings")]
      : []),
    ...collectCollectionViewPaths(admin.views).map(tagged("collection view")),
    // Views offered wherever one of the plugin's field types is used.
    ...(admin.documentViews ?? []).map(view =>
      entry(view.component, owner, "document view")
    ),
    ...collectWidgetEntries(admin.widgets, owner),
    ...collectAdminSlotPaths(admin).map(tagged("slot")),
  ];
}

/**
 * The component each widget declared under `contributes.dashboard` draws
 * with, for the same reason as today's shape: the map is the only importer
 * the admin's registry can rely on. A widget drawn by one of core's views
 * ships no component.
 *
 * Read as plain JavaScript hands it over, since generation runs before
 * startup checks anything: an entry that names no component is skipped here
 * and refused by startup, by name, which is where a declaration's faults are
 * reported.
 */
function collectDeclaredWidgetEntries(
  dashboard: unknown,
  owner: string
): ComponentMapEntry[] {
  const widgets: unknown = isRecord(dashboard) ? dashboard.widgets : undefined;
  if (!Array.isArray(widgets)) return [];
  return widgets.flatMap((widget: unknown): ComponentMapEntry[] => {
    const view = isRecord(widget) ? widget.view : undefined;
    const component = isRecord(view) ? view.component : undefined;
    if (typeof component !== "string" || component.trim() === "") return [];
    const id = isRecord(widget) ? widget.id : undefined;
    return [
      {
        path: component,
        owner,
        use: "widget",
        ...(typeof id === "string" ? { widget: id } : {}),
      },
    ];
  });
}

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

/**
 * Every override and injection point a plugin declares per collection.
 *
 * Its own function rather than two nested loops inline, because the six slots
 * are one list and the enclosing collector already answers several unrelated
 * questions -- pages, settings, field types, header slots, widgets. Flattening
 * them all into one body is what pushed it past the complexity gate.
 */
function collectCollectionViewPaths(
  views: PluginAdminContributions["views"]
): string[] {
  const paths: string[] = [];
  for (const view of Object.values(views ?? {})) {
    for (const slot of [
      view.list,
      view.edit,
      view.beforeList,
      view.afterList,
      view.beforeEdit,
      view.afterEdit,
    ]) {
      if (slot) paths.push(slot);
    }
    // Each document view is a screen the admin resolves by this string too.
    for (const documentView of view.documentViews ?? []) {
      paths.push(documentView.component);
    }
  }
  return paths;
}

/**
 * Every widget component a plugin declares.
 *
 * Being pre-bundled by this map is what puts a component in the registry
 * `PluginSlot` reads; the registry's runtime fallback cannot resolve a bare
 * package specifier in a bundled browser. So while widgets were excluded here,
 * a `custom` widget drew its card and then nothing inside it, unless the plugin
 * called `registerComponents` itself from its admin entry -- which the
 * documented contract never asked it to do.
 */
function collectWidgetEntries(
  widgets: PluginAdminContributions["widgets"],
  owner: string
): ComponentMapEntry[] {
  // Optional now: a declarative widget names an archetype and a query and ships
  // no component at all, so only the ones that HAVE a path contribute one.
  return (widgets ?? []).flatMap((widget): ComponentMapEntry[] =>
    widget.component
      ? [{ path: widget.component, owner, use: "widget", widget: widget.id }]
      : []
  );
}

/**
 * Every editor component a declared block names.
 *
 * A block may supply its own inspector or canvas component through
 * `editor.component`, which is a `ComponentPath` like any admin contribution —
 * so the editor bundle can load it the same way, with no hand-written import.
 *
 * Read from declarations rather than from the block registry, for the reason
 * declarations exist: the registry is populated by `init`, and generation runs
 * no plugin. A block registered imperatively contributes no path here, exactly
 * as it contributes no manifest entry.
 *
 * Malformed declarations are skipped rather than refused. The manifest emitter
 * already validates them and fails generation loudly; repeating the check here
 * would report the same defect twice, and an import map is not the place a
 * schema error should surface.
 */
export function collectBlockEditorComponentPaths(
  plugins: readonly PluginDefinition[]
): string[] {
  return collectBlockEditorEntries(plugins)
    .filter(each => each.use === "block editor")
    .map(each => each.path);
}

/**
 * The block editors with who declared each, read as the paths above are, and
 * each declaration's `editorEntry`: the module exporting the declared block
 * definitions themselves, which is how the editor in the browser receives
 * them. The server registers a declaration at boot, in its own process, and
 * nothing a server registers reaches the admin's bundle; only an import the
 * bundler can see does.
 */
function collectBlockEditorEntries(
  plugins: readonly PluginDefinition[]
): ComponentMapEntry[] {
  const paths: ComponentMapEntry[] = [];
  // No page builder, no registry for these blocks to land in, so their editor
  // components would be imported eagerly for a feature that cannot run. The
  // manifest applies the same rule; disagreeing would describe two different
  // apps from one config.
  if (!isPageBuilderActive(plugins)) return paths;
  for (const declaration of collectDeclarations(plugins, PAGE_BUILDER_PLUGIN)) {
    const editorEntry = declaredEditorEntry(declaration.value);
    if (editorEntry !== undefined) {
      paths.push(
        entry(
          editorEntry,
          `plugin "${declaration.source}"`,
          "block editor entry"
        )
      );
    }
    for (const block of declaredBlocks(declaration.value)) {
      const component = blockEditorComponent(block);
      if (component !== undefined) {
        paths.push(
          entry(component, `plugin "${declaration.source}"`, "block editor")
        );
      }
    }
  }
  return paths;
}

/** The blocks a page-builder declaration lists, or none when it lists none. */
function declaredBlocks(value: unknown): readonly unknown[] {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return [];
  }
  const blocks = (value as { blocks?: unknown }).blocks;
  return Array.isArray(blocks) ? blocks : [];
}

/**
 * The `editorEntry` a page-builder declaration names, or `undefined`.
 *
 * Skipped rather than refused when malformed, as a block's editor component
 * is: the page builder refuses a malformed entry at boot, naming the plugin,
 * which is where a declaration's faults are reported.
 */
function declaredEditorEntry(value: unknown): string | undefined {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return undefined;
  }
  const editorEntry = (value as { editorEntry?: unknown }).editorEntry;
  return typeof editorEntry === "string" && editorEntry.trim() !== ""
    ? editorEntry
    : undefined;
}

/** A block's editor component path, or `undefined` when it names none. */
function blockEditorComponent(block: unknown): string | undefined {
  if (typeof block !== "object" || block === null) return undefined;
  const editor = (block as { editor?: unknown }).editor;
  if (typeof editor !== "object" || editor === null) return undefined;
  const component = (editor as { component?: unknown }).component;
  return typeof component === "string" && component.length > 0
    ? component
    : undefined;
}

interface ParsedPath {
  /** The full component path string (the registry key). */
  path: string;
  /** Module specifier (before `#`). */
  module: string;
  /** Named export (after `#`), or `"default"` when there is no `#`. */
  member: string;
}

function parsePath(path: string): ParsedPath {
  const hash = path.indexOf("#");
  if (hash === -1) return { path, module: path, member: "default" };
  return { path, module: path.slice(0, hash), member: path.slice(hash + 1) };
}

/**
 * Every use of a component the plugins declare, in declared order: admin
 * contributions, declared widgets, then block editor components. A path two
 * contributions share appears once for each.
 *
 * The richer list, kept whole for the check: two widgets drawn with one
 * missing component are two cards that draw empty, and the refusal names and
 * counts both. The map's own entries are derived from it.
 */
export function componentUses(
  plugins: readonly PluginDefinition[]
): ComponentMapEntry[] {
  return [
    ...plugins.flatMap(plugin => collectAdminComponentEntries(plugin)),
    // Block editor components register through the same map, so the editor
    // bundle loads a contributed block's inspector without a hand-written
    // import -- the same guarantee admin contributions already have.
    ...collectBlockEditorEntries(plugins),
  ];
}

/**
 * Every component the generated map registers, once each and sorted by path,
 * derived from {@link componentUses}.
 *
 * The one list the map and its exported path list are built from. Where two
 * contributions name the same path, the first declared keeps it, as the
 * registry keeps the first registration, unless a later one is a dashboard
 * widget's.
 *
 * 🔴 A widget's use wins over any other. One path may serve a page and a
 * widget alike, and the check refuses only over a missing widget component:
 * kept as the page's, that path would only be warned about, and production
 * would serve the widget with an empty card.
 */
export function componentImportMapEntries(
  plugins: readonly PluginDefinition[]
): ComponentMapEntry[] {
  const byPath = new Map<string, ComponentMapEntry>();
  for (const each of componentUses(plugins)) {
    const kept = byPath.get(each.path);
    if (
      kept === undefined ||
      (each.use === "widget" && kept.use !== "widget")
    ) {
      byPath.set(each.path, each);
    }
  }
  return [...byPath.values()].sort((a, b) => a.path.localeCompare(b.path));
}

/** The paths of {@link componentImportMapEntries}, in its order. */
export function componentImportMapPaths(
  plugins: readonly PluginDefinition[]
): string[] {
  return componentImportMapEntries(plugins).map(each => each.path);
}

/**
 * The strings-only list: the paths as a literal tuple, so the map's type check
 * below can compare them with the keys it registers.
 */
const pathListExport = (paths: readonly string[]): string =>
  `export const registeredComponentPaths = ${JSON.stringify(paths)} as const;`;

/**
 * How the map holds itself to its list.
 *
 * The two files are written together, but either can be edited by hand, and
 * the server check reads only the list: a map registering less than its list
 * says would pass that check and still draw an empty card. So the map imports
 * the list and refuses to disagree with it, twice. Its type compares the keys
 * it registers with the listed paths, so `next build` (which type-checks)
 * fails to compile a disagreeing pair. And the same comparison runs when the
 * admin loads it, for `next dev`, which does not type-check.
 */
/** What a developer reads when the pair disagrees, at build and at load. */
export const COMPONENT_MAP_MISMATCH_MESSAGE =
  "component map and its list disagree: run npx nextly generate:types";

const AGREEMENT_CHECK = [
  "type Registered = keyof typeof registered;",
  "type Listed = (typeof listed)[number];",
  "/** `true` only while this map registers exactly the paths its list names. */",
  "type Agrees = [Registered] extends [Listed]",
  "  ? [Listed] extends [Registered]",
  "    ? true",
  `    : ${JSON.stringify(COMPONENT_MAP_MISMATCH_MESSAGE)}`,
  `  : ${JSON.stringify(COMPONENT_MAP_MISMATCH_MESSAGE)};`,
  "export const componentMapAgreesWithList: Agrees = true;",
  "",
  "if (",
  "  JSON.stringify(Object.keys(registered).sort()) !==",
  "  JSON.stringify([...listed].sort())",
  ") {",
  "  throw Object.assign(",
  `    new Error(${JSON.stringify(`The admin's ${COMPONENT_MAP_MISMATCH_MESSAGE}.`)}),`,
  '    { code: "NEXTLY_ADMIN_COMPONENT_MAP_MISMATCH" },',
  "  );",
  "}",
].join("\n");

/** The line the map imports the site's config with, written and read as one: see `configImportOf`. */
const SITE_CONFIG_IMPORT = "import type * as siteConfig from ";

/**
 * The config import a generated map names, as `buildComponentImportMap` wrote it; undefined when it
 * names none or the line cannot be read. A rewrite keeps it, so the map goes on checking against
 * the config it was generated for, a `--config` path included, rather than one found again.
 */
export function configImportOf(mapCode: string): string | undefined {
  const line = mapCode
    .split("\n")
    .find(each => each.startsWith(SITE_CONFIG_IMPORT));
  if (line === undefined) return undefined;
  try {
    const specifier: unknown = JSON.parse(
      line.slice(SITE_CONFIG_IMPORT.length).replace(/;\s*$/, "")
    );
    return typeof specifier === "string" ? specifier : undefined;
  } catch {
    return undefined;
  }
}

/**
 * Build the generated import-map module source for all plugins' admin
 * components. Deterministic: modules and registry keys are sorted; one
 * `import * as` per unique module; duplicate paths deduped. A map with nothing
 * to register imports no component and registers nothing, and still holds
 * itself to its (empty) list.
 */
export function buildComponentImportMap(
  plugins: PluginDefinition[],
  configImport?: string
): string {
  const entries = componentImportMapEntries(plugins);
  const blockEditor = blockEditorHandOff(plugins, entries);
  // An editor entry exports block definitions, not a component, so it is
  // handed to the page builder alone and never put in the component registry,
  // whose type would refuse it in the site's build.
  const paths = entries
    .filter(each => each.use !== "block editor entry")
    .map(each => each.path);
  const parsed = paths.map(parsePath);
  const handedOff = [...blockEditor.entries, ...blockEditor.components].map(
    parsePath
  );
  const modules = Array.from(
    new Set([...parsed, ...handedOff].map(p => p.module))
  ).sort();
  const alias = new Map<string, string>();
  modules.forEach((m, i) => alias.set(m, `_p${i}`));
  const reference = (p: ParsedPath) => `${alias.get(p.module)}.${p.member}`;

  const lines: string[] = [HEADER, ""];
  if (paths.length > 0) {
    lines.push('import { registerComponents } from "@nextlyhq/admin";');
  }
  if (blockEditor.used) {
    lines.push(
      `import { ${BLOCK_EDITOR_REGISTRAR} } from "${PAGE_BUILDER_ADMIN_MODULE}";`
    );
  }
  for (const m of modules) {
    lines.push(`import * as ${alias.get(m)} from "${m}";`);
  }
  lines.push(
    `import { registeredComponentPaths as listed } from "./${COMPONENT_PATHS_FILENAME.replace(/\.ts$/, "")}";`
  );
  // The site's config, for its type alone: the check below reads the widgets it declares.
  // Type-only, so it is erased and no server code reaches the browser bundle.
  if (configImport !== undefined) {
    lines.push('import type { DeclaredComponentMap } from "nextly";');
    lines.push(`${SITE_CONFIG_IMPORT}${JSON.stringify(configImport)};`);
  }
  lines.push("");
  lines.push("const registered = {");
  for (const p of parsed) {
    lines.push(`  ${JSON.stringify(p.path)}: ${reference(p)},`);
  }
  // Each component registered under a typed widget's path must take that widget's props, or
  // the site's build fails here; every other path is left as it was.
  lines.push(
    configImport === undefined
      ? "};"
      : "} satisfies DeclaredComponentMap<typeof siteConfig>;"
  );
  lines.push("");
  if (blockEditor.used) {
    lines.push(
      "/** The modules exporting each plugin's block definitions, for the page builder's editor. */"
    );
    lines.push("const blockEditorEntries = {");
    for (const p of blockEditor.entries.map(parsePath)) {
      lines.push(`  ${JSON.stringify(p.path)}: ${reference(p)},`);
    }
    lines.push("};");
    lines.push("");
  }
  lines.push(
    blockEditor.used
      ? AGREEMENT_CHECK.replace(
          "type Registered = keyof typeof registered;",
          "type Registered =\n  | keyof typeof registered\n  | keyof typeof blockEditorEntries;"
        ).replace(
          "JSON.stringify(Object.keys(registered).sort())",
          "JSON.stringify(\n    [...Object.keys(registered), ...Object.keys(blockEditorEntries)].sort()\n  )"
        )
      : AGREEMENT_CHECK
  );
  lines.push("");
  if (paths.length > 0) lines.push("registerComponents(registered);");
  if (blockEditor.used) {
    // The block inspectors are in `registered` too, which keeps them
    // resolvable by path like any component; they are handed over here as
    // well because the editor reaches no component registry of the admin's.
    lines.push(`${BLOCK_EDITOR_REGISTRAR}({`);
    lines.push("  entries: blockEditorEntries,");
    lines.push("  components: {");
    for (const p of blockEditor.components.map(parsePath)) {
      lines.push(`    ${JSON.stringify(p.path)}: ${reference(p)},`);
    }
    lines.push("  },");
    lines.push("});");
  }
  lines.push("export const registeredComponentPaths = listed;");
  lines.push("");
  return lines.join("\n");
}

/**
 * The page builder's admin entry, and the function there the map hands block
 * modules to. Stated here rather than imported, as the declaration key is, so
 * core carries no dependency on the page builder; the page builder's
 * `admin/registration.test.ts` holds its entry to both.
 */
const PAGE_BUILDER_ADMIN_MODULE = `${PAGE_BUILDER_PLUGIN}/admin`;
const BLOCK_EDITOR_REGISTRAR = "registerBlockEditorModules";

/**
 * What the map hands the page builder: each declared editor entry and each
 * declared block inspector, by path, and whether there is anything to hand
 * over at all. Nothing when the page builder is inactive, since the uses are
 * collected only while it is active. An inspector is handed over whichever
 * use kept its path in the registry, so a component a page also uses still
 * reaches the editor.
 */
function blockEditorHandOff(
  plugins: readonly PluginDefinition[],
  kept: readonly ComponentMapEntry[]
): { entries: string[]; components: string[]; used: boolean } {
  const editorEntries = kept
    .filter(each => each.use === "block editor entry")
    .map(each => each.path);
  const components = [
    ...new Set(
      collectBlockEditorEntries(plugins)
        .filter(each => each.use === "block editor")
        .map(each => each.path)
    ),
  ].sort((a, b) => a.localeCompare(b));
  return {
    entries: editorEntries,
    components,
    used: editorEntries.length > 0 || components.length > 0,
  };
}

/** Filename of the generated list of the paths the map registers. */
export const COMPONENT_PATHS_FILENAME = "plugin-admin-components.generated.ts";

const PATHS_HEADER = [
  "/* AUTO-GENERATED by `nextly generate:types` — DO NOT EDIT.",
  " * The component paths `plugin-admin-imports.generated.ts` registers, as",
  " * plain strings, so server code can read what the admin's map holds",
  " * without importing the components. Regenerated with it. */",
].join("\n");

/**
 * The strings-only companion of the map: the same paths, and nothing that
 * imports a component, so the admin's server layout can compare them with
 * what the config declares.
 */
export function buildComponentPathsModule(
  plugins: readonly PluginDefinition[]
): string {
  return `${PATHS_HEADER}\n\n${pathListExport(componentImportMapPaths(plugins))}\n`;
}

/**
 * The two generated files, placed beside the generated types file so they
 * ship with the app: the map, which the admin page imports to register every
 * component, and its strings-only list, which the admin's server layout reads.
 *
 * 🔴 Always both, even when nothing contributes a component. The admin page
 * and layout import them, so a file removed because the map is empty would
 * stop the app compiling; an empty map registers nothing and lists nothing.
 * Pure: no IO.
 */
export function buildImportMapArtifacts(
  plugins: PluginDefinition[],
  typesOutputPath: string,
  configImport?: string
): { path: string; code: string }[] {
  const dir = dirname(typesOutputPath);
  return [
    {
      path: join(dir, COMPONENT_IMPORT_MAP_FILENAME),
      code: buildComponentImportMap(plugins, configImport),
    },
    {
      path: join(dir, COMPONENT_PATHS_FILENAME),
      code: buildComponentPathsModule(plugins),
    },
  ];
}

/**
 * How the generated map, in `mapDir`, imports the site's config file at `configFile`: relative,
 * with forward slashes, as TypeScript resolves it. Both absolute.
 *
 * A `.ts` or `.js` config is named without its extension. An ESM one keeps it, written as the
 * output's: `.mjs` for an `.mjs` config and for an `.mts` source, which TypeScript maps back to the
 * source. Without it the specifier resolves to neither under the site's Bundler resolution.
 */
export function configImportSpecifier(
  mapDir: string,
  configFile: string
): string {
  const path = relative(mapDir, configFile)
    .split(sep)
    .join("/")
    .replace(/\.(ts|js)$/, "")
    .replace(/\.mts$/, ".mjs");
  return path.startsWith(".") ? path : `./${path}`;
}
