#!/usr/bin/env node
/**
 * Regenerates the vendored Lucide icon set from named, published versions.
 *
 *   node scripts/update-lucide.mjs --lucide 1.60.0 --iconify 1.2.147
 *
 * Lucide's own `lucide-static` package is the source of the icons and their
 * search tags, and of the ISC licence that must ship with them. Iconify's
 * `@iconify-json/lucide` contributes only the alias map: the names Lucide has
 * renamed, so an id stored under an old name keeps resolving. Pick an Iconify
 * release cut from the same Lucide release (its `icons.json` `lastModified`
 * falls on that release's day).
 *
 * Both packages are fetched with `npm pack`, which checks each tarball against
 * the registry's integrity hash, into a fresh temporary directory removed on
 * exit. Nothing is installed and no package script runs.
 */
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA_FILE = join(PACKAGE_ROOT, "src/icons/lucide-data.ts");
const LICENSE_FILE = join(PACKAGE_ROOT, "third-party/lucide/LICENSE");

function argument(name) {
  const at = process.argv.indexOf(`--${name}`);
  const value = at === -1 ? undefined : process.argv[at + 1];
  if (value === undefined || !/^\d+\.\d+\.\d+$/.test(value)) {
    throw new Error(`--${name} <exact version> is required`);
  }
  return value;
}

/** Fetch and unpack one published package; the path of its `package/`. */
function unpack(spec, into) {
  const out = execFileSync("npm", ["pack", spec, "--silent"], {
    cwd: into,
    encoding: "utf8",
  }).trim();
  const tarball = out.split("\n").at(-1);
  const folder = join(into, spec.replace(/[^a-z0-9.]/gi, "_"));
  mkdirSync(folder);
  execFileSync("tar", ["-xzf", join(into, tarball), "-C", folder]);
  return join(folder, "package");
}

/** An icon's nodes as SVG markup, escaped as attribute values must be. */
function bodyOf(nodes) {
  const escape = value =>
    String(value)
      .replace(/&/g, "&amp;")
      .replace(/"/g, "&quot;")
      .replace(/</g, "&lt;");
  return nodes
    .map(
      ([tag, attributes]) =>
        `<${tag}${Object.entries(attributes)
          .map(([key, value]) => ` ${key}="${escape(value)}"`)
          .join("")}/>`
    )
    .join("");
}

const lucide = argument("lucide");
const iconify = argument("iconify");
const work = mkdtempSync(join(tmpdir(), "nextly-lucide-"));
try {
  const staticPackage = unpack(`lucide-static@${lucide}`, work);
  const iconifyPackage = unpack(`@iconify-json/lucide@${iconify}`, work);
  const read = (folder, file) =>
    JSON.parse(readFileSync(join(folder, file), "utf8"));

  /*
   * The alias map must be cut from the SAME Lucide release: an older one
   * omits the renames made since, and an id stored under a renamed name then
   * stops resolving. Iconify stamps its set with when it was built from
   * Lucide; that has to fall within a day and a half of the Lucide release's
   * publication, or nothing is written.
   */
  const published = JSON.parse(
    execFileSync("npm", ["view", "lucide-static", "time", "--json"], {
      encoding: "utf8",
    })
  )[lucide];
  const built = read(iconifyPackage, "icons.json").lastModified;
  const apart =
    typeof published === "string" && typeof built === "number"
      ? Math.abs(Date.parse(published) - built * 1000)
      : Number.NaN;
  if (!(apart <= 36 * 60 * 60 * 1000)) {
    throw new Error(
      `@iconify-json/lucide ${iconify} was not built from Lucide ${lucide} ` +
        `(Lucide published ${String(published)}, Iconify built ` +
        `${typeof built === "number" ? new Date(built * 1000).toISOString() : "at an unknown time"}). ` +
        "Choose the Iconify release cut from this Lucide release."
    );
  }

  const nodes = read(staticPackage, "icon-nodes.json");
  const tags = read(staticPackage, "tags.json");
  const iconifySet = read(iconifyPackage, "icons.json");

  const names = Object.keys(nodes).sort();
  const icons = Object.fromEntries(
    names.map(name => [name, bodyOf(nodes[name])])
  );
  // Only aliases that land on an icon this release has, and never one that
  // shadows a current name.
  const aliases = Object.fromEntries(
    Object.entries(iconifySet.aliases ?? {})
      .filter(
        ([alias, { parent }]) =>
          icons[parent] !== undefined && icons[alias] === undefined
      )
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([alias, { parent }]) => [alias, parent])
  );
  const iconTags = Object.fromEntries(
    names.map(name => [name, tags[name] ?? []])
  );

  const header = [
    "// GENERATED by scripts/update-lucide.mjs. Do not edit by hand.",
    `// Lucide ${lucide} (lucide-static) with aliases from @iconify-json/lucide ${iconify}.`,
    "// Lucide is ISC-licensed: see third-party/lucide/LICENSE, shipped with this package.",
    "",
  ].join("\n");
  writeFileSync(
    DATA_FILE,
    `${header}
/** The Lucide release these icons were taken from. */
export const LUCIDE_VERSION = ${JSON.stringify(lucide)};

/** Each icon's SVG body, drawn in a 24 × 24 box with a 2px round stroke. */
export const LUCIDE_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(icons)};

/** Names Lucide has renamed, and the icon each now is. */
export const LUCIDE_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases)};

/** Words each icon is found by in a search, as Lucide tags them. */
export const LUCIDE_TAGS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(iconTags)};
`
  );
  mkdirSync(dirname(LICENSE_FILE), { recursive: true });
  writeFileSync(
    LICENSE_FILE,
    readFileSync(join(staticPackage, "LICENSE"), "utf8")
  );
  console.log(
    `Wrote ${names.length} icons and ${Object.keys(aliases).length} aliases from Lucide ${lucide}.`
  );
} finally {
  rmSync(work, { recursive: true, force: true });
}
