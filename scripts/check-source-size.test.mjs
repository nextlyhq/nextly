/**
 * What keeps the Page Builder's source files within 1,500 lines. The rules are
 * judged on paths, texts and file lists; the command on a small repository
 * built in a temporary directory, and on this one.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { LIMIT, MIGRATIONS, PACKAGES, countLines, generatorOf, judge, leftOut } from "./check-source-size.mjs";
import { everyPass, lint } from "./lint.mjs";

const SCRIPT = fileURLToPath(new URL("./check-source-size.mjs", import.meta.url));

const lines = count => "x\n".repeat(count);
const text = body => () => body;
const counted = (path, n) => ({ path, lines: n, reason: null });
/** One small counted file in every package, so the population check is met. */
const everyPackage = PACKAGES.map(pkg => counted(`${pkg}/src/index.ts`, 10));
/** The message a counted file over the limit gets, in full. */
const overLimit = (path, size) =>
  `${path} has ${size.toLocaleString("en-US")} lines, over the limit of 1,500. Split it into files of 1,500 lines or fewer, each holding one area of what it does; keep this file as the entry that imports or re-exports the parts, so nothing that uses it has to change.`;

describe("counting lines", () => {
  it("counts lines as an editor numbers them, with or without a final newline", () => {
    expect(countLines("")).toBe(0);
    expect(countLines("a")).toBe(1);
    expect(countLines("a\n")).toBe(1);
    expect(countLines("a\nb")).toBe(2);
    expect(countLines("a\nb\n")).toBe(2);
    expect(countLines("a\r\nb\r\n")).toBe(2);
    expect(countLines(lines(LIMIT + 1))).toBe(LIMIT + 1);
  });
});

describe("what the check leaves out", () => {
  const source = text("export const a = 1;\n");

  it("counts a hand-written script or stylesheet", () => {
    for (const path of ["p/src/a.ts", "p/src/a.tsx", "p/src/a.mjs", "p/src/a.cjs", "p/src/a.js", "p/src/a.mts", "p/src/styles/a.css"]) {
      expect(leftOut(path, source), path).toBeNull();
    }
  });

  it("leaves out files that are not scripts or stylesheets", () => {
    for (const path of ["p/README.md", "p/package.json", "p/third-party/lucide/LICENSE"]) {
      expect(leftOut(path, source), path).toBe("not source");
    }
  });

  it("leaves out tests by name and by folder, and keeps a file that only mentions a test", () => {
    for (const path of ["p/src/a.test.ts", "p/src/a.test.tsx", "p/src/a.spec.ts", "p/src/a.integration.test.ts", "p/src/a.test-d.ts", "p/src/__tests__/harness.ts", "p/src/__tests__/deep/x.tsx"]) {
      expect(leftOut(path, source), path).toBe("test");
    }
    for (const path of ["p/src/test-utils.ts", "p/src/contest.ts", "p/src/latest.test-helpers/a.ts"]) {
      expect(leftOut(path, source), path).toBeNull();
    }
  });

  it("leaves out fixtures by name and by folder", () => {
    for (const path of ["p/src/validation.fixtures.ts", "p/src/a.fixture.ts", "p/src/fixtures/a.ts", "p/src/__fixtures__/a.ts"]) {
      expect(leftOut(path, source), path).toBe("fixture");
    }
    expect(leftOut("p/src/fixture-loader.ts", source)).toBeNull();
  });

  it("leaves out the plugin's migrations, whatever their header says, and no other migrations folder", () => {
    expect(leftOut(`${MIGRATIONS}20261112_seed.ts`, text("/**\n * Written by hand.\n */\n"))).toBe("migration");
    expect(leftOut("packages/blocks-engine/src/migrations/v2.ts", source)).toBeNull();
    expect(leftOut("packages/plugin-page-builder/src/schema/migration-helpers.ts", source)).toBeNull();
  });

  const lucide = "// GENERATED by scripts/update-lucide.mjs. Do not edit by hand.\nexport const a = 1;\n";
  const lucidePath = "packages/blocks-react/src/icons/lucide-data.ts";

  it("leaves out a file whose opening comment names the generator that wrote it, found in its package or from the root", () => {
    expect(leftOut(lucidePath, text(lucide), path => path === "packages/blocks-react/scripts/update-lucide.mjs")).toBe("generated");
    expect(leftOut(lucidePath, text(lucide), path => path === "scripts/update-lucide.mjs")).toBe("generated");
    const block = "/**\n * Generated by `scripts/gen.mjs`, from the schema.\n */\nexport {};\n";
    expect(leftOut("packages/builder/src/x.ts", text(block), path => path === "packages/builder/scripts/gen.mjs")).toBe("generated");
  });

  it("counts a file that claims to be generated by something git does not track", () => {
    expect(leftOut(lucidePath, text(lucide), () => false)).toBeNull();
    expect(leftOut("packages/builder/src/x.ts", text("// Generated by hand, then edited.\n"), path => path === "packages/builder/scripts/gen.mjs")).toBeNull();
  });

  it("reads the generator from the first words of the opening comment only", () => {
    expect(generatorOf(lucide)).toBe("scripts/update-lucide.mjs");
    expect(generatorOf("/**\n * Generated by `nextly migrate:create --plugin`.\n */\n")).toBe("nextly");
    for (const body of [
      "export const a = 1;\n// Generated by scripts/x.mjs\n",
      "/**\n * This module is generated by scripts/x.mjs.\n */\n",
      "// The ids are\n// generated by scripts/x.mjs.\n",
      "\n// Generated by scripts/x.mjs\n",
    ]) {
      expect(generatorOf(body), body).toBeNull();
      expect(leftOut("packages/builder/src/x.ts", text(body), () => true), body).toBeNull();
    }
  });

  it("reads a file's text only when its path does not decide", () => {
    const unread = () => {
      throw new Error("read");
    };
    expect(leftOut("p/src/a.test.ts", unread)).toBe("test");
    expect(leftOut("p/README.md", unread)).toBe("not source");
    expect(() => leftOut("p/src/a.ts", unread)).toThrow("read");
  });
});

describe("judging the files", () => {
  const file = "packages/builder/src/canvas.tsx";

  it("passes a file of exactly the limit, and fails one a line over it, naming the file, its lines and the limit", () => {
    expect(judge([...everyPackage, counted(file, LIMIT)]).problems).toEqual([]);
    expect(judge([...everyPackage, counted(file, LIMIT + 1)]).problems).toEqual([overLimit(file, LIMIT + 1)]);
  });

  it("fails every counted file over the limit, one problem each, however far over it is", () => {
    const other = "packages/blocks-engine/src/style/compile-page.ts";
    const { problems } = judge([...everyPackage, counted(file, 2705), counted(other, LIMIT + 1)]);
    expect(problems).toEqual([overLimit(file, 2705), overLimit(other, LIMIT + 1)]);
  });

  it("does not count left-out files however long they are, and tallies each by its reason", () => {
    const files = [
      ...everyPackage,
      { path: "packages/builder/src/canvas.test.tsx", lines: null, reason: "test" },
      { path: "packages/plugin-page-builder/src/schema/migrations/1.ts", lines: null, reason: "migration" },
      { path: "packages/plugin-page-builder/src/schema/migrations/2.ts", lines: null, reason: "migration" },
    ];
    expect(judge(files)).toEqual({ problems: [], counted: PACKAGES.length, leftOut: { test: 1, migration: 2 } });
  });

  it("fails when a package yields no counted source file, rather than reading an empty package as clean", () => {
    const message = `${PACKAGES[0]} has no source file this check counts, so nothing in it was checked. If the package moved or was renamed, update PACKAGES in scripts/check-source-size.mjs.`;
    expect(judge(everyPackage.slice(1)).problems).toEqual([message]);
    const onlyNotSource = [{ path: `${PACKAGES[0]}/package.json`, lines: null, reason: "not source" }, ...everyPackage.slice(1)];
    expect(judge(onlyNotSource).problems).toEqual([message]);
  });
});

describe("the command", () => {
  let base;

  beforeEach(() => {
    base = mkdtempSync(join(tmpdir(), "source-size-"));
    execFileSync("git", ["init", "-q"], { cwd: base });
    for (const pkg of PACKAGES) put(`${pkg}/src/index.ts`, lines(3));
  });

  afterEach(() => {
    rmSync(base, { recursive: true, force: true });
  });

  function put(path, body) {
    mkdirSync(dirname(join(base, path)), { recursive: true });
    writeFileSync(join(base, path), body);
  }

  /** Tracks the root's files as they stand, then runs the check on it. */
  function run(env = {}) {
    execFileSync("git", ["add", "-A"], { cwd: base });
    return check(env);
  }

  /** Runs the check on the root without touching what git tracks. */
  function check(env = {}) {
    return spawnSync(process.execPath, [SCRIPT, "--root", base], { encoding: "utf8", env: { ...process.env, ...env } });
  }

  const big = "packages/builder/src/big.tsx";

  it("exits 1 for a file a line over the limit, and 0 at the limit", () => {
    put(big, lines(LIMIT + 1));
    const over = run();
    expect(over.status).toBe(1);
    expect(over.stderr).toMatch(/^source-size: FAILED, 1 problem\(s\)\./);
    expect(over.stderr).toContain(`  - ${overLimit(big, LIMIT + 1)}\n`);

    put(big, lines(LIMIT));
    const fits = run();
    expect(fits.status, fits.stderr).toBe(0);
    expect(fits.stdout).toMatch(/^source-size: OK, read 5 source file\(s\) in 4 Page Builder packages: all are within 1,500 lines\. /);
  });

  /*
   * The check has no exceptions. A list of files allowed past the limit,
   * at the path and in the format such a list would take, neither lets a
   * file through nor is opened at all.
   */
  describe("with no exception to the limit", () => {
    const list = "scripts/source-size-allowlist.txt";

    it("fails a file over the limit that a list beside the check names at its size", () => {
      put(list, `# Files allowed past 1,500 lines.\n\n${big} 1700\n`);
      put(big, lines(1700));
      const result = run();
      expect(result.status).toBe(1);
      expect(result.stderr).toMatch(/^source-size: FAILED, 1 problem\(s\)\./);
      expect(result.stderr).toContain(`  - ${overLimit(big, 1700)}\n`);
      expect(result.stderr).not.toContain(list);
    });

    it("never opens that list: a path there that cannot be read as a file changes nothing", () => {
      // Reading a directory as a file throws, so a run that passes never read the path.
      put(`${list}/entry`, `${big} 1700\n`);
      const result = run();
      expect(result.status, result.stderr).toBe(0);
      expect(result.stdout).toMatch(/^source-size: OK, read 4 source file\(s\)/);
    });

    it("takes nothing from a base revision, so a base it cannot read changes nothing", () => {
      const result = run({ SOURCE_SIZE_BASE: "no-such-revision" });
      expect(result.status, result.stderr).toBe(0);
      expect(result.stdout).toMatch(/^source-size: OK, /);
    });
  });

  it("reads past long tests, __tests__, fixtures, migrations and generated files, and names how many it left out", () => {
    put("packages/builder/src/big.test.tsx", lines(3000));
    put("packages/builder/src/__tests__/harness.ts", lines(3000));
    put("packages/blocks-engine/src/validation.fixtures.ts", lines(3000));
    put("packages/plugin-page-builder/src/schema/migrations/20261107_x.ts", `/**\n * Generated by \`nextly migrate:create --plugin\`.\n */\n${lines(3000)}`);
    put("packages/blocks-react/scripts/update.mjs", "export {};\n");
    put("packages/blocks-react/src/icons/data.ts", `// GENERATED by scripts/update.mjs. Do not edit by hand.\n${lines(3000)}`);
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("Left out: fixture 1, generated 1, migration 1, test 2.");
    expect(result.stdout).toContain("Left out as generated: packages/blocks-react/src/icons/data.ts.");

    // The control: the same generated file without its header is counted, and fails.
    put("packages/blocks-react/src/icons/data.ts", lines(3001));
    const headless = run();
    expect(headless.status).toBe(1);
    expect(headless.stderr).toContain("packages/blocks-react/src/icons/data.ts has 3,001 lines");
  });

  it("does not read outside the four packages", () => {
    put("packages/nextly/src/huge.ts", lines(5000));
    put("scripts/huge.mjs", lines(5000));
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("read 4 source file(s)");
  });

  it("treats a tracked file deleted from the working tree as gone, rather than crashing", () => {
    put(big, lines(1600));
    expect(run().status).toBe(1);
    rmSync(join(base, big));
    const result = check();
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("read 4 source file(s)");
  });

  it("reports every problem in one run", () => {
    const other = "packages/blocks-engine/src/big.ts";
    put(big, lines(1501));
    put(other, lines(1600));
    rmSync(join(base, `${PACKAGES[3]}/src/index.ts`));
    const result = run();
    expect(result.status).toBe(1);
    expect(result.stderr).toMatch(/^source-size: FAILED, 3 problem\(s\)\./);
    expect(result.stderr).toContain(`  - ${PACKAGES[3]} has no source file this check counts`);
    expect(result.stderr).toContain(`  - ${overLimit(big, 1501)}\n`);
    expect(result.stderr).toContain(`  - ${overLimit(other, 1600)}\n`);
  });

  it("passes on this repository", () => {
    const result = spawnSync(process.execPath, [SCRIPT], { encoding: "utf8" });
    expect(result.status, result.stderr).toBe(0);
  });
});

describe("pnpm lint", () => {
  const passing = () => true;

  it("fails when only the size check fails, after running every oxlint pass", () => {
    const ran = [];
    expect(lint([], args => (ran.push(args), true), () => 1)).toBe(1);
    expect(ran).toEqual(everyPass([]));
  });

  it("passes when every pass and the size check pass, and fails when a pass fails though the size check passes", () => {
    expect(lint([], passing, () => 0)).toBe(0);
    const firstFails = args => args.join(" ") !== everyPass([])[0].join(" ");
    let checked = false;
    expect(lint([], firstFails, () => ((checked = true), 0))).toBe(1);
    expect(checked).toBe(true);
  });
});

