/**
 * What keeps the Page Builder's source files within 1,500 lines. The rules are
 * judged on paths, texts and file lists; the command on a small repository
 * built in a temporary directory, and on this one; the allowlist's format on
 * a real merge of two branches that each delete a neighbouring entry.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
  ALLOWLIST,
  LIMIT,
  MIGRATIONS,
  PACKAGES,
  countLines,
  generatorOf,
  judge,
  leftOut,
  parseAllowlist,
  wideningProblems,
} from "./check-source-size.mjs";
import { everyPass, lint } from "./lint.mjs";

const SCRIPT = fileURLToPath(new URL("./check-source-size.mjs", import.meta.url));
const REPO = fileURLToPath(new URL("..", import.meta.url));

const lines = count => "x\n".repeat(count);
/** This process's environment without a base revision, so a run compares only what a test sets. */
const { SOURCE_SIZE_BASE: _unset, ...ENV } = process.env;
const text = body => () => body;
const counted = (path, n) => ({ path, lines: n, reason: null });
/** One small counted file in every package, so the population check is met. */
const everyPackage = PACKAGES.map(pkg => counted(`${pkg}/src/index.ts`, 10));
const listOf = entries => parseAllowlist(entries.map(([path, n]) => `${path} ${n}`).join("\n\n")).entries;

describe("counting lines", () => {
  it("counts lines as an editor numbers them, with or without a final newline", () => {
    expect(countLines("")).toBe(0);
    expect(countLines("a")).toBe(1);
    expect(countLines("a\n")).toBe(1);
    expect(countLines("a\nb")).toBe(2);
    expect(countLines("a\nb\n")).toBe(2);
    expect(countLines("a\r\nb\r\n")).toBe(2);
    expect(countLines(lines(LIMIT + 1))).toBe(LIMIT + 1);
  });
});

describe("what the check leaves out", () => {
  const source = text("export const a = 1;\n");

  it("counts a hand-written script or stylesheet", () => {
    for (const path of ["p/src/a.ts", "p/src/a.tsx", "p/src/a.mjs", "p/src/a.cjs", "p/src/a.js", "p/src/a.mts", "p/src/styles/a.css"]) {
      expect(leftOut(path, source), path).toBeNull();
    }
  });

  it("leaves out files that are not scripts or stylesheets", () => {
    for (const path of ["p/README.md", "p/package.json", "p/third-party/lucide/LICENSE"]) {
      expect(leftOut(path, source), path).toBe("not source");
    }
  });

  it("leaves out tests by name and by folder, and keeps a file that only mentions a test", () => {
    for (const path of ["p/src/a.test.ts", "p/src/a.test.tsx", "p/src/a.spec.ts", "p/src/a.integration.test.ts", "p/src/a.test-d.ts", "p/src/__tests__/harness.ts", "p/src/__tests__/deep/x.tsx"]) {
      expect(leftOut(path, source), path).toBe("test");
    }
    for (const path of ["p/src/test-utils.ts", "p/src/contest.ts", "p/src/latest.test-helpers/a.ts"]) {
      expect(leftOut(path, source), path).toBeNull();
    }
  });

  it("leaves out fixtures by name and by folder", () => {
    for (const path of ["p/src/validation.fixtures.ts", "p/src/a.fixture.ts", "p/src/fixtures/a.ts", "p/src/__fixtures__/a.ts"]) {
      expect(leftOut(path, source), path).toBe("fixture");
    }
    expect(leftOut("p/src/fixture-loader.ts", source)).toBeNull();
  });

  it("leaves out the plugin's migrations, whatever their header says, and no other migrations folder", () => {
    expect(leftOut(`${MIGRATIONS}20261112_seed.ts`, text("/**\n * Written by hand.\n */\n"))).toBe("migration");
    expect(leftOut("packages/blocks-engine/src/migrations/v2.ts", source)).toBeNull();
    expect(leftOut("packages/plugin-page-builder/src/schema/migration-helpers.ts", source)).toBeNull();
  });

  const lucide = "// GENERATED by scripts/update-lucide.mjs. Do not edit by hand.\nexport const a = 1;\n";
  const lucidePath = "packages/blocks-react/src/icons/lucide-data.ts";

  it("leaves out a file whose opening comment names the generator that wrote it, found in its package or from the root", () => {
    expect(leftOut(lucidePath, text(lucide), path => path === "packages/blocks-react/scripts/update-lucide.mjs")).toBe("generated");
    expect(leftOut(lucidePath, text(lucide), path => path === "scripts/update-lucide.mjs")).toBe("generated");
    const block = "/**\n * Generated by `scripts/gen.mjs`, from the schema.\n */\nexport {};\n";
    expect(leftOut("packages/builder/src/x.ts", text(block), path => path === "packages/builder/scripts/gen.mjs")).toBe("generated");
  });

  it("counts a file that claims to be generated by something git does not track", () => {
    expect(leftOut(lucidePath, text(lucide), () => false)).toBeNull();
    expect(leftOut("packages/builder/src/x.ts", text("// Generated by hand, then edited.\n"), path => path === "packages/builder/scripts/gen.mjs")).toBeNull();
  });

  it("reads the generator from the first words of the opening comment only", () => {
    expect(generatorOf(lucide)).toBe("scripts/update-lucide.mjs");
    expect(generatorOf("/**\n * Generated by `nextly migrate:create --plugin`.\n */\n")).toBe("nextly");
    for (const body of [
      "export const a = 1;\n// Generated by scripts/x.mjs\n",
      "/**\n * This module is generated by scripts/x.mjs.\n */\n",
      "// The ids are\n// generated by scripts/x.mjs.\n",
      "\n// Generated by scripts/x.mjs\n",
    ]) {
      expect(generatorOf(body), body).toBeNull();
      expect(leftOut("packages/builder/src/x.ts", text(body), () => true), body).toBeNull();
    }
  });

  it("reads a file's text only when its path does not decide", () => {
    const unread = () => {
      throw new Error("read");
    };
    expect(leftOut("p/src/a.test.ts", unread)).toBe("test");
    expect(leftOut("p/README.md", unread)).toBe("not source");
    expect(() => leftOut("p/src/a.ts", unread)).toThrow("read");
  });
});

describe("reading the allowlist", () => {
  it("reads a path and a line count per line, skipping comments and blank lines", () => {
    const { entries, errors } = parseAllowlist("# a comment\n\npackages/a.ts 1600\n\n  packages/b.css   2000  \n");
    expect(errors).toEqual([]);
    expect([...entries]).toEqual([
      ["packages/a.ts", { lines: 1600, at: 3 }],
      ["packages/b.css", { lines: 2000, at: 5 }],
    ]);
  });

  it("names a line it cannot read and a path listed twice, with their line numbers", () => {
    const { errors } = parseAllowlist("packages/a.ts\npackages/b.ts 12x\npackages/c.ts 1600\npackages/c.ts 1700\n", "list.txt");
    expect(errors).toEqual([
      'list.txt:1 reads "packages/a.ts", which is not a path followed by its line count, such as "packages/builder/src/canvas.tsx 2705".',
      'list.txt:2 reads "packages/b.ts 12x", which is not a path followed by its line count, such as "packages/builder/src/canvas.tsx 2705".',
      "list.txt:4 lists packages/c.ts again (first on line 3). Keep one line for it.",
    ]);
  });
});

describe("holding the list to a base", () => {
  const base = listOf([["packages/a.ts", 2000], ["packages/b.ts", 1800]]);

  it("passes entries kept, lowered or deleted", () => {
    expect(wideningProblems(base, listOf([["packages/a.ts", 2000], ["packages/b.ts", 1600]]), "dev")).toEqual([]);
    expect(wideningProblems(base, listOf([["packages/b.ts", 1800]]), "dev")).toEqual([]);
  });

  it("fails an added path and a raised count, naming the base", () => {
    const problems = wideningProblems(base, listOf([["packages/a.ts", 2001], ["packages/b.ts", 1800], ["packages/c.ts", 1600]]), "dev", "list.txt");
    expect(problems).toEqual([
      "packages/a.ts is allowed 2,001 lines by list.txt (line 1), more than the 2,000 it was allowed at dev. The list only shrinks: put its count back to 2000 and take the file back under it.",
      "packages/c.ts is in list.txt (line 5) but was not at dev. The list only shrinks: split the file rather than adding it.",
    ]);
  });
});

describe("judging the files", () => {
  const file = "packages/builder/src/canvas.tsx";

  it("passes a file of exactly the limit, and fails one a line over it, naming the file, its lines and the limit", () => {
    expect(judge([...everyPackage, counted(file, LIMIT)], new Map()).problems).toEqual([]);
    const { problems } = judge([...everyPackage, counted(file, LIMIT + 1)], new Map());
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatch(/^packages\/builder\/src\/canvas\.tsx has 1,501 lines, over the limit of 1,500\. Split it /);
    expect(problems[0]).toContain(`Do not add it to ${ALLOWLIST}`);
  });

  it("fails a listed file that grew past its recorded size, saying by how much", () => {
    const { problems } = judge([...everyPackage, counted(file, 2706)], listOf([[file, 2705]]));
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatch(/^packages\/builder\/src\/canvas\.tsx has 2,706 lines, 1 more than the 2,705 /);
  });

  it("passes a listed file at its recorded size, and one that shrank with a note that its size can be lowered", () => {
    expect(judge([...everyPackage, counted(file, 2705)], listOf([[file, 2705]]))).toMatchObject({ problems: [], lowerable: [] });
    const shrank = judge([...everyPackage, counted(file, 2600)], listOf([[file, 2705]]));
    expect(shrank.problems).toEqual([]);
    expect(shrank.lowerable).toEqual([`${file} is down to 2,600 lines; its line in ${ALLOWLIST} (line 1) can be lowered from 2705 to 2600.`]);
  });

  it("reports a listed file that now fits as ready to leave the list", () => {
    for (const size of [LIMIT, 900]) {
      const { problems } = judge([...everyPackage, counted(file, size)], listOf([[file, 2705]]));
      expect(problems).toHaveLength(1);
      expect(problems[0]).toMatch(new RegExp(`^packages/builder/src/canvas\\.tsx now has ${size.toLocaleString("en-US")} lines, within the limit of 1,500, so it leaves the list\\. Delete its line`));
    }
  });

  it("fails a listed path that no longer exists, one outside the packages, or one the check does not count", () => {
    const gone = judge(everyPackage, listOf([["packages/builder/src/gone.tsx", 2000]])).problems;
    expect(gone).toHaveLength(1);
    expect(gone[0]).toMatch(/^packages\/builder\/src\/gone\.tsx is listed \(.* line 1\) but no longer exists\./);
    const outside = judge(everyPackage, listOf([["packages/nextly/src/big.ts", 2000]])).problems;
    expect(outside).toEqual([expect.stringMatching(/^packages\/nextly\/src\/big\.ts is listed .* but is outside the packages this check reads/)]);
    const test = { path: "packages/builder/src/canvas.test.tsx", lines: null, reason: "test" };
    const notCounted = judge([...everyPackage, test], listOf([[test.path, 2800]])).problems;
    expect(notCounted).toEqual([expect.stringMatching(/^packages\/builder\/src\/canvas\.test\.tsx is listed .* but is not a file this check counts \(it is a test file\)\. Delete its line\.$/)]);
  });

  it("does not count left-out files however long they are, and tallies each by its reason", () => {
    const files = [
      ...everyPackage,
      { path: "packages/builder/src/canvas.test.tsx", lines: null, reason: "test" },
      { path: "packages/plugin-page-builder/src/schema/migrations/1.ts", lines: null, reason: "migration" },
      { path: "packages/plugin-page-builder/src/schema/migrations/2.ts", lines: null, reason: "migration" },
    ];
    expect(judge(files, new Map())).toMatchObject({ problems: [], counted: PACKAGES.length, leftOut: { test: 1, migration: 2 } });
  });

  it("fails when a package yields no counted source file, rather than reading an empty package as clean", () => {
    const message = `${PACKAGES[0]} has no source file this check counts, so nothing in it was checked. If the package moved or was renamed, update PACKAGES in scripts/check-source-size.mjs.`;
    expect(judge(everyPackage.slice(1), new Map()).problems).toEqual([message]);
    const onlyNotSource = [{ path: `${PACKAGES[0]}/package.json`, lines: null, reason: "not source" }, ...everyPackage.slice(1)];
    expect(judge(onlyNotSource, new Map()).problems).toEqual([message]);
  });
});

describe("the command", () => {
  let base;

  beforeEach(() => {
    base = mkdtempSync(join(tmpdir(), "source-size-"));
    execFileSync("git", ["init", "-q"], { cwd: base });
    for (const pkg of PACKAGES) put(`${pkg}/src/index.ts`, lines(3));
  });

  afterEach(() => {
    rmSync(base, { recursive: true, force: true });
  });

  function put(path, body) {
    mkdirSync(dirname(join(base, path)), { recursive: true });
    writeFileSync(join(base, path), body);
  }

  function run(env = {}) {
    execFileSync("git", ["add", "-A"], { cwd: base });
    return spawnSync(process.execPath, [SCRIPT, "--root", base], { encoding: "utf8", env: { ...ENV, ...env } });
  }

  function commit() {
    execFileSync("git", ["add", "-A"], { cwd: base });
    execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "base"], { cwd: base });
  }

  const big = "packages/builder/src/big.tsx";

  it("exits 1 for an unlisted file a line over the limit, and 0 at the limit", () => {
    put(big, lines(LIMIT + 1));
    const over = run();
    expect(over.status).toBe(1);
    expect(over.stderr).toMatch(/^source-size: FAILED, 1 problem\(s\)\./);
    expect(over.stderr).toContain(`${big} has 1,501 lines, over the limit of 1,500.`);

    put(big, lines(LIMIT));
    const fits = run();
    expect(fits.status, fits.stderr).toBe(0);
    expect(fits.stdout).toMatch(/^source-size: OK, read 5 source file\(s\) in 4 Page Builder packages/);
  });

  it("holds a listed file to its recorded size: growing fails, shrinking passes and says so, fitting fails until its line goes", () => {
    put(ALLOWLIST, `# header\n\n${big} 1700\n`);
    put(big, lines(1700));
    expect(run().status).toBe(0);

    put(big, lines(1701));
    const grew = run();
    expect(grew.status).toBe(1);
    expect(grew.stderr).toContain(`${big} has 1,701 lines, 1 more than the 1,700 ${ALLOWLIST} allows it until it is split.`);

    put(big, lines(1650));
    const shrank = run();
    expect(shrank.status, shrank.stderr).toBe(0);
    expect(shrank.stdout).toContain(`${big} is down to 1,650 lines; its line in ${ALLOWLIST} (line 3) can be lowered from 1700 to 1650.`);

    put(big, lines(1400));
    const fits = run();
    expect(fits.status).toBe(1);
    expect(fits.stderr).toContain(`${big} now has 1,400 lines, within the limit of 1,500, so it leaves the list.`);

    put(ALLOWLIST, "# header\n\n\n");
    expect(run().status).toBe(0);
  });

  it("reads past long tests, __tests__, fixtures, migrations and generated files, and names how many it left out", () => {
    put("packages/builder/src/big.test.tsx", lines(3000));
    put("packages/builder/src/__tests__/harness.ts", lines(3000));
    put("packages/blocks-engine/src/validation.fixtures.ts", lines(3000));
    put("packages/plugin-page-builder/src/schema/migrations/20261107_x.ts", `/**\n * Generated by \`nextly migrate:create --plugin\`.\n */\n${lines(3000)}`);
    put("packages/blocks-react/scripts/update.mjs", "export {};\n");
    put("packages/blocks-react/src/icons/data.ts", `// GENERATED by scripts/update.mjs. Do not edit by hand.\n${lines(3000)}`);
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("Left out: fixture 1, generated 1, migration 1, test 2.");
    expect(result.stdout).toContain("Left out as generated: packages/blocks-react/src/icons/data.ts.");

    // The control: the same generated file without its header is counted, and fails.
    put("packages/blocks-react/src/icons/data.ts", lines(3001));
    const headless = run();
    expect(headless.status).toBe(1);
    expect(headless.stderr).toContain("packages/blocks-react/src/icons/data.ts has 3,001 lines");
  });

  it("does not read outside the four packages", () => {
    put("packages/nextly/src/huge.ts", lines(5000));
    put("scripts/huge.mjs", lines(5000));
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("read 4 source file(s)");
  });

  it("treats a tracked file deleted from the working tree as gone, rather than crashing", () => {
    put(big, lines(1600));
    put(ALLOWLIST, `${big} 1600\n`);
    expect(run().status).toBe(0);
    rmSync(join(base, big));
    const result = spawnSync(process.execPath, [SCRIPT, "--root", base], { encoding: "utf8", env: ENV });
    expect(result.status).toBe(1);
    expect(result.stderr).toContain(`${big} is listed (${ALLOWLIST} line 1) but no longer exists.`);
  });

  describe("against a base revision", () => {
    const other = "packages/blocks-engine/src/other.ts";

    beforeEach(() => {
      put(big, lines(1700));
      put(other, lines(1600));
      put(ALLOWLIST, `${big} 1700\n\n${other} 1600\n`);
      commit();
    });

    it("passes a list that kept or shrank its entries, and says it compared", () => {
      expect(run({ SOURCE_SIZE_BASE: "HEAD" }).stdout).toContain("The list has not grown since HEAD (");
      put(big, lines(1650));
      put(other, lines(1400));
      put(ALLOWLIST, `${big} 1650\n\n`);
      const shrank = run({ SOURCE_SIZE_BASE: "HEAD" });
      expect(shrank.status, shrank.stderr).toBe(0);
    });

    it("fails an entry the base did not have, even for a file at its listed size", () => {
      const added = "packages/builder/src/added.tsx";
      put(added, lines(1800));
      put(ALLOWLIST, `${big} 1700\n\n${other} 1600\n\n${added} 1800\n`);
      const result = run({ SOURCE_SIZE_BASE: "HEAD" });
      expect(result.status).toBe(1);
      expect(result.stderr).toMatch(/^source-size: FAILED, 1 problem\(s\)\./);
      expect(result.stderr).toContain(`${added} is in ${ALLOWLIST} (line 5) but was not at HEAD (`);
    });

    it("fails a count raised above the base's, even when the file matches the new count", () => {
      put(big, lines(2000));
      put(ALLOWLIST, `${big} 2000\n\n${other} 1600\n`);
      const result = run({ SOURCE_SIZE_BASE: "HEAD" });
      expect(result.status).toBe(1);
      expect(result.stderr).toContain(`${big} is allowed 2,000 lines by ${ALLOWLIST} (line 1), more than the 1,700 it was allowed at HEAD (`);
    });

    it("fails when the base it was given cannot be read, rather than skipping the comparison", () => {
      const result = run({ SOURCE_SIZE_BASE: "no-such-revision" });
      expect(result.status).toBe(1);
      expect(result.stderr).toContain("SOURCE_SIZE_BASE names no-such-revision, which this checkout does not have");
    });

    it("compares nothing with a base that has no list yet, and says so", () => {
      put("packages/builder/src/added.tsx", lines(1800));
      put(ALLOWLIST, `${big} 1700\n\n${other} 1600\n\npackages/builder/src/added.tsx 1800\n`);
      execFileSync("git", ["rm", "-q", "--cached", ALLOWLIST], { cwd: base });
      execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "no list"], { cwd: base });
      const result = run({ SOURCE_SIZE_BASE: "HEAD" });
      expect(result.status, result.stderr).toBe(0);
      expect(result.stdout).toContain(`has no ${ALLOWLIST}, so there is nothing to compare.`);
    });

    it("says it did not compare when no base is set and there is no origin/dev", () => {
      const result = run();
      expect(result.status, result.stderr).toBe(0);
      expect(result.stdout).toContain("Not compared with a base: no origin/dev to compare the list with");
    });
  });

  it("reports every problem in one run", () => {
    put(ALLOWLIST, "packages/builder/src/gone.tsx 1600\nnot an entry\n");
    put(big, lines(1501));
    const result = run();
    expect(result.status).toBe(1);
    expect(result.stderr).toMatch(/^source-size: FAILED, 3 problem\(s\)\./);
  });

  it("passes on this repository with the committed allowlist", () => {
    const result = spawnSync(process.execPath, [SCRIPT], { encoding: "utf8" });
    expect(result.status, result.stderr).toBe(0);
  });
});

describe("pnpm lint", () => {
  const passing = () => true;

  it("fails when only the size check fails, after running every oxlint pass", () => {
    const ran = [];
    expect(lint([], args => (ran.push(args), true), () => 1)).toBe(1);
    expect(ran).toEqual(everyPass([]));
  });

  it("passes when every pass and the size check pass, and fails when a pass fails though the size check passes", () => {
    expect(lint([], passing, () => 0)).toBe(0);
    const firstFails = args => args.join(" ") !== everyPass([])[0].join(" ");
    let checked = false;
    expect(lint([], firstFails, () => ((checked = true), 0))).toBe(1);
    expect(checked).toBe(true);
  });
});

describe("the committed allowlist", () => {
  const committed = readFileSync(join(REPO, ALLOWLIST), "utf8");
  const lineList = committed.split("\n");
  const entryAt = lineList.flatMap((line, index) => (/^\S+\s+\d+$/.test(line.trim()) && !line.startsWith("#") ? [index] : []));

  it("lists only files over the limit, each once, and reads without errors", () => {
    const { entries, errors } = parseAllowlist(committed);
    expect(errors).toEqual([]);
    expect(entries.size).toBe(entryAt.length);
    expect(entries.size).toBeGreaterThan(0);
    for (const [path, { lines: size }] of entries) expect(size, path).toBeGreaterThan(LIMIT);
  });

  it("keeps a blank line between every two entries", () => {
    for (const [i, at] of entryAt.entries()) {
      if (i > 0) expect(lineList[at - 1], `before line ${at + 1}`).toBe("");
    }
  });

  /*
   * The property the blank lines exist for: two branches that each delete a
   * neighbouring entry merge without a conflict, as the split work does.
   */
  it("merges two branches that each delete a neighbouring entry without a conflict", () => {
    const repo = mkdtempSync(join(tmpdir(), "source-size-merge-"));
    const git = (...args) => execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], { cwd: repo, encoding: "utf8" });
    const list = join(repo, "list.txt");
    const without = index => lineList.filter((_, i) => i !== entryAt[index]).join("\n");
    try {
      git("init", "-q", "-b", "base");
      writeFileSync(list, committed);
      git("add", "list.txt");
      git("commit", "-qm", "base");
      git("checkout", "-qb", "first");
      writeFileSync(list, without(0));
      git("commit", "-qam", "first");
      git("checkout", "-q", "base");
      git("checkout", "-qb", "second");
      writeFileSync(list, without(1));
      git("commit", "-qam", "second");
      git("merge", "-q", "--no-edit", "first");
      const merged = parseAllowlist(readFileSync(list, "utf8"));
      expect(merged.errors).toEqual([]);
      const before = [...parseAllowlist(committed).entries.keys()];
      expect([...merged.entries.keys()]).toEqual(before.slice(2));
    } finally {
      rmSync(repo, { recursive: true, force: true });
    }
  });
});
