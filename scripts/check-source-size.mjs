#!/usr/bin/env node
/**
 * Keeps the Page Builder's source files at 1,500 lines or fewer, so a
 * contributor can find things in them and a review of a change stays readable.
 *
 * What it counts: every file git tracks under the four Page Builder packages
 * whose extension is a script or a stylesheet (see `SOURCE`), less what a
 * person does not write and split by hand. That is decided by the rules in
 * `leftOut`, and only by them, so an exemption is always one of these:
 *
 * - a test: a `.test.` or `.spec.` file (with `.test-d.` type tests), or
 *   anything under a `__tests__` folder;
 * - a fixture: a `.fixture.` or `.fixtures.` file, or anything under a
 *   `fixtures` or `__fixtures__` folder;
 * - a migration: anything in the plugin's migrations folder (`MIGRATIONS`).
 *   A migration module is sealed by its checksum once it has run, so it is
 *   never split;
 * - generated: a file whose opening comment starts with `Generated by`
 *   followed by the path of its generator, a file git tracks in the same
 *   package or from the repository's root (`// GENERATED by
 *   scripts/update-lucide.mjs.`). Naming a generator that is not there, or
 *   none, does not exempt a file. The run names each generated file it left
 *   out, so a new one is seen in review.
 *
 * The files that were over the limit when the check landed are listed in
 * `scripts/source-size-allowlist.txt` with their size on that day. A listed
 * file may shrink but not grow, and its line comes out once it fits. The list
 * only ever shrinks: a new file over the limit is split, never added.
 *
 * It fails on:
 * - a counted file over the limit that is not listed;
 * - a listed file that has grown past its recorded size;
 * - a listed file that now fits, or that no longer exists, or that the
 *   check does not count or read (so its line is dead weight);
 * - a line of the list it cannot read, or a path listed twice;
 * - a package with no counted source file, which means the check was looking
 *   in the wrong place rather than that everything fits.
 *
 * A tracked file that is gone from the working tree, mid-way through a local
 * move or split, is treated as gone: it is not read, and so not counted.
 *
 * A listed file that shrank passes, and the run prints the lower size its line
 * can be brought down to.
 *
 * That the list only shrinks is checked against a base revision: an entry
 * the base's list does not have, or a count higher than the base's, fails.
 * The base is `SOURCE_SIZE_BASE` when it is set (CI sets it to the commit the
 * change is compared with), and a base that cannot be read then fails the
 * run. Otherwise it is where HEAD left `origin/dev`, and without that ref the
 * comparison is skipped and the run says so. A base with no list yet has
 * nothing to compare.
 *
 * `pnpm lint` runs it after the oxlint passes (scripts/lint.mjs).
 *
 *   node scripts/check-source-size.mjs [--root <dir>]
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

import { isCliEntry } from "./cli-entry.mjs";

/** The most lines a counted file may have. */
export const LIMIT = 1500;

/** The Page Builder's packages, the only places the check reads. */
export const PACKAGES = [
  "packages/blocks-engine",
  "packages/blocks-react",
  "packages/builder",
  "packages/plugin-page-builder",
];

/** Script and stylesheet sources, by extension. */
export const SOURCE = /\.(?:[cm]?[jt]sx?|css)$/;

/** The list of files allowed past the limit until they are split. */
export const ALLOWLIST = "scripts/source-size-allowlist.txt";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TEST_FILE = /\.(?:test|spec)(?:-d)?\.[^./]+$/;
const FIXTURE_FILE = /\.fixtures?\.[^./]+$/;
const TEST_FOLDERS = new Set(["__tests__"]);
const FIXTURE_FOLDERS = new Set(["fixtures", "__fixtures__"]);

/** The plugin's migration modules, written by `nextly migrate:create --plugin`. */
export const MIGRATIONS = "packages/plugin-page-builder/src/schema/migrations/";

/** How many of a file's first lines are read to find its opening comment's first words. */
const HEADER_LINES = 5;

/**
 * The generator a file's opening comment names, or null when it names none:
 * the word after `Generated by` (in any case) when those are the first words
 * of the file past the comment markers, with quotes and closing punctuation
 * taken off. Words later in the comment, or a comment after code, do not count.
 */
export function generatorOf(text) {
  for (const raw of text.split("\n", HEADER_LINES)) {
    const line = raw.trim();
    if (!/^(?:\/\/|\/\*|\*)/.test(line)) return null;
    const words = line.replace(/^(?:\/\/+|\/\*+|\*+)\s*/, "");
    if (words === "") continue;
    const match = /^generated by\s+(\S+)/i.exec(words);
    return match ? match[1].replace(/^[`'"]+|[`'".,;:)]+$/g, "") : null;
  }
  return null;
}

/** The package of `path` among `PACKAGES`, or null outside them. */
export function packageOf(path) {
  return PACKAGES.find(pkg => path.startsWith(`${pkg}/`)) ?? null;
}

/**
 * Why a tracked file is not counted, or null when it is. `read` returns the
 * file's text, and is only called for a file the path alone does not decide;
 * `tracked` says whether git tracks a path, to find a named generator.
 *
 * @returns {"not source" | "test" | "fixture" | "migration" | "generated" | null}
 */
export function leftOut(path, read, tracked = () => false) {
  if (!SOURCE.test(path)) return "not source";
  const folders = posix.dirname(path).split("/");
  const name = posix.basename(path);
  if (TEST_FILE.test(name) || folders.some(f => TEST_FOLDERS.has(f))) {
    return "test";
  }
  if (FIXTURE_FILE.test(name) || folders.some(f => FIXTURE_FOLDERS.has(f))) {
    return "fixture";
  }
  if (path.startsWith(MIGRATIONS)) return "migration";
  const generator = generatorOf(read());
  if (generator !== null) {
    const pkg = packageOf(path);
    const candidates = [generator, ...(pkg ? [`${pkg}/${generator}`] : [])];
    if (candidates.some(candidate => tracked(posix.normalize(candidate)))) {
      return "generated";
    }
  }
  return null;
}

/** The lines a text has, as an editor numbers them: a final newline ends the last line rather than starting another. */
export function countLines(text) {
  if (text === "") return 0;
  const breaks = text.split("\n").length - 1;
  return text.endsWith("\n") ? breaks : breaks + 1;
}

/**
 * The allowlist's entries, and the lines it could not read. An entry is a
 * path and a line count, separated by spaces; blank lines and lines starting
 * with `#` are skipped.
 *
 * @returns {{ entries: Map<string, { lines: number, at: number }>, errors: string[] }}
 */
export function parseAllowlist(text, name = ALLOWLIST) {
  const entries = new Map();
  const errors = [];
  text.split("\n").forEach((raw, index) => {
    const at = index + 1;
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) return;
    const match = /^(\S+)\s+(\d+)$/.exec(line);
    if (!match) {
      errors.push(
        `${name}:${at} reads "${line}", which is not a path followed by its line count, such as "packages/builder/src/canvas.tsx 2705".`
      );
      return;
    }
    const [, path, lines] = match;
    if (entries.has(path)) {
      errors.push(
        `${name}:${at} lists ${path} again (first on line ${entries.get(path).at}). Keep one line for it.`
      );
      return;
    }
    entries.set(path, { lines: Number(lines), at });
  });
  return { entries, errors };
}

const n = value => value.toLocaleString("en-US");

/**
 * Judges the tracked files against the limit and the allowlist.
 *
 * @param {{ path: string, lines: number | null, reason: string | null }[]} files
 *   every tracked file under the packages: `reason` is why it is left out
 *   (null when counted), and `lines` its length when counted.
 * @param {Map<string, { lines: number, at: number }>} entries the allowlist.
 * @returns {{ problems: string[], lowerable: string[], counted: number, listed: number, leftOut: Record<string, number> }}
 */
export function judge(files, entries, { limit = LIMIT, packages = PACKAGES, list = ALLOWLIST } = {}) {
  const options = { limit, packages, list };
  const countedFiles = files.filter(file => file.reason === null);
  const tally = {};
  for (const file of files) {
    if (file.reason !== null) tally[file.reason] = (tally[file.reason] ?? 0) + 1;
  }
  const verdicts = countedFiles.map(file => fileVerdict(file, entries.get(file.path), options));
  const byPath = new Map(files.map(file => [file.path, file]));
  const problems = [
    ...packages.filter(pkg => !countedFiles.some(file => file.path.startsWith(`${pkg}/`))).map(
      pkg => `${pkg} has no source file this check counts, so nothing in it was checked. If the package moved or was renamed, update PACKAGES in scripts/check-source-size.mjs.`
    ),
    ...verdicts.flatMap(verdict => verdict.problem ?? []),
    ...[...entries].flatMap(([path, entry]) => entryProblem(path, entry, byPath.get(path), options) ?? []),
  ];
  const lowerable = verdicts.flatMap(verdict => verdict.lowerable ?? []);
  return { problems, lowerable, counted: countedFiles.length, listed: entries.size, leftOut: tally };
}

/** What a counted file's size says against its allowlist entry, if it has one. */
function fileVerdict(file, entry, { limit, list }) {
  if (file.lines <= limit) return {};
  if (!entry) {
    return {
      problem: `${file.path} has ${n(file.lines)} lines, over the limit of ${n(limit)}. Split it into files of ${n(limit)} lines or fewer, each holding one area of what it does; keep this file as the entry that imports or re-exports the parts, so nothing that uses it has to change. Do not add it to ${list}: that list only shrinks.`,
    };
  }
  if (file.lines > entry.lines) {
    return {
      problem: `${file.path} has ${n(file.lines)} lines, ${n(file.lines - entry.lines)} more than the ${n(entry.lines)} ${list} allows it until it is split. A listed file may shrink but not grow: put the new code in a new file beside it, or take out as many lines as you added.`,
    };
  }
  if (file.lines < entry.lines) {
    return {
      lowerable: `${file.path} is down to ${n(file.lines)} lines; its line in ${list} (line ${entry.at}) can be lowered from ${entry.lines} to ${file.lines}.`,
    };
  }
  return {};
}

/** Why an allowlist entry should come out, or null while it still earns its place. */
function entryProblem(path, entry, file, { limit, packages, list }) {
  const where = `${list} line ${entry.at}`;
  if (!packages.some(pkg => path.startsWith(`${pkg}/`))) {
    return `${path} is listed (${where}) but is outside the packages this check reads (${packages.join(", ")}). Delete its line.`;
  }
  if (!file) {
    return `${path} is listed (${where}) but no longer exists. If it was split or deleted, delete its line; if it moved and is still over ${n(limit)} lines, split it rather than listing the new path.`;
  }
  if (file.reason !== null) {
    const kind = file.reason === "not source" ? "not a script or stylesheet" : `a ${file.reason} file`;
    return `${path} is listed (${where}) but is not a file this check counts (it is ${kind}). Delete its line.`;
  }
  if (file.lines <= limit) {
    return `${path} now has ${n(file.lines)} lines, within the limit of ${n(limit)}, so it leaves the list. Delete its line (${where}), and leave the blank lines around it in place.`;
  }
  return null;
}

function trackedFiles(base) {
  return execFileSync("git", ["ls-files", "-z"], {
    cwd: base,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
    .split("\0")
    .filter(Boolean);
}

/** Every tracked file under the packages, with why it is left out or its length. */
export function readFiles(base = root, packages = PACKAGES) {
  const tracked = new Set(trackedFiles(base));
  return [...tracked]
    .filter(path => packages.some(pkg => path.startsWith(`${pkg}/`)))
    .filter(path => existsSync(join(base, path)))
    .map(path => {
      let text;
      const read = () => (text ??= readFileSync(join(base, path), "utf8"));
      const reason = leftOut(path, read, candidate => tracked.has(candidate));
      return { path, reason, lines: reason === null ? countLines(read()) : null };
    });
}

/**
 * Problems with entries that widen the list against `baseEntries`, the list
 * at `label`: a path it did not have, or a count higher than it had.
 */
export function wideningProblems(baseEntries, entries, label, list = ALLOWLIST) {
  return [...entries].flatMap(([path, entry]) => {
    const before = baseEntries.get(path);
    if (!before) {
      return [`${path} is in ${list} (line ${entry.at}) but was not at ${label}. The list only shrinks: split the file rather than adding it.`];
    }
    if (entry.lines > before.lines) {
      return [`${path} is allowed ${n(entry.lines)} lines by ${list} (line ${entry.at}), more than the ${n(before.lines)} it was allowed at ${label}. The list only shrinks: put its count back to ${before.lines} and take the file back under it.`];
    }
    return [];
  });
}

const git = (base, args) =>
  execFileSync("git", args, { cwd: base, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

/**
 * The list at the base revision, to compare the list against.
 *
 * @returns {{ label: string, entries?: Map<string, { lines: number, at: number }>, skipped?: string, problem?: string }}
 */
export function baseAllowlist(base, env = process.env) {
  let rev = env.SOURCE_SIZE_BASE;
  const required = Boolean(rev);
  if (!required) {
    try {
      rev = git(base, ["merge-base", "HEAD", "origin/dev"]).trim();
    } catch {
      return { label: "origin/dev", skipped: "no origin/dev to compare the list with, so whether it only shrank was not checked" };
    }
  }
  let commit;
  try {
    commit = git(base, ["rev-parse", "--verify", "--quiet", `${rev}^{commit}`]).trim();
  } catch {
    return { label: rev, problem: `SOURCE_SIZE_BASE names ${rev}, which this checkout does not have, so whether ${ALLOWLIST} only shrank could not be checked. Fetch that commit, or unset SOURCE_SIZE_BASE.` };
  }
  const label = required ? `${rev} (${commit.slice(0, 10)})` : `origin/dev at ${commit.slice(0, 10)} (where HEAD left it)`;
  if (git(base, ["ls-tree", "--name-only", commit, "--", ALLOWLIST]).trim() === "") {
    return { label, skipped: `${label} has no ${ALLOWLIST}, so there is nothing to compare` };
  }
  return { label, entries: parseAllowlist(git(base, ["show", `${commit}:${ALLOWLIST}`])).entries };
}

/** What the run says about the base comparison when it raised no problem of its own. */
function baseNote(before, widened) {
  if (before.skipped) return [`Not compared with a base: ${before.skipped}.`];
  if (before.problem || widened.length > 0) return [];
  return [`The list has not grown since ${before.label}.`];
}

/** Checks a checkout and returns the exit code: 0 when every counted file fits, 1 when one does not. */
export function main(base = root, env = process.env) {
  const listPath = join(base, ALLOWLIST);
  const { entries, errors } = parseAllowlist(
    existsSync(listPath) ? readFileSync(listPath, "utf8") : ""
  );
  const files = readFiles(base);
  const result = judge(files, entries);
  const before = baseAllowlist(base, env);
  const widened = before.entries ? wideningProblems(before.entries, entries, before.label) : [];
  const problems = [...errors, ...(before.problem ? [before.problem] : []), ...widened, ...result.problems];
  const left = Object.entries(result.leftOut)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([reason, count]) => `${reason} ${n(count)}`)
    .join(", ");
  const generated = files.filter(file => file.reason === "generated").map(file => file.path);
  const notes = [
    ...baseNote(before, widened),
    ...(generated.length > 0 ? [`Left out as generated: ${generated.join(", ")}.`] : []),
    ...result.lowerable,
  ];

  if (problems.length > 0) {
    console.error(
      `source-size: FAILED, ${problems.length} problem(s). Page Builder source files may have at most ${n(LIMIT)} lines:`
    );
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error(
      `Read ${n(result.counted)} source file(s) in ${PACKAGES.length} packages; left out: ${left || "none"}. The rules are at the top of scripts/check-source-size.mjs.`
    );
    for (const note of notes) console.error(`  ${note}`);
    return 1;
  }
  console.log(
    `source-size: OK, read ${n(result.counted)} source file(s) in ${PACKAGES.length} Page Builder packages: all are within ${n(LIMIT)} lines except the ${result.listed} listed in ${ALLOWLIST}, and none of those has grown. Left out: ${left || "none"}.`
  );
  for (const note of notes) console.log(`  ${note}`);
  return 0;
}

if (isCliEntry(import.meta.url)) {
  let values;
  try {
    ({ values } = parseArgs({ options: { root: { type: "string" } } }));
  } catch (error) {
    // parseArgs refuses `--root` without a value, and any other option.
    console.error(`${error.message}\nusage: node scripts/check-source-size.mjs [--root <dir>]`);
    process.exit(64);
  }
  process.exit(main(values.root === undefined ? root : resolve(values.root)));
}
