#!/usr/bin/env node
/**
 * Keeps the Page Builder's source files at 1,500 lines or fewer, so a
 * contributor can find things in them and a review of a change stays readable.
 * Every counted file is held to the limit: there is no list of exceptions, and
 * nothing outside the files themselves changes the verdict.
 *
 * What it counts: every file git tracks under the four Page Builder packages
 * whose extension is a script or a stylesheet (see `SOURCE`), less what a
 * person does not write and split by hand. That is decided by the rules in
 * `leftOut`, and only by them, so a file left out is always one of these:
 *
 * - a test: a `.test.` or `.spec.` file (with `.test-d.` type tests), or
 *   anything under a `__tests__` folder;
 * - a fixture: a `.fixture.` or `.fixtures.` file, or anything under a
 *   `fixtures` or `__fixtures__` folder;
 * - a migration: anything in the plugin's migrations folder (`MIGRATIONS`).
 *   A migration module is sealed by its checksum once it has run, so it is
 *   never split;
 * - generated: a file whose opening comment starts with `Generated by`
 *   followed by the path of its generator, a file git tracks in the same
 *   package or from the repository's root (`// GENERATED by
 *   scripts/update-lucide.mjs.`). Naming a generator that is not there, or
 *   none, does not leave a file out. The run names each generated file it
 *   left out, so a new one is seen in review.
 *
 * It fails on:
 * - a counted file over the limit, which is split into parts of the limit or
 *   fewer, with the original kept as the entry that imports or re-exports
 *   them;
 * - a package with no counted source file, which means the check was looking
 *   in the wrong place rather than that everything fits.
 *
 * A tracked file that is gone from the working tree, mid-way through a local
 * move or split, is treated as gone: it is not read, and so not counted.
 *
 * `pnpm lint` runs it after the oxlint passes (scripts/lint.mjs).
 *
 *   node scripts/check-source-size.mjs [--root <dir>]
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

import { isCliEntry } from "./cli-entry.mjs";

/** The most lines a counted file may have. */
export const LIMIT = 1500;

/** The Page Builder's packages, the only places the check reads. */
export const PACKAGES = [
  "packages/blocks-engine",
  "packages/blocks-react",
  "packages/builder",
  "packages/plugin-page-builder",
];

/** Script and stylesheet sources, by extension. */
export const SOURCE = /\.(?:[cm]?[jt]sx?|css)$/;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TEST_FILE = /\.(?:test|spec)(?:-d)?\.[^./]+$/;
const FIXTURE_FILE = /\.fixtures?\.[^./]+$/;
const TEST_FOLDERS = new Set(["__tests__"]);
const FIXTURE_FOLDERS = new Set(["fixtures", "__fixtures__"]);

/** The plugin's migration modules, written by `nextly migrate:create --plugin`. */
export const MIGRATIONS = "packages/plugin-page-builder/src/schema/migrations/";

/** How many of a file's first lines are read to find its opening comment's first words. */
const HEADER_LINES = 5;

/**
 * The generator a file's opening comment names, or null when it names none:
 * the word after `Generated by` (in any case) when those are the first words
 * of the file past the comment markers, with quotes and closing punctuation
 * taken off. Words later in the comment, or a comment after code, do not count.
 */
export function generatorOf(text) {
  for (const raw of text.split("\n", HEADER_LINES)) {
    const line = raw.trim();
    if (!/^(?:\/\/|\/\*|\*)/.test(line)) return null;
    const words = line.replace(/^(?:\/\/+|\/\*+|\*+)\s*/, "");
    if (words === "") continue;
    const match = /^generated by\s+(\S+)/i.exec(words);
    return match ? match[1].replace(/^[`'"]+|[`'".,;:)]+$/g, "") : null;
  }
  return null;
}

/** The package of `path` among `PACKAGES`, or null outside them. */
export function packageOf(path) {
  return PACKAGES.find(pkg => path.startsWith(`${pkg}/`)) ?? null;
}

/**
 * Why a tracked file is not counted, or null when it is. `read` returns the
 * file's text, and is only called for a file the path alone does not decide;
 * `tracked` says whether git tracks a path, to find a named generator.
 *
 * @returns {"not source" | "test" | "fixture" | "migration" | "generated" | null}
 */
export function leftOut(path, read, tracked = () => false) {
  if (!SOURCE.test(path)) return "not source";
  const folders = posix.dirname(path).split("/");
  const name = posix.basename(path);
  if (TEST_FILE.test(name) || folders.some(f => TEST_FOLDERS.has(f))) {
    return "test";
  }
  if (FIXTURE_FILE.test(name) || folders.some(f => FIXTURE_FOLDERS.has(f))) {
    return "fixture";
  }
  if (path.startsWith(MIGRATIONS)) return "migration";
  const generator = generatorOf(read());
  if (generator !== null) {
    const pkg = packageOf(path);
    const candidates = [generator, ...(pkg ? [`${pkg}/${generator}`] : [])];
    if (candidates.some(candidate => tracked(posix.normalize(candidate)))) {
      return "generated";
    }
  }
  return null;
}

/** The lines a text has, as an editor numbers them: a final newline ends the last line rather than starting another. */
export function countLines(text) {
  if (text === "") return 0;
  const breaks = text.split("\n").length - 1;
  return text.endsWith("\n") ? breaks : breaks + 1;
}

const n = value => value.toLocaleString("en-US");

/**
 * Judges the tracked files against the limit.
 *
 * @param {{ path: string, lines: number | null, reason: string | null }[]} files
 *   every tracked file under the packages: `reason` is why it is left out
 *   (null when counted), and `lines` its length when counted.
 * @returns {{ problems: string[], counted: number, leftOut: Record<string, number> }}
 */
export function judge(files, { limit = LIMIT, packages = PACKAGES } = {}) {
  const countedFiles = files.filter(file => file.reason === null);
  const tally = {};
  for (const file of files) {
    if (file.reason !== null) tally[file.reason] = (tally[file.reason] ?? 0) + 1;
  }
  const problems = [
    ...packages.filter(pkg => !countedFiles.some(file => file.path.startsWith(`${pkg}/`))).map(
      pkg => `${pkg} has no source file this check counts, so nothing in it was checked. If the package moved or was renamed, update PACKAGES in scripts/check-source-size.mjs.`
    ),
    ...countedFiles
      .filter(file => file.lines > limit)
      .map(
        file => `${file.path} has ${n(file.lines)} lines, over the limit of ${n(limit)}. Split it into files of ${n(limit)} lines or fewer, each holding one area of what it does; keep this file as the entry that imports or re-exports the parts, so nothing that uses it has to change.`
      ),
  ];
  return { problems, counted: countedFiles.length, leftOut: tally };
}

function trackedFiles(base) {
  return execFileSync("git", ["ls-files", "-z"], {
    cwd: base,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
    .split("\0")
    .filter(Boolean);
}

/** Every tracked file under the packages, with why it is left out or its length. */
export function readFiles(base = root, packages = PACKAGES) {
  const tracked = new Set(trackedFiles(base));
  return [...tracked]
    .filter(path => packages.some(pkg => path.startsWith(`${pkg}/`)))
    .filter(path => existsSync(join(base, path)))
    .map(path => {
      let text;
      const read = () => (text ??= readFileSync(join(base, path), "utf8"));
      const reason = leftOut(path, read, candidate => tracked.has(candidate));
      return { path, reason, lines: reason === null ? countLines(read()) : null };
    });
}

/** Checks a checkout and returns the exit code: 0 when every counted file fits, 1 when one does not. */
export function main(base = root) {
  const files = readFiles(base);
  const result = judge(files);
  const left = Object.entries(result.leftOut)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([reason, count]) => `${reason} ${n(count)}`)
    .join(", ");
  const generated = files.filter(file => file.reason === "generated").map(file => file.path);
  const notes = generated.length > 0 ? [`Left out as generated: ${generated.join(", ")}.`] : [];

  if (result.problems.length > 0) {
    console.error(
      `source-size: FAILED, ${result.problems.length} problem(s). Page Builder source files may have at most ${n(LIMIT)} lines:`
    );
    for (const problem of result.problems) console.error(`  - ${problem}`);
    console.error(
      `Read ${n(result.counted)} source file(s) in ${PACKAGES.length} packages; left out: ${left || "none"}. The rules are at the top of scripts/check-source-size.mjs.`
    );
    for (const note of notes) console.error(`  ${note}`);
    return 1;
  }
  console.log(
    `source-size: OK, read ${n(result.counted)} source file(s) in ${PACKAGES.length} Page Builder packages: all are within ${n(LIMIT)} lines. Left out: ${left || "none"}.`
  );
  for (const note of notes) console.log(`  ${note}`);
  return 0;
}

if (isCliEntry(import.meta.url)) {
  let values;
  try {
    ({ values } = parseArgs({ options: { root: { type: "string" } } }));
  } catch (error) {
    // parseArgs refuses `--root` without a value, and any other option.
    console.error(`${error.message}\nusage: node scripts/check-source-size.mjs [--root <dir>]`);
    process.exit(64);
  }
  process.exit(main(values.root === undefined ? root : resolve(values.root)));
}
