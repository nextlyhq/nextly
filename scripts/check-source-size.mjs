#!/usr/bin/env node
/**
 * Keeps the Page Builder's source files at 1,500 lines or fewer, so a
 * contributor can find things in them and a review of a change stays readable.
 *
 * What it counts: every file git tracks under the four Page Builder packages
 * whose extension is a script or a stylesheet (see `SOURCE`), less what a
 * person does not write and split by hand. That is decided by the rules in
 * `leftOut`, and only by them, so an exemption is always one of these:
 *
 * - a test: a `.test.` or `.spec.` file (with `.test-d.` type tests), or
 *   anything under a `__tests__` folder;
 * - a fixture: a `.fixture.` or `.fixtures.` file, or anything under a
 *   `fixtures` or `__fixtures__` folder;
 * - a migration: anything under a `migrations` folder. A migration module is
 *   sealed by its checksum once it has run, so it is never split;
 * - generated: a file whose opening comment starts with `Generated by` (in
 *   any case), which is how the repository's generators head what they write.
 *
 * The files that were over the limit when the check landed are listed in
 * `scripts/source-size-allowlist.txt` with their size on that day. A listed
 * file may shrink but not grow, and its line comes out once it fits. The list
 * only ever shrinks: a new file over the limit is split, never added.
 *
 * It fails on:
 * - a counted file over the limit that is not listed;
 * - a listed file that has grown past its recorded size;
 * - a listed file that now fits, or that no longer exists, or that the
 *   check does not count (so its line is dead weight);
 * - a line of the list it cannot read, or a path listed twice;
 * - a package that yields no files at all, which means the check was looking
 *   in the wrong place rather than that everything fits.
 *
 * A listed file that shrank passes, and the run prints the lower size its line
 * can be brought down to.
 *
 * `pnpm lint` runs it after the oxlint passes (scripts/lint.mjs).
 *
 *   node scripts/check-source-size.mjs [--root <dir>]
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { isCliEntry } from "./cli-entry.mjs";

/** The most lines a counted file may have. */
export const LIMIT = 1500;

/** The Page Builder's packages, the only places the check reads. */
export const PACKAGES = [
  "packages/blocks-engine",
  "packages/blocks-react",
  "packages/builder",
  "packages/plugin-page-builder",
];

/** Script and stylesheet sources, by extension. */
export const SOURCE = /\.(?:[cm]?[jt]sx?|css)$/;

/** The list of files allowed past the limit until they are split. */
export const ALLOWLIST = "scripts/source-size-allowlist.txt";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TEST_FILE = /\.(?:test|spec)(?:-d)?\.[^./]+$/;
const FIXTURE_FILE = /\.fixtures?\.[^./]+$/;
const TEST_FOLDERS = new Set(["__tests__"]);
const FIXTURE_FOLDERS = new Set(["fixtures", "__fixtures__"]);
const MIGRATION_FOLDERS = new Set(["migrations"]);

/** How many of a file's first lines are read to find its opening comment's first words. */
const HEADER_LINES = 5;

/**
 * Whether the file's opening comment starts with `Generated by`: the first
 * words of the file, past the comment markers, as the repository's generators
 * write them (`// GENERATED by ...`, or `Generated by ...` opening a block).
 * Words later in the comment, or a comment after code, do not count.
 */
export function isGenerated(text) {
  for (const raw of text.split("\n", HEADER_LINES)) {
    const line = raw.trim();
    if (!/^(?:\/\/|\/\*|\*)/.test(line)) return false;
    const words = line.replace(/^(?:\/\/+|\/\*+|\*+)\s*/, "");
    if (words !== "") return /^generated by\b/i.test(words);
  }
  return false;
}

/**
 * Why a tracked file is not counted, or null when it is. `read` returns the
 * file's text, and is only called for a file the path alone does not decide.
 *
 * @returns {"not source" | "test" | "fixture" | "migration" | "generated" | null}
 */
export function leftOut(path, read) {
  if (!SOURCE.test(path)) return "not source";
  const folders = posix.dirname(path).split("/");
  const name = posix.basename(path);
  if (TEST_FILE.test(name) || folders.some(f => TEST_FOLDERS.has(f))) {
    return "test";
  }
  if (FIXTURE_FILE.test(name) || folders.some(f => FIXTURE_FOLDERS.has(f))) {
    return "fixture";
  }
  if (folders.some(f => MIGRATION_FOLDERS.has(f))) return "migration";
  if (isGenerated(read())) return "generated";
  return null;
}

/** The lines a text has, as an editor numbers them: a final newline ends the last line rather than starting another. */
export function countLines(text) {
  if (text === "") return 0;
  const breaks = text.split("\n").length - 1;
  return text.endsWith("\n") ? breaks : breaks + 1;
}

/**
 * The allowlist's entries, and the lines it could not read. An entry is a
 * path and a line count, separated by spaces; blank lines and lines starting
 * with `#` are skipped.
 *
 * @returns {{ entries: Map<string, { lines: number, at: number }>, errors: string[] }}
 */
export function parseAllowlist(text, name = ALLOWLIST) {
  const entries = new Map();
  const errors = [];
  text.split("\n").forEach((raw, index) => {
    const at = index + 1;
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) return;
    const match = /^(\S+)\s+(\d+)$/.exec(line);
    if (!match) {
      errors.push(
        `${name}:${at} reads "${line}", which is not a path followed by its line count, such as "packages/builder/src/canvas.tsx 2705".`
      );
      return;
    }
    const [, path, lines] = match;
    if (entries.has(path)) {
      errors.push(
        `${name}:${at} lists ${path} again (first on line ${entries.get(path).at}). Keep one line for it.`
      );
      return;
    }
    entries.set(path, { lines: Number(lines), at });
  });
  return { entries, errors };
}

const n = value => value.toLocaleString("en-US");

/**
 * Judges the tracked files against the limit and the allowlist.
 *
 * @param {{ path: string, lines: number | null, reason: string | null }[]} files
 *   every tracked file under the packages: `reason` is why it is left out
 *   (null when counted), and `lines` its length when counted.
 * @param {Map<string, { lines: number, at: number }>} entries the allowlist.
 * @returns {{ problems: string[], lowerable: string[], counted: number, listed: number, leftOut: Record<string, number> }}
 */
export function judge(files, entries, { limit = LIMIT, packages = PACKAGES, list = ALLOWLIST } = {}) {
  const problems = [];
  const lowerable = [];
  const byPath = new Map(files.map(file => [file.path, file]));
  const tally = {};

  for (const pkg of packages) {
    if (!files.some(file => file.path.startsWith(`${pkg}/`))) {
      problems.push(
        `${pkg} has no tracked files, so nothing in it was checked. If the package moved or was renamed, update PACKAGES in scripts/check-source-size.mjs.`
      );
    }
  }

  for (const file of files) {
    if (file.reason !== null) {
      tally[file.reason] = (tally[file.reason] ?? 0) + 1;
      continue;
    }
    const entry = entries.get(file.path);
    if (file.lines <= limit) continue;
    if (!entry) {
      problems.push(
        `${file.path} has ${n(file.lines)} lines, over the limit of ${n(limit)}. Split it into files of ${n(limit)} lines or fewer, each holding one area of what it does; keep this file as the entry that re-exports what moved, so imports keep working. Do not add it to ${list}: that list only shrinks.`
      );
    } else if (file.lines > entry.lines) {
      problems.push(
        `${file.path} has ${n(file.lines)} lines, ${n(file.lines - entry.lines)} more than the ${n(entry.lines)} ${list} allows it until it is split. A listed file may shrink but not grow: put the new code in a new file beside it, or take out as many lines as you added.`
      );
    } else if (file.lines < entry.lines) {
      lowerable.push(
        `${file.path} is down to ${n(file.lines)} lines; its line in ${list} (line ${entry.at}) can be lowered from ${entry.lines} to ${file.lines}.`
      );
    }
  }

  for (const [path, entry] of entries) {
    const file = byPath.get(path);
    const where = `${list} line ${entry.at}`;
    if (!file) {
      problems.push(
        `${path} is listed (${where}) but git does not track it. If it was split or deleted, delete its line; if it moved and is still over ${n(limit)} lines, split it rather than listing the new path.`
      );
    } else if (file.reason !== null) {
      problems.push(
        `${path} is listed (${where}) but is not a file this check counts (it is ${file.reason === "not source" ? "not a script or stylesheet" : `a ${file.reason} file`}). Delete its line.`
      );
    } else if (file.lines <= limit) {
      problems.push(
        `${path} now has ${n(file.lines)} lines, within the limit of ${n(limit)}, so it leaves the list. Delete its line (${where}), and leave the blank lines around it in place.`
      );
    }
  }

  const counted = files.filter(file => file.reason === null).length;
  return { problems, lowerable, counted, listed: entries.size, leftOut: tally };
}

function trackedFiles(base, packages) {
  return execFileSync("git", ["ls-files", "-z", "--", ...packages], {
    cwd: base,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
    .split("\0")
    .filter(Boolean);
}

/** Every tracked file under the packages, with why it is left out or its length. */
export function readFiles(base = root, packages = PACKAGES) {
  return trackedFiles(base, packages).map(path => {
    let text;
    const read = () => (text ??= readFileSync(join(base, path), "utf8"));
    const reason = leftOut(path, read);
    return { path, reason, lines: reason === null ? countLines(read()) : null };
  });
}

/** Checks a checkout and returns the exit code: 0 when every counted file fits, 1 when one does not. */
export function main(base = root) {
  const listPath = join(base, ALLOWLIST);
  const { entries, errors } = parseAllowlist(
    existsSync(listPath) ? readFileSync(listPath, "utf8") : ""
  );
  const result = judge(readFiles(base), entries);
  const problems = [...errors, ...result.problems];
  const left = Object.entries(result.leftOut)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([reason, count]) => `${reason} ${n(count)}`)
    .join(", ");

  if (problems.length > 0) {
    console.error(
      `source-size: FAILED, ${problems.length} problem(s). Page Builder source files may have at most ${n(LIMIT)} lines:`
    );
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error(
      `Read ${n(result.counted)} source file(s) in ${PACKAGES.length} packages; left out: ${left || "none"}. The rules are at the top of scripts/check-source-size.mjs.`
    );
    return 1;
  }
  console.log(
    `source-size: OK, read ${n(result.counted)} source file(s) in ${PACKAGES.length} Page Builder packages: all are within ${n(LIMIT)} lines except the ${result.listed} listed in ${ALLOWLIST}, and none of those has grown. Left out: ${left || "none"}.`
  );
  for (const note of result.lowerable) console.log(`  ${note}`);
  return 0;
}

if (isCliEntry(import.meta.url)) {
  const at = process.argv.indexOf("--root");
  if (at !== -1 && !process.argv[at + 1]) {
    console.error("usage: node scripts/check-source-size.mjs [--root <dir>]");
    process.exit(64);
  }
  process.exit(main(at === -1 ? root : resolve(process.argv[at + 1])));
}
