/**
 * Regenerates the WCAG contrast report the theme switcher's badge reads.
 *
 * Runs `validateTheme` over every theme this build knows about -- Nextly
 * originals and tweakcn presets alike -- and writes a flat
 * `Record<string, number>` of measured failure counts keyed by theme id.
 * The switcher can then look a theme's score up with no special-casing for
 * where it came from.
 *
 * This deliberately does not read `EXPECTED_CONTRAST_FAILURES`: that record
 * only covers the Nextly set and exists to let three specific themes miss
 * WCAG AA on purpose without failing the test suite. The badge instead
 * measures everything fresh, so a tweakcn preset shows its real number
 * rather than silently defaulting to "pass". As a sanity check, the Nextly
 * subset of what gets measured here is compared against that expectation
 * record before writing anything -- a mismatch means the contrast harness
 * or a theme's tokens drifted, and is reported rather than papered over.
 *
 * Run: node --experimental-strip-types scripts/generate-contrast-report.mjs
 */
import { register } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";

import { contrastSourceStamp } from "./contrast-source-stamp.mjs";

// Registered before the theme-lab modules are imported below, so their own
// extensionless internal imports resolve. See ts-extension-loader.mjs.
register("./ts-extension-loader.mjs", import.meta.url);

const here = dirname(fileURLToPath(import.meta.url));

const { NEXTLY_THEMES, TWEAKCN_THEMES, EXPECTED_CONTRAST_FAILURES } =
  await import("../src/theme-lab/themes/index.ts");
const { validateTheme } = await import("../src/theme-lab/validate-contrast.ts");

// The `--color-*` scale referenced by the pairings is theme-independent and
// lives in the shipped stylesheet, not in any one theme's tokens.
const themeCssPath = resolvePath(
  here,
  "../../../packages/ui/src/styles/theme.css"
);
const themeCss = readFileSync(themeCssPath, "utf8");

const ALL_THEMES = [...NEXTLY_THEMES, ...TWEAKCN_THEMES];

/** @type {Record<string, number>} */
const report = {};
for (const theme of ALL_THEMES) {
  report[theme.id] = validateTheme(theme, themeCss).length;
}

// The Nextly set has recorded expectations -- all four at 0 since Calm's
// rehabilitation. Measuring them here must reproduce those numbers exactly:
// this is what proves the two harnesses agree rather than one silently
// drifting from the other.
const mismatches = [];
for (const theme of NEXTLY_THEMES) {
  const expected = EXPECTED_CONTRAST_FAILURES[theme.id] ?? 0;
  const measured = report[theme.id];
  if (measured !== expected) {
    mismatches.push(`${theme.id}: expected ${expected}, measured ${measured}`);
  }
}
if (mismatches.length > 0) {
  console.error(
    "generate-contrast-report: measured counts disagree with EXPECTED_CONTRAST_FAILURES:\n" +
      mismatches.join("\n")
  );
  process.exit(1);
}

const outPath = resolvePath(here, "../src/theme-lab/contrast-report.generated.ts");

// Which contrast harness these numbers were measured against. See
// `contrast-source-stamp.mjs` for why this hashes contents rather than naming
// a commit.
const contrastSourceRev = contrastSourceStamp(resolvePath(here, "../../.."));

const banner = `/**
 * Measured WCAG AA failure counts for every theme lab theme, keyed by id.
 *
 * Generated by scripts/generate-contrast-report.mjs -- do not edit by hand.
 * Covers Nextly originals and tweakcn presets alike: unlike
 * EXPECTED_CONTRAST_FAILURES (themes/index.ts), which records only the themes
 * that miss WCAG AA on purpose, this measures all of them, so a tweakcn
 * preset shows its real score instead of defaulting to "pass".
 *
 * Measured against contrast source \`${contrastSourceRev}\`
 * (packages/ui/src/styles/contrast). These counts are only comparable with
 * others taken against the SAME revision -- the harness deciding them is as
 * much an input as the theme is.
 */
export const CONTRAST_REPORT: Record<string, number> = `;

const body = JSON.stringify(report, Object.keys(report).sort(), 2);
writeFileSync(outPath, `${banner}${body};\n`);

console.log(
  `generate-contrast-report: wrote ${ALL_THEMES.length} theme scores to ${outPath}`
);
